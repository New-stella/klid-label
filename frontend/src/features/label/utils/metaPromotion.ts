// 자동 계산값이 <b>사람의 판정으로 승격되는 것</b>을 막는 판정의 단일 지점.
//
// 메타 축(촬영환경·개인정보 판정·프레임 설명 등)의 유효값은 «수동 저장값이 있으면 그 값, 없으면
// 자동으로 계산한 값»이다. 화면이 그 자동 계산값을 그대로 되돌려 보내면 서버는 받은 값만으로
// 「사용자가 고른 것」과 「자동 계산값이 되돌아온 것」을 구분하지 못해, 추정값이 사람의 판정으로
// 굳는다.
//
// <h3>왜 함수 하나로 모았나</h3>
// 이 규율은 원래 내부 라벨링 화면의 촬영환경 패널과 영상축 개인정보 패널에 <b>각각</b> 있었고
// (두 파일이 서로 「같은 규율」임을 주석으로 밝히고 있었다), 프레임축 개인정보 패널에 세 번째
// 사본이 있었다. 포털 채널이 같은 규율을 필요로 하면서 <b>네 번째 사본</b>이 될 참이라 판정만
// 여기로 모았다. 사본이 늘면 한쪽만 고쳐도 화면은 그럴듯하게 보인다 — 이 저장소의 반복 결함이다.
//
// <h3>★이것이 유일한 방어가 아니다 — 그렇다고 「지키면 좋은 것」이 아니다</h3>
// 서버도 같은 것을 <b>독립으로</b> 막는다(받은 값이 원본의 현재 유효값과 같으면 아무것도 쌓지
// 않고, 이미 쌓여 있으면 지운다). 그래서 화면이 이 계약을 어겨도 저장소가 오염되지는 않는다.
// 그럼에도 화면이 지키는 이유는 ①서버 방어가 성립하는 축이 저장소 형태에 달려 있어 모든 창구가
// 같지 않고(원장에 직접 쓰는 창구는 「행이 없다」가 「수동값을 지운다」는 다른 뜻이라 같은 방어를
// 쓸 수 없다) ②보내지 않으면 애초에 판정할 것이 없기 때문이다.

// @design API-235 @design AC-1068

/**
 * 값의 <b>원본 쪽</b> 출처.
 *
 * - `MANUAL` — 원본에서 사람이 직접 고른 값
 * - `DERIVED` — 원본에 저장값이 없어 자동으로 계산한 값
 * - `STORED` — 출처 구분이 없는 축의 저장값(시계열 메타 등)
 * - `NONE` — 원본에 값 자체가 없다
 * - `null`/`undefined` — 창구가 출처를 내려주지 않는다(구 응답·미제공 축)
 *
 * ⚠ 이것은 「내 값이 원본을 덮었는가」와 <b>다른 축</b>이다. 둘을 합치면
 * 「자동으로 채워져 있던 값을 사람이 바꿨다」를 표현하지 못한다.
 */
export type MetaValueSource = 'MANUAL' | 'DERIVED' | 'STORED' | 'NONE' | null | undefined;

/**
 * 이 값을 저장 요청에 실어야 하는가.
 *
 * <p>사용자가 값을 바꿨거나(현재값 ≠ 원본값) 원본이 <b>이미 사람이 고른 값</b>이면 싣고, 손대지
 * 않은 자동 계산값은 싣지 않는다.
 *
 * <p>출처를 내려주지 않는 창구(`null`)에서는 «손댔는가» 한 축으로만 판정한다 — 그래도 자동
 * 계산값의 승격은 막힌다(손대지 않으면 보내지 않으므로). 다만 원본이 수동값이었다는 사실을
 * 알 수 없어, 전체 교체 계약의 창구에서는 손대지 않은 수동값이 비워질 수 있다(그 창구의 알려진
 * 한계이며 이 함수가 만들어낸 것이 아니다).
 *
 * @param current  화면의 현재 값
 * @param original 화면이 받아 그린 원본 값(같은 자료형으로 정규화해 넘긴다)
 * @param source   원본 쪽 값의 출처
 */
export function isUserDeterminedMetaValue<T>(
  current: T,
  original: T,
  source: MetaValueSource,
): boolean {
  return current !== original || source === 'MANUAL';
}
