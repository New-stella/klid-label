/**
 * 포털 라벨링 화면 — **포털의 라벨링 화면은 이것 하나뿐이다.**
 *
 * 대상은 두 출처다. 데이터마트에서 불러온 영상의 프레임과, 본인이 올린 영상에서 추출된
 * 프레임이다. 예전에는 출처마다 **본문이 두 벌**이었고 업로드 갈래만 별도의 미니멀 화면을
 * 그리고 있었다 — 같은 작업을 두 자리에서 배워야 했고, 도구바·객체 패널·필름스트립·단축키가
 * 그쪽에만 없었다. 이제 두 출처가 **같은 라벨링 도구**를 쓰고 갈리는 것은 창구뿐이다.
 *
 * <h3>이 파일이 하는 일</h3>
 * 주소가 말하는 자산 출처를 읽어 라벨링 화면에 넘긴다. 판정은 이 파일이 하지 않고
 * `@/features/portal/labelingEntry` 에 위임한다 — 목록의 진입 주소를 만드는 쪽과 **같은
 * 함수**를 써야 「목록은 업로드로 보내는데 화면은 데이터마트로 읽는」 어긋남이 안 생긴다.
 *
 * ★**출처는 화면이 아니라 데이터 계층으로 내려간다.** 이 파일이 고르는 것은 본문이 아니라
 *   조회·이미지·저장 창구다. 본문을 갈래마다 두면 다음 변경 때마다 한쪽만 갱신된다.
 *
 * ⚠ **출처를 주소에 적는 것은 창구가 아직 하나가 아니기 때문이다.** 두 출처의 프레임 라벨이
 *   같은 창구로 오가면 표기 없이 `:id` 하나로 열리며, 그때 이 분기는 사라진다. 지금 표기가 없는
 *   주소는 데이터마트로 읽는다(fail-closed — 지금까지의 동작).
 *
 * ⚠ **이 화면은 이동 탭에 뜨지 않는다.** 목적지가 아니라 목록에서 행을 눌러 들어가는 몰입 편집
 *   화면이다. 노출 판정은 포털 내비게이션 선언의 허용 목록이 하므로 **그 목록에 넣지 않는 것**
 *   으로 지켜진다(여기에 «숨김» 을 따로 적지 않는다 — 두 번째 목록이 된다).
 *
 * ⚠ 라벨 내보내기·원본 파일 내려받기는 이 화면에 두지 않는다 — 자산 단위 조작이라 자산 목록
 *   화면의 행 액션이 갖는다(확정 사양).
 *
 * ⚠ **포털 모습은 이 화면의 「본문 안쪽」까지만 닿았다 (2026-09-16).** 포털 부품으로 바꾼 것은 이
 *   화면이 소유한 자리, 즉 옆 칸 '메타' 탭 본문(`features/portal/work/components/*`)뿐이다.
 *   시안이 말하는 **편집기 뼈대**(머리 줄·도구 줄·도구 칸·캔버스·프레임 줄, 그리고 화면 전체를
 *   덮는 안내 넷 — 잘못된 프레임 · 업로드 자산 상태 · 불러오는 중 · 들어갈 수 없음)는 전부
 *   관제 라벨링 화면이 그리고, 그 화면은 이 채널이 고치지 않는다.
 *
 * ⚠ 그래서 **여기에 포털 판(`klid-authoring-edit`)을 씌워도 소용이 없다** — 관제 본체가 화면을
 *   통째로 덮는 고정 판으로 서서 바깥 판이 보이지 않는다. 씌우는 대신 **적지 않았다.**
 *   포털 시안대로 서려면 그 뼈대를 포털 부품으로 바꾸는 별도 라운드가 필요하다.
 *
 * @design SCREEN-029
 * @design NAV-002
 */

import { useSearchParams } from 'react-router-dom';

import { resolvePortalLabelSource } from '@/features/portal/labelingEntry';
import { LabelingPage } from '@/pages/label/LabelingPage';

export function PortalLabelingPage() {
  const [searchParams] = useSearchParams();
  const source = resolvePortalLabelSource(searchParams);

  // 라벨링 코어가 채널(PORTAL)로 스스로 분기하고, 출처는 조회·이미지·저장 창구만 가른다.
  return <LabelingPage source={source} />;
}
