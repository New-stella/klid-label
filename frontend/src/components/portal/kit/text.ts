/**
 * 글줄 — **뜻이 갈리는 자리에서 접히지 않게 한다** (UX-writing.md §6 「줄바꿈」).
 *
 * 브라우저는 들어가는 데까지 채우고 아무 어절 뒤에서나 접는다. 그래서 「확인할 수 /
 * 있습니다」 「확인한 / 뒤」 「보유한 이미지· / 영상을」 「이미지 / 1장으로」처럼
 * 한 덩어리인 말이 갈린다.
 *
 * 손질은 두 층이다.
 *
 * ① `glue()` — **부품이 스스로 건다.** 어느 화면에서든 늘 붙어야 하는 자리(의존명사 ·
 *    보조용언 · 가운뎃점 나열 · 수량)를 규칙으로 붙인다. 화면은 글만 꽂으면 된다.
 * ② `phrase()` — **문장 쓰는 쪽이 접을 자리를 고른다.** `|` 로 표시한 자리 사이만
 *    접히므로, 긴 문장을 뜻 단위로 끊고 싶을 때 쓴다.
 *
 * 두 층 다 **접히는 자리를 고르는 일만** 한다. 그중 어디서 접을지는 `text-wrap: balance`
 * 가 줄 길이를 고르게 맞춰 정하므로, 폭이 바뀌어도 어긋나지 않는다 (손으로 넣는
 * 줄바꿈 `<br>`·`\n` 을 대신한다 — UX-writing.md §6).
 */

/**
 * 앞말과 붙어야 읽히는 뒷말 (의존명사·단위성 의존명사).
 * **어절 전체가 이것과 같을 때만** 붙인다 — 「수집합니다」 「등록된」 처럼 같은 글자로
 * 시작하는 보통 낱말까지 붙이면 엉뚱한 자리가 묶인다.
 */
const BOUND = new Set([
  '수', '수가', '수는', '수도', '수를',
  '것', '것이', '것을', '것은', '것도', '것과', '것이다',
  '때', '때가', '때는', '때에', '때도', '때까지', '때부터',
  '뒤', '뒤에', '뒤로', '뒤에는',
  '후', '후에', '후로', '후에는',
  '중', '중에', '중인', '중이다', '중입니다', '중이며',
  '채', '채로',
  '만큼', '만큼은', '만큼만',
  '대로', '대로만',
  '뿐', '뿐이다', '뿐입니다', '뿐이며', '뿐만',
  '줄', '줄은', '줄로',
  '등', '등의', '등을', '등이', '등은', '등과', '등에서', '등으로',
  '바', '바가', '바를', '바는',
  '데', '데에', '데는', '데가',
])

/**
 * **뒷말과 붙어야 읽히는 앞말** (관형사·수관형사). 뒤에 오는 체언을 꾸미므로 갈라지면
 * 「다른 / 키워드로」 「새 / 모델이」 처럼 꾸미는 말만 줄 끝에 남는다.
 * 여기서도 **어절 전체가 같을 때만** 붙인다.
 */
const DET = new Set([
  '이', '그', '저', '요',
  '이런', '그런', '저런', '어떤', '무슨', '웬',
  '다른', '새', '여러', '온갖', '각', '각각의', '모든', '온',
  '지난', '이번', '다음', '매', '첫',
  '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉', '열', '몇',
])

/** 「~할 수 있습니다」 — `수` 뒤에 이것이 오면 셋을 한 덩어리로 붙인다 */
const AUX_AFTER_SU = new Set([
  '있습니다', '없습니다', '있다', '없다', '있는', '없는', '있을', '없을',
  '있어', '없어', '있고', '없고', '있으며', '없으며', '있어요', '없어요',
  '있지만', '없지만', '있어야', '없어야',
])

const NBSP = '\u00a0'
/** 낱말 붙임표 — 글자는 없고 "여기서 접지 마라" 는 뜻만 있다 */
const JOINER = '\u2060'

/** 어절 끝에 붙은 문장부호를 떼고 본말만 본다 */
const bare = (w: string) => w.replace(/[.,!?)\]}]+$/u, '')

/**
 * 가운뎃점(·) **앞뒤 양쪽**을 붙인다. 브라우저는 가운뎃점을 접을 자리로 보아
 * 「보유한 이미지· / 영상을」(뒤에서) 「지자체 CCTV 재난 / ·안전 영상으로」(앞에서)처럼
 * 양쪽으로 갈랐다. 가운뎃점은 **같은 급을 나열**할 때만 쓰므로(UX-writing.md §4)
 * 나열 전체가 한 덩어리다 — 중간에서 접히면 안 된다.
 */
const tieDots = (text: string) => text.replace(/\u2060?·\u2060?/g, `${JOINER}·${JOINER}`)

/**
 * **늘 붙어야 하는 자리를 붙인다.** 부품(결과 없음 · 다이얼로그 · 모달 · 알림 띠)이
 * 받은 글에 스스로 걸므로 화면은 아무것도 하지 않아도 된다.
 *
 * 붙이는 자리 다섯 —
 *   · 의존명사 : 「확인한 뒤」 「저장한 것」 「유형·지역 등」
 *   · 보조용언 : 「확인할 수 있습니다」 (셋을 한 덩어리로)
 *   · 관형사   : 「다른 키워드」 「새 모델」 「한 번」
 *   · 가운뎃점 : 「이미지·영상」 「침수·화재」
 *   · 수량     : 「이미지 1장」 「5개까지」
 *
 * 이미 `phrase()` 를 거친 글에 다시 걸어도 안전하다 (묶인 자리는 보통 공백이 아니라
 * 건드리지 않는다).
 */
export function glue(text: string): string {
  const parts = text.split(' ')
  if (parts.length < 2) return tieDots(text)

  const out = [parts[0]]
  for (let i = 1; i < parts.length; i++) {
    const word = parts[i]
    const last = out[out.length - 1]
    // 앞 덩어리의 **마지막 어절**로 판단한다 (이미 NBSP 로 묶여 있을 수 있다)
    const prevWord = bare(last).split(NBSP).pop() ?? ''
    const tie =
      BOUND.has(bare(word)) ||
      /^[0-9]/.test(bare(word)) ||
      DET.has(prevWord) ||
      (prevWord === '수' && AUX_AFTER_SU.has(bare(word)))
    if (tie) out[out.length - 1] = `${last}${NBSP}${word}`
    else out.push(word)
  }
  return tieDots(out.join(' '))
}

/**
 * **접어도 되는 자리를 문장 쪽이 고른다.** `|` 로 나눈 덩어리 안쪽 공백을 NBSP 로 묶어,
 * 덩어리와 덩어리 사이만 접을 자리로 남긴다.
 *
 * ★ 덩어리 하나는 **가장 좁은 칸에 들어갈 만큼** 짧아야 한다. 칸보다 긴 덩어리는 접을
 *   자리가 없어 낱말 가운데서 끊긴다(overflow-wrap: break-word). 대략 2~4 어절이 기준이다.
 *
 * ★ `|` 가 하나도 없으면 문장 전체가 한 덩어리가 된다 — **절대 접히지 않는다.**
 *   이름·상표처럼 갈라지면 안 되는 짧은 말에만 그렇게 쓴다.
 *
 * ```
 * phrase('내부 학습데이터를 불러오거나 | 보유한 이미지·영상을 | 통합 업로드 버튼으로 | 올립니다.')
 * // 넓은 칸 → 내부 학습데이터를 불러오거나 보유한 이미지·영상을
 * //           통합 업로드 버튼으로 올립니다.
 * // 좁은 칸 → 내부 학습데이터를 불러오거나
 * //           보유한 이미지·영상을
 * //           통합 업로드 버튼으로 올립니다.
 * ```
 */
export function phrase(text: string): string {
  return tieDots(
    text
      .split('|')
      .map((chunk) => chunk.trim().replace(/ /g, NBSP))
      .filter(Boolean)
      .join(' '),
  )
}
