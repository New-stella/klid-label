            WHEN (r.orgnl_raw_sn IS NULL) THEN i.psdo_incl_yn
            ELSE NULL::bpchar
        END AS src_psdo_incl_yn,
        CASE
            WHEN (r.orgnl_raw_sn IS NULL) THEN i.prvc_incl_yn
            ELSE NULL::bpchar
        END AS src_prvc_incl_yn,
    to_char(m.rvw_cmpl_dt, 'YYYY'::text) AS data_etbl_yr,
