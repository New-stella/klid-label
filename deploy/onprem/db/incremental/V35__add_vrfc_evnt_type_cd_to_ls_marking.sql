-- =============================================================================
-- V35 — 마킹 원장에 「작업자가 고른 검증 이벤트 유형」 칸 신설
--       @design ERD-013 · SCREEN-006 · API-047 · API-043 · UC-019 · AC-1013
--
--   ls_marking.vrfc_evnt_type_cd  varchar(20) NULL  (검증이벤트유형코드)
--
-- -----------------------------------------------------------------------------
-- * 왜 이 칸이 필요한가 (CO-20260907-VLM연동규격-v120-정합)
-- -----------------------------------------------------------------------------
--   관제가 검증 이벤트 유형을 보내지 않는 영상이 실재한다. 그런 영상은 지금 둘 다 잃는다 —
--     ① 질문 목록이 유형으로 조회되므로 <비어서> 작업자가 질문을 고를 수 없고,
--     ② 묘사 축 위탁도 유형이 없어 사업자가 거부한다.
--   즉 그 영상은 시계열 메타를 <하나도> 받지 못한다.
--
--   → 관제 값이 없을 때 작업자가 마킹 화면에서 유형을 직접 고르면 ①②가 함께 풀린다.
--     고른 유형은 질문 목록을 끌어오고, 묘사 축 위탁의 이벤트 유형 2순위 조달값이 된다.
--     이 칸이 그 선택을 담는다.
--
--   ★ 노출 규칙 — 관제 값이 <없을 때만> 화면이 유형 선택을 띄운다. 있으면 아예 띄우지 않는다.
--     그래서 우선순위 충돌이 구조적으로 발생하지 않는다(둘이 경쟁할 일이 없다).
--     「표시하되 잠근다」안은 검토 후 채택하지 않았다.
--
--   이벤트 유형 조달 순서 = 관제 인입 값 -> 이 칸(작업자 선택) -> null.
--   ⚠ null 폴백을 없애지 않는다 — 「값을 지어내지 않는다」가 확정 정책이고, 사업자 필수 필드라
--     거부가 예상되며 그 거부를 기록한다.
--
--   ⚠ 관제 인입 원장(ls_data_ingest)에 쓰지 않는다 — 그 표는 관제가 직접 INSERT 하는
--     수신 원장이라 불변이다. 우리 선택값은 우리 원장에 둔다.
--
--   ⚠ 선택 사항이다 — 고르지 않아도 마킹은 완료된다. 필수로 만들면 유형 미수신 영상의 마킹이
--     막혀(지금은 진행된다) 하위호환이 깨진다.
--
-- -----------------------------------------------------------------------------
-- * 표준용어·표준도메인 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- -----------------------------------------------------------------------------
--   vrfc_evnt_type_cd  <- 기존 ls_data_ingest.vrfc_evnt_type_cd 와 <물리명·자료형·길이 동일>.
--                         검증 VRFC + 이벤트 EVNT + 유형 TYPE + 코드 CD.
--                         코드값 표준도메인 varchar(20).
--                         ★ 신규 용어 등록 불필요 — 같은 값 공간의 기존 칸을 그대로 따른다.
--
--   ★ 같은 값 공간이므로 표기 정규화도 인입과 같은 규칙을 쓴다. 정규화를 복제하면 인입이
--     대문자로 실어 보낸 값이 이쪽에서만 조달에 실패한다.
--
-- -----------------------------------------------------------------------------
-- * 왜 물리 외래키를 걸지 않는가
-- -----------------------------------------------------------------------------
--   같은 표의 vrfc_evnt_qstn_sn 과 같은 이유다 — 검증 이벤트 유형·질문 카탈로그는 전체 교체로
--   저장되어 <가리키던 행이 사라지는 것이 정상 동선>이다. 참조 무결성은 데이터베이스 제약이
--   아니라 조달 판정이 갖는다.
--   덧붙여 이 카탈로그는 <허용목록이 아니다> — 목록에 없는 유형의 영상도 위탁은 그대로 나간다.
--
-- -----------------------------------------------------------------------------
-- * 되돌리기
-- -----------------------------------------------------------------------------
--   nullable 이라 되돌리지 않아도 무해하다. 드롭 마이그레이션을 만들지 않는다.
-- =============================================================================

ALTER TABLE ls_marking
    ADD COLUMN IF NOT EXISTS vrfc_evnt_type_cd varchar(20);

COMMENT ON COLUMN ls_marking.vrfc_evnt_type_cd IS
    '검증이벤트유형코드 — 관제가 유형을 보내지 않은 영상에서 작업자가 마킹 화면에서 직접 고른 값. 관제 값이 있으면 화면이 선택을 노출하지 않으므로 이 칸은 쓰이지 않는다(조달 순서: 관제 인입 값 -> 이 칸 -> null). 선택 사항이라 비어 있을 수 있다.';
