-- ============================================================================
-- V38 — 작업 이력 원장에 「행위 시점의 행위자 역할」 한 칸을 더한다
--
-- 지금 이 원장은 <누가> 했는지만 남기고 <그때 어떤 역할이었는지>는 남기지 않는다.
-- 그래서 관리자가 승인한 건과 검수자가 승인한 건이 사후에 구분되지 않는다.
-- 조회 시점에 그 사람의 역할을 다시 읽어 메우는 방법은 쓰지 않는다 — 그러면 사람의
-- 역할이 바뀌는 순간 <과거 행위의 역할까지 따라 바뀐다>. 같은 저장소의 이슈 댓글이
-- 작성 시점 역할을 박아 두는 선례를 그대로 따른다.
--
-- ★ 이번 라운드의 <유일한> 스키마 변경이다.
--   함께 도입되는 「검수 시작」 이벤트 종류는 스키마를 건드리지 않는다 —
--   evnt_type_cd 에 CHECK 제약이 없고 표준도메인 폭(varchar(20)) 안에 들어간다.
--   영상별 조회에 쓰는 인덱스(ix_ls_task_evnt_log_raw)도 이미 있다.
--
-- ⚠ 비워 둘 수 있게(nullable) 만든다. 이미 쌓인 이력은 그때의 역할을 <복원할 수 없고>,
--   지어낸 값으로 메우면 그 순간 이력이 거짓이 된다. 소급해 채우지 말 것.
--   또 이 원장에는 배정·제출 같은 다른 종류도 함께 쌓이는데 그쪽은 이번 범위가 아니라
--   역할이 비어 있는 채로 계속 들어온다 — 그것이 정상이며 결함이 아니다.
--
-- ⚠ 허용값에 관리자(ADMIN)가 반드시 들어간다.
--   관리자는 검수자 권한을 계층으로 물려받아 검수 창구를 그대로 통과하므로,
--   관리자가 승인하면 이 칸에 관리자가 들어온다. <V27 이 이슈 댓글에서 정확히 이
--   누락 때문에 500 을 냈고> 뒤늦게 넓혔다. 같은 실수를 되풀이하지 말 것.
--
-- ⚠ 작업자(WORKER)도 들어간다 — 이 원장은 승인·반려뿐 아니라 <제출>도 담고,
--   제출은 작업자가 한다. 「검수 이력이니 검수 역할만」으로 좁히지 말 것.
--   반대로 셋 밖의 값(포털 회원 등)은 계속 거부된다. 이 원장은 내부 채널 소유다.
--
-- ★ 역할 값역이 층마다 다른 것은 정상이다 — 이력 칸은 셋(관리자·검수자·작업자)이고,
--   승인자 표시는 둘(관리자·검수자)이다. 「일관성」을 이유로 통일하지 말 것.
--
-- 물리명 근거: 행위자 ACTOR + 역할 ROLE + 코드 CD.
--   ⚠ 공통표준의 행위자 약어는 ACTR 이지만, 같은 원장에 이미 ACTOR_USER_NO
--     (사업표준 「행위자사용자번호」)가 실재한다. ACTR_ 로 쓰면 한 표 안에서 같은
--     개념이 두 약어가 되므로 ACTOR 로 맞춘다.
--   타입·폭은 코드값 표준도메인 varchar(20).
--
-- 되돌리기:
--   ALTER TABLE ls_task_evnt_log DROP CONSTRAINT ck_ls_task_evnt_log_actor_role;
--   ALTER TABLE ls_task_evnt_log DROP COLUMN actor_role_cd;
--   ⚠ 되돌리면 그동안 쌓인 역할이 <전부 사라진다>. 복원할 수단이 없다.
-- ============================================================================

ALTER TABLE ls_task_evnt_log
    ADD COLUMN IF NOT EXISTS actor_role_cd character varying(20);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('ls_task_evnt_log')
          AND conname = 'ck_ls_task_evnt_log_actor_role'
    ) THEN
        ALTER TABLE ls_task_evnt_log DROP CONSTRAINT ck_ls_task_evnt_log_actor_role;
    END IF;
END $$;

-- NULL 은 이 제약을 통과한다(비워 둘 수 있다는 뜻이며 의도된 것이다).
ALTER TABLE ls_task_evnt_log
    ADD CONSTRAINT ck_ls_task_evnt_log_actor_role
    CHECK (actor_role_cd IN ('ADMIN', 'REVIEWER', 'WORKER'));

COMMENT ON COLUMN ls_task_evnt_log.actor_role_cd IS
    '행위자역할 — 행위자가 그 행위를 한 <시점>의 역할이며 이력 표시에 쓴다. 허용값은 관리자(ADMIN)·검수자(REVIEWER)·라벨링 작업자(WORKER) 셋이고 비어 있을 수 있다. ★비어 있는 경우: 이 칸이 생기기 전에 쌓인 이력, 그리고 역할을 남기지 않는 종류(배정·재배정 등). 비었다고 결함이 아니며 소급해 채우지 않는다 — 그때의 역할은 복원할 수 없고 지어내면 이력이 거짓이 된다. ★관리자가 허용값에 있는 이유: 관리자는 검수자 권한을 계층으로 물려받아 검수 창구를 그대로 통과하므로 관리자가 승인하면 이 값이 들어온다. 쓰이지 않는 값처럼 보인다고 빼지 말 것 — 빼면 관리자 승인이 제약 위반으로 실패한다. ★작업자가 있는 이유: 이 원장은 제출도 담고 제출은 작업자가 한다. 조회 시점에 그 사람의 현재 역할을 읽어 이 값을 대신하지 말 것 — 역할이 바뀌면 과거 행위의 역할까지 따라 바뀐다.';
