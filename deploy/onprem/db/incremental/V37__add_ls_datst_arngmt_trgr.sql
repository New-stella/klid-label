-- ============================================================================
-- V37 — 포털 데이터셋 정리 트리거 접수 원장 신설
--       @design ERD-035 · API-244 · INT-014 · AC-1102 · AC-1103 · ADR-012
--
--   ls_datst_arngmt_trgr (4칸) — 포털이 학습데이터셋의 새 버전을 받아 보낸
--                                정리 삭제 트리거의 접수 기록
--
-- ----------------------------------------------------------------------------
-- * 왜 이 표가 필요한가
-- ----------------------------------------------------------------------------
--   포털이 학습데이터셋의 새 버전을 받으면 저작도구의 정리 삭제 트리거 수신 창구를
--   호출한다(API-244). 저작도구는 그 트리거를 <받은 시점부터 유예를 세고> 그 뒤에
--   올드 해제본을 지운다.
--
--   창구는 이미 두 규칙을 규정하고 있었다.
--     ① 같은 데이터셋 코드와 버전으로 다시 오면 성공 무처리로 답하고
--        <유예 시작 시각을 갱신하지 않는다>. 기준은 <처음 받은 시각>이다.
--     ② 알지 못하는 데이터셋 코드나 버전이 와도 같은 접수 응답으로 답한다.
--
--   그런데 ①이 말하는 <처음 받은 시각>을 담을 자리가 어디에도 없었다.
--   이 파일이 그 자리를 만든다.
--
--   ★ 갱신하면 중복 수신이 반복될 때마다 정리가 무한히 미뤄져 <영영 일어나지 않는다>.
--     그래서 재수신은 이 표를 건드리지 않고 지나간다.
--
-- ----------------------------------------------------------------------------
-- * ★ 이 표는 보존 규칙의 정본이 아니다
-- ----------------------------------------------------------------------------
--   보존 기간과 기산점 규칙의 정본은 포털 작업 데이터 보존기간 만료 자동 삭제
--   기능(DFEAT-055)이다. 이 표는 그 규칙이 읽어 갈 <기산점 값>을 담는 자리일 뿐이며,
--   기간·절차를 이 표나 창구에 복제하지 않는다.
--
-- ----------------------------------------------------------------------------
-- * ★★ 유일 제약이 재수신 멱등의 근거다 (조회 후 삽입으로 대체하지 말 것)
-- ----------------------------------------------------------------------------
--   (데이터셋코드, 버전번호) 유일 제약이 있어야 두 트리거가 <동시에> 도착해도
--   기산점이 갈리지 않는다. 조회한 뒤 삽입하는 방식은 두 요청이 같은 순간에 오면
--   둘 다 조회를 통과해 행이 둘 생기고, 어느 쪽이 기산점인지 알 수 없게 된다.
--
--   그래서 판정을 조회가 아니라 <실행문 자체>에 건다 — 삽입에 ON CONFLICT DO NOTHING
--   을 걸어, 이미 있으면 아무것도 하지 않고 지나가게 한다. 이 저장소가 파생영상 폐기
--   삭제에서 세운 원칙(판정 조건을 최종 실행문에 건다)과 같은 축이다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록"
--   오판을 낸다). <신규 등록이 필요 없다> — 구성 단어가 전부 등재어다.
--
--     데이터셋 DATST   (행안부 공통표준단어)    정리   ARNGMT (행안부 공통표준단어)
--     트리거   TRGR    (행안부 공통표준단어)    코드   CD     (행안부 공통표준단어)
--     일련번호 SN      (행안부 공통표준단어)
--
--   ★ 아래 둘은 <단어 조합이 아니라 등재된 공통표준용어>다. 조합해 만든 것이 아니다.
--     수신일시 RCPTN_DT  (공통표준용어 · 도메인 연월일시분초D)
--     버전번호 VER_NO    (공통표준용어 · 도메인 번호V50)
--
--   타입·폭:
--     datst_cd  character varying(20)  — 코드값 표준도메인
--     ver_no    character varying(50)  — 도메인 번호V50
--
--   ⚠ datst_cd 의 폭 20 은 <잠정>이다. 코드값 표준도메인을 따랐으나 포털의 데이터셋
--     코드 표현 형식(길이·문자집합)이 회신되지 않아 충분한지 확인되지 않았다. 회신이
--     오면 조정한다. 넓혀 두는 쪽으로 미리 벗어나면 표준도메인 이탈이 되어 감리 지적
--     대상이므로, 근거 없이 넓히지 않는다.
--
-- ----------------------------------------------------------------------------
-- * ★ 버전은 문자열로 보존한다 (숫자로 파싱하지 않는다)
-- ----------------------------------------------------------------------------
--   창구가 받는 값이 문자열이고 버전 표기법이 회신되지 않았다. 숫자로 해석하면
--   표기법에 따라 값이 달라지거나 접수 자체가 실패한다.
--
-- ----------------------------------------------------------------------------
-- * ★ 등록일시를 따로 두지 않는 것은 의도다
-- ----------------------------------------------------------------------------
--   행이 생기는 시각과 트리거를 받은 시각이 같다. 둘을 나란히 두면 <같은 사실의
--   두 번째 진실원>이 되고, 나중에 한쪽만 갱신되면 어느 쪽이 기산점인지 갈린다.
--
-- ----------------------------------------------------------------------------
-- * 재적용 안전성
-- ----------------------------------------------------------------------------
--   CREATE TABLE IF NOT EXISTS / CREATE UNIQUE INDEX IF NOT EXISTS 라 두 번 돌아도
--   안전하다. 신규 설치(빈 DB)와 기존 DB 어느 쪽에서도 같은 형상에 도달한다.
--
--   ⚠ public. 리터럴을 박지 않는다 — 스키마가 klid_at 이라 신규 DB 재적용이 조용히
--     어긋난다. 비한정 식별자로 두어 접속 search_path 를 따르게 한다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (Active-Active)
-- ----------------------------------------------------------------------------
--   새 표를 만들 뿐이라 기존 표를 잠그지 않는다. 외래키가 없다 — 데이터셋 코드는
--   포털이 소유한 식별자라 이 저장소에 대응하는 부모 표가 없다.
--
--   ★ 이 변경은 <하위호환>이다. 구 jar 노드는 이 표를 모르므로 아무것도 읽지 않고,
--     새 jar 노드만 쓰고 읽는다. 롤링 재기동으로 무중단 배포가 가능하다.
--
-- ★ 롤백 절차 — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   ⚠ 되돌리면 <접수한 트리거의 기산점이 사라진다>. 그 값은 어디에도 사본이 없고
--     포털이 재전송해 주지도 않는다(중복 수신은 성공 무처리라 재전송이 기산점을
--     복구하지 않는다). 비가역이다.
--
--     DROP TABLE IF EXISTS ls_datst_arngmt_trgr;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '37';
--
-- ----------------------------------------------------------------------------
-- * 이번에 손대지 않는 것 (빠뜨린 것이 아니다)
-- ----------------------------------------------------------------------------
--   - 실제 해제본 삭제 실행 — 지울 대상인 해제본 저장소·원장이 아직 서지 않았다.
--     이 표는 트리거를 접수해 기산점을 남기는 데까지다.
--   - 신규 데이터마트 조달(소재 조회·압축 해제·적재) — 그 창구는 포털이 소유하고
--     응답 규격이 회신되지 않았다.
-- ============================================================================

CREATE TABLE IF NOT EXISTS ls_datst_arngmt_trgr (
    datst_arngmt_trgr_sn bigint GENERATED BY DEFAULT AS IDENTITY,
    datst_cd             character varying(20) NOT NULL,
    ver_no               character varying(50) NOT NULL,
    rcptn_dt             timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ls_datst_arngmt_trgr_pkey PRIMARY KEY (datst_arngmt_trgr_sn)
);

COMMENT ON TABLE ls_datst_arngmt_trgr IS
    '데이터셋정리트리거 — 포털이 학습데이터셋의 새 버전을 받아 보낸 정리 삭제 트리거의 접수 기록. 한 행이 하나의 데이터셋 코드와 버전 짝에 대응하며, 정리 유예의 기산점을 보관한다. 보존 기간·기산점 규칙의 정본은 DFEAT-055 이고 이 표는 그 값을 담는 자리다.';
COMMENT ON COLUMN ls_datst_arngmt_trgr.datst_arngmt_trgr_sn IS
    '데이터셋정리트리거일련번호 — PK. 값은 데이터베이스가 발급한다.';
COMMENT ON COLUMN ls_datst_arngmt_trgr.datst_cd IS
    '데이터셋코드 — 정리 대상을 가리키는 학습데이터셋 코드. 포털이 소유한 식별자라 대응하는 부모 표가 없고 외래키를 두지 않는다. 폭 20 은 코드값 표준도메인을 따른 잠정값이며, 포털의 표현 형식이 회신되면 조정한다.';
COMMENT ON COLUMN ls_datst_arngmt_trgr.ver_no IS
    '버전번호 — 포털이 새로 받은 학습데이터셋 버전. 이 버전이 들어오면 그보다 이전의 올드 해제본이 정리 대상이 된다. 숫자로 파싱하지 않고 문자열로 보존한다 — 창구가 받는 값이 문자열이고 버전 표기법이 회신되지 않았다.';
COMMENT ON COLUMN ls_datst_arngmt_trgr.rcptn_dt IS
    '수신일시 — 이 데이터셋 코드와 버전의 트리거를 처음 받은 시각이며 정리 유예의 기산점이다. 재수신으로 갱신하지 않는다 — 갱신하면 중복 수신이 반복될 때마다 정리가 무한히 미뤄진다. 등록일시를 따로 두지 않는 것은 의도이며, 행이 생기는 시각과 같은 사실이라 나누면 두 번째 진실원이 된다.';

-- ★ 재수신 멱등의 근거 — 이 제약이 있어야 동시 도착에서도 기산점이 갈리지 않는다.
--   삽입은 ON CONFLICT DO NOTHING 으로 걸어 판정을 실행문 자체에 둔다.
CREATE UNIQUE INDEX IF NOT EXISTS uk_ls_datst_arngmt_trgr
    ON ls_datst_arngmt_trgr (datst_cd, ver_no);
