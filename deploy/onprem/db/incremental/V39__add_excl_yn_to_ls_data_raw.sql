-- ============================================================================
-- V39 — 영상 원장에 「화면에서 뺄지」 한 칸을 더한다
--
-- 잘못 들어온 영상과 시험 데이터가 목록에 남아 실제 작업 대상을 가린다. 지울 수는
-- 없다 — 관제가 보낸 자산이고 이미 배치·통지를 탄 것도 있다. 그래서 행을 지우지 않고
-- 표시만 해서 화면에서 뺀다. 되돌릴 수 있다.
--
-- ★★ 이 값이 미치는 범위는 <저작도구 화면 시야 하나>다.
--   배치 파이프라인 · 관제 통지 · 데이터마트 조회 뷰 · 학습데이터 산출물 · 관제 조회
--   창구 · 통계 · 포털 채널은 <전부 무변경>이고 제외된 영상도 그대로 흐른다.
--   ⚠ 다음 사람이 「일관성」을 이유로 그쪽에도 이 조건을 붙이는 것을 막는 것이
--     이 주석의 목적이다. 붙이면 관제가 보던 행이 예고 없이 사라진다.
--   ⚠ 특히 학습데이터 산출물의 <콘텐츠 해시 입력에 넣지 말 것> — 넣으면 제외를 켰다
--     끄는 것만으로 산출물이 재생성되고 관제에 수정 통지가 나간다.
--
-- ★ 이번 라운드의 <유일한> 스키마 변경이다.
--   함께 도입되는 이벤트 종류 둘(영상 제외·영상 복원)은 스키마를 건드리지 않는다 —
--   ls_task_evnt_log.evnt_type_cd 에 CHECK 제약이 없고 표준도메인 폭(varchar(20))
--   안에 들어가며, 누가·그때 어떤 역할이었는지·언제·왜를 담을 칸도 이미 다 있다.
--
-- ★ NOT NULL DEFAULT 'N' 로 둔다 — 비워 둘 수 있게 만들면 <모든 조회부가 빈값 처리를
--   각자 재구현>해야 하고, 그중 한 곳만 빠뜨려도 제외한 영상이 그 화면에 그대로 뜬다.
--   기존 행은 기본값으로 전부 'N'(=표시)이 되므로 <적용 즉시 동작이 바뀌지 않는다>.
--
-- 물리명 근거: 행안부 공통표준용어 「제외여부 = EXCL_YN」 + 공통표준도메인 「여부C1」
--   (character(1), 값역 Y/N). 1순위 사전에 그대로 있어 신규 등록이 필요 없고
--   사업표준용어에는 이 개념이 0건이다.
--   ⚠ HIDE(숨김)·EXPSR(노출) 로 바꾸지 말 것 — 사용자가 쓴 말이 「제외」이고 그 용어가
--     1순위에 실재한다. 같은 개념에 두 이름을 만들지 않는다.
--   ⚠ {대상}_EXCL_YN 꼴(통계제외여부 등)로 늘리지 말 것 — 이 칸이 앉는 표가 이미 영상
--     원장이라 대상이 자명하고, 파생형을 쓰면 그 합성 용어를 새로 등록해야 한다.
--
-- 되돌리기:
--   ALTER TABLE ls_data_raw DROP COLUMN excl_yn;
--   ⚠ 되돌리면 그동안 제외해 둔 판정이 <전부 사라진다>. 숨겨 뒀던 영상이 한꺼번에
--     목록으로 돌아오며, 어느 것이 제외돼 있었는지는 작업 이력에서 되짚어야 한다.
-- ============================================================================

ALTER TABLE ls_data_raw
    ADD COLUMN IF NOT EXISTS excl_yn character(1) DEFAULT 'N' NOT NULL;

COMMENT ON COLUMN ls_data_raw.excl_yn IS
    '제외여부 — 이 영상을 저작도구 화면 목록에서 뺄지에 대한 사람의 판정이다. Y=제외 / N=표시(기본값). 행을 삭제하지 않고 표시만 하므로 언제든 되돌릴 수 있다. 판정 주체는 검수자 이상이며 누가·그 시점 역할·언제·왜가 작업 이력 원장에 남는다. ★★미치는 범위는 저작도구 화면 시야 하나다 — 영상 처리 현황·작업 목록·검수 목록 세 목록에서만 빠지고, 배치 파이프라인·관제 통지·데이터마트 조회 뷰·학습데이터 산출물·관제 조회 창구·통계·포털 채널은 그대로이며 제외된 영상도 그대로 흐른다. 그쪽에 이 조건을 붙이지 말 것 — 붙이면 관제가 보던 행이 예고 없이 사라진다. ★학습데이터 산출물의 콘텐츠 해시 입력이 아니다 — 넣으면 제외를 켰다 끄는 것만으로 산출물이 재생성되고 수정 통지가 나간다. ★비워 둘 수 없게 한 이유: 빈값을 허용하면 모든 조회부가 빈값 처리를 각자 재구현해야 하고 한 곳만 빠져도 제외한 영상이 그 화면에 그대로 뜬다. ★가시성 축이며 개인정보 성질 축(prvc_type_cd·de_ident_yn)과 무관하다 — 둘을 엮지 말 것. 행안부 공통표준용어 제외여부(EXCL_YN) + 공통표준도메인 여부C1.';
