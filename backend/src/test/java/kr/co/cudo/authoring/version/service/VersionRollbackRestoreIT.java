    @Test
    @DisplayName("SKELETON_왕복_롤백_후_POINT_CN_의_v_가_변질되지_않는다")
    void skeletonRoundTripKeepsPointCnRepresentation() {
        // given — 17-keypoint SKELETON 라벨 1건으로 v1 스냅샷 생성.
        String keypoints = skeletonPoints();
        Long id = labelRepository.save(LsDataLbl.createManual(
                srcSn, LsDataLbl.TYPE_SKELETON, null, "person", keypoints, "100")).getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();

        // 작업본을 드리프트시켜 실제 교체 경로를 타게 한다.
        seedLabel(srcSn, "drift", "[[9.0,9.0],[9.5,9.5]]");

        // when
        versionService.rollback(v1Hash, srcSn, reviewer);

        // then — 복원된 좌표는 DB 정규형 그대로(v 가 2.0 으로 변질되지 않음).
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).hasSize(1);
        assertThat(after.get(0).getLblSn()).isEqualTo(id);
        assertThat(after.get(0).getPointCn()).isEqualTo(keypoints);
        assertThat(after.get(0).getPointCn()).doesNotContain("2.0]");
    }

    /** COCO-17 키포인트 좌표(DB 정규형 — x/y 는 double, v 는 정수). */
    private static String skeletonPoints() {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < 17; i++) {
            if (i > 0) {
                sb.append(',');
            }
            sb.append('[').append(10.0 + i).append(',').append(20.0 + i).append(",2]");
        }
        return sb.append(']').toString();
    }

