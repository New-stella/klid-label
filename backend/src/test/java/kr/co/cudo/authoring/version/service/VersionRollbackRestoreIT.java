    @Test
    @DisplayName("복원하려는_LBL_SN_이_이미_존재하면_신규발급으로_폴백하고_전체가_실패하지_않는다")
    void conflictingLblSnFallsBackToNewId() {
        // given — 다른 프레임(other)이 LBL_SN 을 점유한 상태의 스냅샷.
        Long otherSrcSn = srcRepository.save(LsDataSrc.create(rawSn, 1, "/raw/1.jpg", LocalDateTime.now()))
                .getSrcSn();
        Long occupiedId = seedLabel(otherSrcSn, "occupied", "[[0.0,0.0],[1.0,1.0]]").getLblSn();
        String hash = seedVersion("aa11bb22cc33dd44ee55ff66aa77bb88cc99dd00",
                payload(item(occupiedId, "person", "[[10.0,10.0],[50.0,50.0]]", null, null, null, null)));

        // when — 점유된 PK 로 복원 시도.
        assertThatCode(() -> versionService.rollback(hash, srcSn, reviewer)).doesNotThrowAnyException();

        // then — 대상 프레임은 새 PK 로 복원되고, 점유 라벨(타 프레임)은 그대로 남는다.
        List<LsDataLbl> restored = labelRepository.findBySrcSn(srcSn);
        assertThat(restored).hasSize(1);
        assertThat(restored.get(0).getLblSn()).isNotEqualTo(occupiedId);
        assertThat(restored.get(0).getLabelNm()).isEqualTo("person");
        assertThat(labelRepository.findById(occupiedId)).isPresent()
                .get().extracting(LsDataLbl::getSrcSn).isEqualTo(otherSrcSn);
    }

    // ---------- S2: IDENTITY 시퀀스 동기화 ----------

    @Test
    @DisplayName("명시_PK_복원_후에도_다음_라벨_저장이_PK_충돌없이_성공한다")
    void identitySequenceStaysAheadAfterExplicitIdRestore() {
        // given — 시퀀스가 다음에 발급할 값(maxId + 1)을 스냅샷 LBL_SN 으로 사용한다.
        //   시퀀스를 동기화하지 않으면 이후 첫 라벨 저장이 이 PK 를 재발급해 23505(중복키)로 전면 실패한다.
        Long maxId = seedLabel(srcSn, "seed", "[[0.0,0.0],[1.0,1.0]]").getLblSn();
        Long nextIdentity = maxId + 1;
        String hash = seedVersion("bb11cc22dd33ee44ff55aa66bb77cc88dd99ee00",
                payload(item(nextIdentity, "person", "[[10.0,10.0],[50.0,50.0]]", null, null, null, null)));

        versionService.rollback(hash, srcSn, reviewer);
        assertThat(labelRepository.findBySrcSn(srcSn)).extracting(LsDataLbl::getLblSn)
                .containsExactly(nextIdentity);

        // when / then — 복원 이후 신규 라벨 저장이 PK 충돌 없이 성공해야 한다.
        assertThatCode(() -> {
            LsDataLbl saved = seedLabel(srcSn, "after", "[[2.0,2.0],[3.0,3.0]]");
            assertThat(saved.getLblSn()).isGreaterThan(nextIdentity);
        }).doesNotThrowAnyException();
    }

    // ---------- S5: 같은 트랜잭션 재조회 정합 ----------

    @Test
    @DisplayName("복원_직후_같은_트랜잭션에서_재조회하면_새_라벨이_보인다")
    @Transactional(transactionManager = "controlTransactionManager")
    void restoredLabelsVisibleInSameTransaction() {
        Long id1 = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]").getLblSn();
        Long id2 = seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]").getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();
        labelRepository.deleteAllByIdInBatch(List.of(id1, id2));
        assertThat(labelRepository.findBySrcSn(srcSn)).isEmpty();

        versionService.rollback(v1Hash, srcSn, reviewer);

        // 네이티브 삽입은 영속성 컨텍스트를 우회하므로 같은 트랜잭션 재조회가 0건이 되면 안 된다.
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).extracting(LsDataLbl::getLblSn).containsExactlyInAnyOrder(id1, id2);
    }

    /**
     * DEV_FIX-B(M4) — bulk delete(JPQL) 는 1차 캐시를 evict 하지 않는다. 복원 대상 {@code LBL_SN} 이
     * managed 로 남아 있으면 후속 조회가 <b>복원 전 내용</b>을 돌려준다(행 수만 맞음).
     *
     * <p>구 테스트({@link #restoredLabelsVisibleInSameTransaction})는 {@code LBL_SN} 만 단언하고
     * 픽스처가 "복원 전 == 복원 후" 라 stale 을 원리적으로 검출할 수 없었다. 여기서는 <b>복원 전 작업본을
     * 드리프트</b>시켜(라벨명·좌표 상이) 내용까지 단언한다.
     */
    @Test
    @DisplayName("복원_후_재조회가_복원_전_내용을_돌려주지_않는다")
    @Transactional(transactionManager = "controlTransactionManager")
    void reReadAfterRestoreDoesNotReturnStalePersistenceContextState() {
        // given — v1 스냅샷(person/car) 생성 후, 같은 LBL_SN 을 유지한 채 내용만 드리프트시킨다.
        LsDataLbl l1 = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]");
        LsDataLbl l2 = seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]");
        Long id1 = l1.getLblSn();
        Long id2 = l2.getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();

        l1.updateUserContent(LsDataLbl.TYPE_BBOX, null, "drifted-person", "[[99.0,99.0],[100.0,100.0]]");
        l2.updateUserContent(LsDataLbl.TYPE_BBOX, null, "drifted-car", "[[98.0,98.0],[100.0,100.0]]");
        labelRepository.flush();
        // 드리프트된 인스턴스가 1차 캐시에 managed 로 남아 있는 상태(= stale 재현 조건).
        assertThat(labelRepository.findBySrcSn(srcSn)).extracting(LsDataLbl::getLabelNm)
                .containsExactlyInAnyOrder("drifted-person", "drifted-car");

        // when — v1 로 롤백(같은 LBL_SN 으로 원래 내용 복원).
        versionService.rollback(v1Hash, srcSn, reviewer);

        // then — 같은 트랜잭션 재조회가 복원 <b>후</b> 내용을 돌려줘야 한다(행 수·식별자만이 아니라 내용까지).
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).extracting(LsDataLbl::getLblSn).containsExactlyInAnyOrder(id1, id2);
        assertThat(after).extracting(LsDataLbl::getLabelNm)
                .containsExactlyInAnyOrder("person", "car");
        assertThat(after).extracting(LsDataLbl::getPointCn)
                .containsExactlyInAnyOrder("[[10.0,10.0],[50.0,50.0]]", "[[1.0,1.0],[2.0,2.0]]");
    }

    /**
     * DEV_FIX-B(M2) — SKELETON 왕복 롤백이 {@code POINT_CN} 의 가시성 v 표현을 변질시키지 않는지
     * <b>실 DB 값</b>으로 확인한다(스냅샷은 v 를 {@code 2.0} 으로, DB 는 {@code 2} 로 쓴다).
     */
    @Test
    @DisplayName("SKELETON_왕복_롤백_후_POINT_CN_의_v_가_변질되지_않는다")
    void skeletonRoundTripKeepsPointCnRepresentation() {
        // given — 17-keypoint SKELETON 라벨 1건으로 v1 스냅샷 생성.
        String keypoints = skeletonPoints();
        Long id = labelRepository.save(LsDataLbl.createManual(
                srcSn, LsDataLbl.TYPE_SKELETON, null, "person", keypoints, 100L)).getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();

        // 작업본을 드리프트시켜 실제 교체 경로를 타게 한다.
        seedLabel(srcSn, "drift", "[[9.0,9.0],[9.5,9.5]]");

        // when
        versionService.rollback(v1Hash, srcSn, reviewer);

        // then — 복원된 좌표는 DB 정규형 그대로(v 가 2.0 으로 변질되지 않음).
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).hasSize(1);
        assertThat(after.get(0).getLblSn()).isEqualTo(id);
        assertThat(after.get(0).getPointCn()).isEqualTo(keypoints);
        assertThat(after.get(0).getPointCn()).doesNotContain("2.0]");
    }

    /** COCO-17 키포인트 좌표(DB 정규형 — x/y 는 double, v 는 정수). */
    private static String skeletonPoints() {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < 17; i++) {
            if (i > 0) {
                sb.append(',');
            }
            sb.append('[').append(10.0 + i).append(',').append(20.0 + i).append(",2]");
        }
        return sb.append(']').toString();
    }

