    @Test
    @DisplayName("복원하려는_LBL_SN_이_이미_존재하면_신규발급으로_폴백하고_전체가_실패하지_않는다")
    void conflictingLblSnFallsBackToNewId() {
        // given — 다른 프레임(other)이 LBL_SN 을 점유한 상태의 스냅샷.
        Long otherSrcSn = srcRepository.save(LsDataSrc.create(rawSn, 1, "/raw/1.jpg", LocalDateTime.now()))
                .getSrcSn();
        Long occupiedId = seedLabel(otherSrcSn, "occupied", "[[0.0,0.0],[1.0,1.0]]").getLblSn();
        String hash = seedVersion("aa11bb22cc33dd44ee55ff66aa77bb88cc99dd00",
                payload(item(occupiedId, "person", "[[10.0,10.0],[50.0,50.0]]", null, null, null, null)));

        // when — 점유된 PK 로 복원 시도.
        assertThatCode(() -> versionService.rollback(hash, srcSn, reviewer)).doesNotThrowAnyException();

        // then — 대상 프레임은 새 PK 로 복원되고, 점유 라벨(타 프레임)은 그대로 남는다.
        List<LsDataLbl> restored = labelRepository.findBySrcSn(srcSn);
        assertThat(restored).hasSize(1);
        assertThat(restored.get(0).getLblSn()).isNotEqualTo(occupiedId);
        assertThat(restored.get(0).getLabelNm()).isEqualTo("person");
        assertThat(labelRepository.findById(occupiedId)).isPresent()
                .get().extracting(LsDataLbl::getSrcSn).isEqualTo(otherSrcSn);
    }

