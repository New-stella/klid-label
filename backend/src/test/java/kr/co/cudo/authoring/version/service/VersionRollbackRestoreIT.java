    private LsDataLbl seedLabel(Long frameSn, String label, String pointsJson) {
        return labelRepository.save(
                LsDataLbl.createManual(frameSn, LsDataLbl.TYPE_BBOX, null, label, pointsJson, "100"));
    }

    /** 지정 payload 를 그대로 담은 active 버전 행을 적재하고 해시를 반환(롤백 입력용). */
    private String seedVersion(String hash, String payload) {
        labelVersionRepository.save(LsLabelVersion.create(
                rawSn, srcSn, hash, payload, 1, LsLabelVersion.SAVE_REASON_APPROVED, "1"));
        return hash;
    }

    /** commitApproved 가 만든 현재 active 스냅샷 해시. */
    private String activeSnapshotHash() {
        return labelVersionRepository.findByDataSrcSnOrderByRegDtDesc(srcSn).stream()
                .filter(v -> LsLabelVersion.ACTIVE_YES.equals(v.getActiveYn()))
                .findFirst().orElseThrow().getVersionHash();
    }

    /** 스냅샷 item 1건 JSON — 옛 LBL_SN(id) 및 AI 메타/트랙 포함(필드는 null 허용). */
    private static String item(Long id, String label, String points, String autoLblYn,
                               String confScore, String trackId, String lblSrcCd) {
        return "{\"id\":" + id + ",\"lblTypeCd\":\"BBOX\",\"label\":\"" + label
                + "\",\"labelId\":null,\"points\":" + points
                + ",\"autoLblYn\":" + (autoLblYn == null ? "null" : "\"" + autoLblYn + "\"")
                + ",\"confScore\":" + (confScore == null ? "null" : confScore)
                + ",\"trackId\":" + (trackId == null ? "null" : "\"" + trackId + "\"")
                + ",\"lblSrcCd\":" + (lblSrcCd == null ? "null" : "\"" + lblSrcCd + "\"") + "}";
    }

    private String payload(String... items) {
        return "{\"srcSn\":" + srcSn + ",\"frameNo\":0,\"items\":[" + String.join(",", items) + "]}";
    }

