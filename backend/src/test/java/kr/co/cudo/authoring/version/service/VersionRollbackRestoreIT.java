    @Test
    @DisplayName("속성값을_보유한_프레임_롤백시_FK_위반_500_이_발생하지_않는다")
    void rollbackWithAttributeValuesDoesNotViolateFk() {
        // given — 라벨 1건 + 그 라벨의 속성값(LS_DATA_LBL_ATTR_VAL — LS_DATA_LBL 에 실 FK).
        Long id1 = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]").getLblSn();
        createdLabelId = lsLabelRepository.save(
                LsLabel.create("롤백복원IT라벨", "#FF0000", LsDataLbl.TYPE_BBOX, 1, "1")).getLabelId();
        createdAttrId = lsLabelAttrRepository.save(LsLabelAttr.create(
                createdLabelId, "색상", LsLabelAttr.INPUT_TEXT, null, null, "Y", 1, "1")).getAttrId();
        attrValRepository.save(LsDataLblAttrVal.create(id1, createdAttrId, "red"));

        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();
        // D-ISSUE-24 — 작업본이 스냅샷과 완전히 동일하면 롤백은 진짜 no-op(라벨 미교체)이 되어 FK 경로를
        //   타지 않는다. 실제 교체 경로를 검증하려면 작업본을 드리프트시켜 둔다.
        seedLabel(srcSn, "drift", "[[9.0,9.0],[9.5,9.5]]");

        // when / then — 속성값 선정리 없이 부모를 지우면 FK 위반(500)이 된다.
        assertThatCode(() -> versionService.rollback(v1Hash, srcSn, reviewer))
                .doesNotThrowAnyException();
        assertThat(labelRepository.findBySrcSn(srcSn)).extracting(LsDataLbl::getLblSn)
                .containsExactly(id1);
        // ★ 알려진 한계(적대 #7 — 스코프 밖, 별건): 스냅샷 payload 에 라벨 <b>속성값</b> 필드가 없어
        //   어떤 버전으로 롤백해도 LS_DATA_LBL_ATTR_VAL 은 복원할 수 없다(FK 위반 방지를 위해 삭제만 한다).
        //   따라서 아래 isEmpty() 는 "정상 동작"이 아니라 <b>복원 불가라는 현 한계를 고정</b>한 단언이다.
        //   복원까지 하려면 스냅샷 스키마 확장(속성값 포함)이 선행돼야 하며 본 수정 범위가 아니다.
        assertThat(attrValRepository.findByLblSnIn(List.of(id1))).isEmpty();
    }

    @Test
    @DisplayName("롤백_후_AI메타와_TRCK_ID_가_고아가_되지_않고_복원된다")
    void rollbackRestoresAiMetaAndTrackIdWithoutOrphans() {
        // given — 라벨 A(스냅샷 대상) / 라벨 B(스냅샷 미포함) 각각 AI 메타 보유.
        Long idA = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]").getLblSn();
        Long idB = seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]").getLblSn();
        aiInfoRepository.save(LsDataLblAiInfo.create(idA, rawSn, srcSn,
                LsDataLblAiInfo.SRC_YOLO, new BigDecimal("0.50000"), "1"));
        aiInfoRepository.save(LsDataLblAiInfo.create(idB, rawSn, srcSn,
                LsDataLblAiInfo.SRC_SAM2, new BigDecimal("0.60000"), "1"));
        String hash = seedVersion("cc11dd22ee33ff44aa55bb66cc77dd88ee99ff00",
                payload(item(idA, "person", "[[10.0,10.0],[50.0,50.0]]",
                        LsDataLbl.AUTO_YES, "0.90000", "T-1", LsDataLblAiInfo.SRC_YOLO)));

        // when
        versionService.rollback(hash, srcSn, reviewer);

        // then — TRCK_ID 복원(구 구현은 createManual 이라 항상 NULL).
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).hasSize(1);
        assertThat(after.get(0).getLblSn()).isEqualTo(idA);
        assertThat(after.get(0).getTrackId()).isEqualTo("T-1");

        // AI 메타는 스냅샷 값으로 복원.
        List<LsDataLblAiInfo> aiA = aiInfoRepository.findByDataLblSnIn(List.of(idA));
        assertThat(aiA).hasSize(1);
        assertThat(aiA.get(0).getLblSrcCd()).isEqualTo(LsDataLblAiInfo.SRC_YOLO);
        assertThat(aiA.get(0).getAutoLblYn()).isEqualTo(LsDataLbl.AUTO_YES);
        assertThat(aiA.get(0).getConfScore()).isEqualByComparingTo("0.90000");

        // 스냅샷에 없어 삭제된 라벨 B 의 AI 메타는 고아로 남지 않는다.
        assertThat(aiInfoRepository.findByDataLblSnIn(List.of(idB))).isEmpty();
    }

    @Test
    @DisplayName("AI메타_키가_없는_옛_스냅샷도_롤백이_성공한다")
    void legacySnapshotWithoutAiMetaKeysStillRolledBack() {
        // given — id/autoLblYn/confScore/trackId/lblSrcCd 키가 전혀 없는 옛 스냅샷 형식.
        seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]");
        String legacyPayload = "{\"srcSn\":" + srcSn + ",\"frameNo\":0,\"items\":["
                + "{\"lblTypeCd\":\"BBOX\",\"label\":\"person\",\"points\":[[10.0,10.0],[50.0,50.0]]}]}";
        String hash = seedVersion("dd11ee22ff33aa44bb55cc66dd77ee88ff99aa00", legacyPayload);

        // when / then — 신규 PK 발급으로 복원되고 예외가 없어야 한다.
        assertThatCode(() -> versionService.rollback(hash, srcSn, reviewer))
                .doesNotThrowAnyException();
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).hasSize(1);
        assertThat(after.get(0).getLabelNm()).isEqualTo("person");
        assertThat(after.get(0).getTrackId()).isNull();
        assertThat(aiInfoRepository.findByDataLblSnIn(List.of(after.get(0).getLblSn()))).isEmpty();
    }
