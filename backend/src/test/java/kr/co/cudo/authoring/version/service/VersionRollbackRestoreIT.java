    @Test
    @DisplayName("롤백_복원시_스냅샷의_LBL_SN_이_그대로_유지된다")
    void rollbackPreservesSnapshotLblSn() {
        // given — 라벨 2건으로 승인 스냅샷 v1 생성 후, 라벨을 전혀 다른 세트로 교체.
        Long id1 = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]").getLblSn();
        Long id2 = seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]").getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();

        labelRepository.deleteAllByIdInBatch(List.of(id1, id2));
        seedLabel(srcSn, "bike", "[[7.0,7.0],[8.0,8.0]]");

        // when
        versionService.rollback(v1Hash, srcSn, reviewer);

        // then — 옛 LBL_SN 이 그대로 복원(재발급 금지).
        List<LsDataLbl> after = labelRepository.findBySrcSn(srcSn);
        assertThat(after).extracting(LsDataLbl::getLblSn)
                .containsExactlyInAnyOrder(id1, id2);
        assertThat(after).extracting(LsDataLbl::getLabelNm)
                .containsExactlyInAnyOrder("person", "car");
    }

    @Test
    @DisplayName("좌표가_동일한_롤백_후_diff_가_변경없음으로_판정")
    void diffAfterRoundTripReportsNoChange() {
        // given — v1(person) → 수정(car) → v2 → v1 로 롤백 → 재승인.
        Long id1 = seedLabel(srcSn, "person", "[[10.0,10.0],[50.0,50.0]]").getLblSn();
        versionService.commitApproved(rawSn, reviewer);
        String v1Hash = activeSnapshotHash();

        labelRepository.deleteAllByIdInBatch(List.of(id1));
        seedLabel(srcSn, "car", "[[1.0,1.0],[2.0,2.0]]");
        versionService.commitApproved(rawSn, reviewer);

        // when
        versionService.rollback(v1Hash, srcSn, reviewer);
        versionService.commitApproved(rawSn, reviewer);

        // then — 롤백 후 상태는 v1 과 라벨 식별자·좌표가 동일하므로 diff 는 변경 0건.
        DiffResponseDto diff = versionService.diff(v1Hash, activeSnapshotHash(), reviewer);
        assertThat(diff.labels()).isEmpty();
        assertThat(labelRepository.findBySrcSn(srcSn)).extracting(LsDataLbl::getLblSn)
                .containsExactly(id1);
    }

