-- Phase 3 — Gitea fallback 영속 큐.
-- ccarch if-gitea-contents (동기 REST + fallback 큐) 명세에 맞춰 신설.
--
-- 정책
--  - CircuitBreaker open 또는 호출 실패 시 본 큐에 적재.
--  - Quartz GiteaFallbackRetryJob 가 NEXT_RETRY_AT <= now 인 PENDING/RETRYING 항목을 백오프 재시도.
--  - RETRY_COUNT > MAX_RETRY 시 DEAD_LETTER 마킹 + 운영 메트릭.
--  - 동일 IDEMPOTENCY_KEY UNIQUE — 중복 적재 차단 (S-4 방어).
--  - CONTENT_BASE64 는 TEXT (라벨 JSON base64). 적재 전 1MB 크기 제한은 서비스 레벨에서 검증.

CREATE TABLE LS_GITEA_FALLBACK_QUEUE (
    QUEUE_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    IDEMPOTENCY_KEY VARCHAR(64) NOT NULL,
    OPERATION VARCHAR(16) NOT NULL,
    PATH VARCHAR(512) NOT NULL,
    BRANCH VARCHAR(128) NULL,
    COMMIT_MESSAGE VARCHAR(1024) NULL,
    AUTHOR VARCHAR(64) NULL,
    CONTENT_BASE64 TEXT NULL,
    RETRY_COUNT INT NOT NULL DEFAULT 0,
    MAX_RETRY INT NOT NULL DEFAULT 5,
    STATUS VARCHAR(16) NOT NULL,
    LAST_ERROR VARCHAR(2000) NULL,
    NEXT_RETRY_AT TIMESTAMP NULL,
    DEAD_LETTER_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (QUEUE_SN),
    CONSTRAINT uk_idempotency_key UNIQUE (IDEMPOTENCY_KEY)
);

CREATE INDEX idx_status_next_retry ON LS_GITEA_FALLBACK_QUEUE (STATUS, NEXT_RETRY_AT);
CREATE INDEX idx_dead_letter ON LS_GITEA_FALLBACK_QUEUE (DEAD_LETTER_AT);
