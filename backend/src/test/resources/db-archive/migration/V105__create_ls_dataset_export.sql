-- =============================================================================
-- V105: 학습데이터 파일 산출 추적 테이블 LS_DATASET_EXPORT
--
-- 목적: 검수 승인(APPROVED) 시 라벨링 산출물을 파일로 저장하는 기능(Phase 1 인프라)의
--       추적/버전 도출 원장. 영상(DATA_RAW_SN) 단위로 export 를 누적 기록하고, 그 건수로
--       다음 산출 버전(EXPORT_VER_NO = count + 1)을 도출한다. 실제 폴더는
--       {labeling_root}/{RAW_SN}/v{n}/{orgnl|deid}/ 구조로 산출된다(버전이 orgnl/deid 상위).
--
-- 멱등/제약:
--   - UK(DATA_RAW_SN, EXPORT_VER_NO) — 같은 영상의 같은 버전 중복 산출 차단(재승인 race 방어).
--     이 UK 가 생성하는 복합 btree 인덱스(선두=DATA_RAW_SN)가 버전 도출(countByDataRawSn)·
--     최신 버전 조회(findFirst...OrderByExportVerNoDesc)를 모두 커버하므로 별도 단일 인덱스는 두지 않는다.
--
-- 표준 정합(Critical):
--   - 물리명은 기존 LS_LABEL_VERSION(DATA_RAW_SN·VER_NO)·LS_DATA_RAW 약어 컨벤션을 재사용한다.
--     새 표준단어 도입 없음(SN·PATH_NM·STTS_CD·CNT·REG_DT 모두 기존 스키마 표준 조합).
--   - EXPORT_PATH_NM 길이는 RAW_FILE_PATH_NM(V97, 500) 과 정합.
--   - 감사 시각 REG_DT 는 TIMESTAMP(기존 테이블 관례).
--   - JPA ddl-auto=validate 정합 — 엔티티 LsDatasetExport 와 컬럼/타입 정확히 일치.
--
-- PostgreSQL 표준 문법.
-- =============================================================================

CREATE TABLE IF NOT EXISTS LS_DATASET_EXPORT (
    EXPORT_SN       BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    DATA_RAW_SN     BIGINT       NOT NULL,
    EXPORT_VER_NO   INT          NOT NULL,
    EXPORT_PATH_NM  VARCHAR(500),
    EXPORT_STTS_CD  VARCHAR(20)  NOT NULL,
    FRAME_CNT       INT,
    REG_DT          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (EXPORT_SN),
    CONSTRAINT UK_LS_DATASET_EXPORT UNIQUE (DATA_RAW_SN, EXPORT_VER_NO)
);
