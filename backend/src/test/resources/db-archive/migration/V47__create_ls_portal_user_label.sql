-- V2.0: 포털 사용자 작업 데이터 별도 적재. 원본(LS_DATA_LBL) 미수정 정책.
CREATE TABLE IF NOT EXISTS LS_PORTAL_USER_LABEL (
    USER_LBL_SN     BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    PORTAL_USER_NO  VARCHAR(100)    NOT NULL,
    SRC_RAW_SN      BIGINT          NOT NULL,
    SRC_DATA_SRC_SN BIGINT          NOT NULL,
    LBL_TYPE_CD     VARCHAR(16)     NOT NULL,
    LABEL_NM        VARCHAR(255),
    POINT_CN        TEXT,
    REG_DT          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MDFCN_DT        TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_LBL_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LPUL_USER ON LS_PORTAL_USER_LABEL (PORTAL_USER_NO, SRC_RAW_SN);
CREATE INDEX IF NOT EXISTS IDX_LPUL_SRC ON LS_PORTAL_USER_LABEL (PORTAL_USER_NO, SRC_DATA_SRC_SN);
