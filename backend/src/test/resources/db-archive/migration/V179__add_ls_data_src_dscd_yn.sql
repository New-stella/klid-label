-- =============================================================================
-- V179: 프레임(LS_DATA_SRC)에 <폐기여부> 컬럼 신설 (DSCD_YN)
--
-- 목적(그룹 ③ P1 — 데이터 기반): "이 프레임을 학습데이터 산출물에서 뺀다"는 사람의 판정을
-- 담을 컬럼을 신설한다. 이번 단계는 <컬럼 + 엔티티 매핑>만 담당하고, 폐기/복원 API·목록 필터·
-- export 제외 배선은 후속(P2·P3)이다 — 이 마이그레이션만으로는 기존 동작이 바뀌지 않는다.
--
-- ★ 프레임 행을 물리 삭제하지 않는 이유: LS_DATA_LBL(라벨)·LS_DATA_LBL_HSTRY(이력)·
--   LS_LABEL_VERSION(승인 스냅샷)이 SRC_SN 을 참조한다. 행을 지우면 이미 승인·통지된 산출물의
--   근거가 사라지고 복원(R5)이 성립하지 않는다. 폐기는 <표시>이지 삭제가 아니다.
--
-- 표준용어/표준도메인 (CSV 정본 대조 완료 — 신규 등록 0건, 기존 등록 재사용):
--   - 공통표준용어.csv: 폐기여부,못 쓰게 된 것을 버렸는지 여부,DSCD_YN,여부C1,
--     "Y : 여(예), N : 부(아니요)",1자리 문자
--   - 공통표준도메인.csv: 여부C1,여부,C,1,1자리 문자,Y or N
--   즉 DSCD_YN 은 신규 약어 조합이 아니라 행정안전부 공통표준용어에 이미 등록된 용어명 그대로다.
--   ※ RVK_YN(취소/철회) 계열을 쓰지 않는다 — 그건 토큰 revoke 전용 의미라 이 축과 다르다.
--
-- NULL 정책 — NOT NULL DEFAULT 'N' (V177 REVLT_YN 과 같은 축):
--   이 플래그는 "폐기된 적이 있는가"를 나타내며, 컬럼 신설 이전 행은 그 사실 자체가 없었다
--   (신설 이전에는 폐기 기능이 존재하지 않았다) — 즉 기존 행은 전부 <폐기되지 않음>이 맞는 값이라
--   DEFAULT 'N' 이 <값을 지어내는 것>이 아니다. 별도 백필 UPDATE 를 쓰지 않는다(DEFAULT 가 채운다).
--
-- ★ 애플리케이션도 값을 명시 INSERT 한다(엔티티 LsDataSrc 팩토리) — 이 엔티티에는
--   @DynamicInsert 가 없어 Hibernate 가 모든 컬럼을 명시 INSERT(값 없으면 명시적 NULL)하므로
--   DB DEFAULT 는 주 적재 경로에서 적용되지 않는다. 개인정보 3필드(2026-08-04)와 동일한 이유다.
--   여기 DEFAULT 는 <기존 행 채움> + <우리 코드를 거치지 않는 INSERT> 를 위한 안전망이다.
--
-- 우리 소유 LS_* 테이블(관제 MNG_* 아님) — 협의 불요. PostgreSQL 표준 문법. 멱등(IF NOT EXISTS).
--
-- 롤백 SQL (V162 규약 — 스키마 변경에는 롤백 전문을 동반한다):
--   ALTER TABLE LS_DATA_SRC DROP COLUMN IF EXISTS DSCD_YN;
--   ※ 애플리케이션 롤백도 함께 필요하다 — 엔티티 매핑(LsDataSrc.dscdYn)이 남아 있으면
--     컬럼 부재로 INSERT/조회가 실패한다.
-- =============================================================================

ALTER TABLE LS_DATA_SRC ADD COLUMN IF NOT EXISTS DSCD_YN CHAR(1) NOT NULL DEFAULT 'N';

COMMENT ON COLUMN LS_DATA_SRC.DSCD_YN IS
    '폐기여부 — 이 프레임을 학습데이터 산출물에서 제외할지에 대한 사람의 판정. '
    'Y=폐기(산출 제외) / N=사용(기본값). 행을 삭제하지 않고 표시만 한다(복원 가능). '
    '행안부 공통표준용어 DSCD_YN + 공통표준도메인 여부C1(CHAR(1), Y/N).';
