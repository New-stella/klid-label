-- =============================================================================
-- V97: 포털향 통합 메타 물리 테이블 LS_DATASET_VIDEO_META
--
-- 목적: 검수 승인(APPROVED) 시점에 영상 메타(NIA video.* 블록)를 1영상=1행 컬럼형으로
--       동결(materialize) 적재한다. control DB(klid_at)가 단일 진실원(SoT)이고, 포털 DB는
--       outbox 단방향 복제본으로 반영된다(본 마이그레이션은 control 원본만 생성).
--
-- 멱등키/이력:
--   - SNPSHT_HASH(SHA-256, hex) — 동결 페이로드 해시. LS_LABEL_VERSION.VERSION_HASH 방식 준용.
--   - UK(RAW_SN, SNPSHT_HASH) — 동일 페이로드 재승인 시 중복 스냅샷 차단(멱등).
--   - ACTIVE_YN — 재검수·수정 후 재승인 시 신규 행 append + 이전 행 'N'(append-only 이력).
--
-- 표준 정합(Critical):
--   - YN 도메인은 V85 프로젝트 표준(공공 표준 여부 도메인 = CHAR(1), 예외 0)에 따라 CHAR(1).
--     (설계 초안의 VARCHAR(1) 표기 대신 codebase 표준을 따라 drift 방지 + ddl-auto=validate 정합.)
--   - 감사 ID(REG_ID)는 V94 표준(전 테이블 VARCHAR(64) 통일)에 정합.
--   - 해상도는 program 표준 RESL(비표준 legacy RSLTN 미사용).
--   - WGS84_LAT/LOT 는 기존 LS_DATA_RAW 원천(V2) 및 MngResourceCctv 와 동일 DECIMAL(10,7).
--
-- PostgreSQL 표준 문법.
-- =============================================================================

CREATE TABLE IF NOT EXISTS LS_DATASET_VIDEO_META (
    META_SNPSHT_SN   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    RAW_SN           BIGINT       NOT NULL,
    SNPSHT_HASH      VARCHAR(64)  NOT NULL,
    ACTIVE_YN        CHAR(1)      NOT NULL DEFAULT 'Y',

    -- 원시(LS_DATA_RAW 유래)
    ORGNL_RAW_SN     BIGINT,
    VMS_CLIP_ID      VARCHAR(128),
    VMS_CCTV_ID      VARCHAR(64),
    RAW_FILE_PATH_NM VARCHAR(500),
    SHT_DT           TIMESTAMP,
    VDO_LEN_SEC      INT,
    LCLGV_CD         VARCHAR(32),
    PRVC_YN          CHAR(1),
    PRVC_TYPE_CD     VARCHAR(16),
    DE_IDENT_YN      CHAR(1),
    AI_CRT_YN        CHAR(1),
    EVNT_TYPE_CD     VARCHAR(32),

    -- MNG 동결(관제 공유 테이블 조인 결과를 스냅샷 시점에 복제)
    CCTV_NM          VARCHAR(255),
    WGS84_LAT        DECIMAL(10,7),
    WGS84_LOT        DECIMAL(10,7),
    SIDO_NM          VARCHAR(100),
    SGG_NM           VARCHAR(100),
    FILE_FMT         VARCHAR(32),
    EVNT_NM          VARCHAR(255),

    -- ffprobe 기술 메타
    VDO_CDC          VARCHAR(32),
    FPS              NUMERIC,
    BIT_RT           BIGINT,
    ASPRT_RT         NUMERIC,
    RESL             VARCHAR(32),
    VDO_WDTH         INT,
    VDO_HGT          INT,
    FILE_SZ          BIGINT,

    -- 파생(SHT_DT)/수기
    DAY_NGT_CD       VARCHAR(8),
    SESN_CD          VARCHAR(8),
    WTHR_NM          VARCHAR(32),

    -- 관리
    RVW_CMPL_DT      TIMESTAMP,
    REG_DT           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID           VARCHAR(64),

    PRIMARY KEY (META_SNPSHT_SN),
    CONSTRAINT UK_LS_DATASET_VIDEO_META UNIQUE (RAW_SN, SNPSHT_HASH)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DATASET_VIDEO_META_RAW_ACTIVE
    ON LS_DATASET_VIDEO_META (RAW_SN, ACTIVE_YN);

CREATE INDEX IF NOT EXISTS IDX_LS_DATASET_VIDEO_META_RVW_CMPL
    ON LS_DATASET_VIDEO_META (RVW_CMPL_DT);
