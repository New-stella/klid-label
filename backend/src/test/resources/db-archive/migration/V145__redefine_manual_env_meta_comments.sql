-- V145: 촬영환경 수동입력 컬럼의 DB COMMENT 재정의 (문서 드리프트 정정 — Phase 10B L-4)
--
-- 배경: V130 이 신설한 LS_DATA_RAW.WTHR_NM / DAY_NGT_CD / SESN_CD 의 COMMENT 는
--       "NULL=미입력(파생 폴백 대상)" 이라고 서술한다. 그 정책은 E-ISSUE-42(2026-07-29)로
--       <폐기>됐다 — 촬영일시(SHT_DT) 기반 추정(self-fill)은 화면 프리필(조회)에만 남고,
--       승인 동결(LS_DATASET_VIDEO_META)·export JSON·데이터마트 뷰에는 수동값이 없으면
--       null(미상)을 그대로 싣는다. 동결·산출 경로에는 출처 구분자가 없어 추정값이 관측값과
--       구분 없이 관제로 소비되기 때문이다(실증: 여름 18:00 촬영분이 구 규칙 hour>=18 → NGT 로
--       야간 오분류. 한국 7월 일몰 ≈ 19:50).
--
-- 마이그레이션 파일은 불변이므로 V130 을 수정하지 않고 여기서 COMMENT 만 재정의한다.
-- 컬럼/타입/제약/데이터 변경 없음 — 신규 물리명이 없으므로 표준용어·표준도메인 신규 판단 대상도 없다
-- (컬럼 자체는 V130 이 표준용어 근거와 함께 신설했고 그대로 유지된다).
-- COMMENT ON 은 항상 덮어쓰기라 멱등이다(재실행 안전).
--
-- 우리 소유 LS_* 테이블(관제 MNG_* 아님) — 협의 불요. PostgreSQL 표준 문법.
-- =============================================================================

COMMENT ON COLUMN LS_DATA_RAW.WTHR_NM    IS '촬영 날씨(작업자 수동입력). NULL=미입력(미상). 자동 파생 원천이 없어 값이 있으면 항상 수동값이다.';
COMMENT ON COLUMN LS_DATA_RAW.DAY_NGT_CD IS '촬영 시간대 코드 주간/야간(작업자 수동입력). NULL=미입력(미상). 동결·export·데이터마트 뷰는 NULL 을 그대로 싣는다 — 촬영일시 추정 안 함(E-ISSUE-42). 촬영일시 파생은 화면 프리필(조회 응답 source=DERIVED)에만 쓴다.';
COMMENT ON COLUMN LS_DATA_RAW.SESN_CD    IS '촬영 계절 코드(작업자 수동입력). NULL=미입력(미상). 동결·export·데이터마트 뷰는 NULL 을 그대로 싣는다 — 촬영일시 추정 안 함(E-ISSUE-42). 촬영일시 파생은 화면 프리필(조회 응답 source=DERIVED)에만 쓴다.';
