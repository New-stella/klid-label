-- ============================================================================
-- V29 — 라벨 원장의 라벨명 NOT NULL 을 푼다  @design ADR-058, ERD-028, ERD-010
--
--   ls_data_lbl.lbl_nm  NOT NULL → NULL 허용   (되돌릴 수 있다)
--
-- ----------------------------------------------------------------------------
-- * 왜 푸나
-- ----------------------------------------------------------------------------
--   포털 업로드 자산의 수동 라벨은 <라벨명이 없을 수 있다> — 흡수 전 전용 표
--   (ls_portal_uld_lbl.lbl_nm)가 nullable 이었고, 포털 라벨링 화면은 마스터를 참조하지 않는
--   자유 입력이라 이름 없이 도형만 그리는 것이 정상 동선이다.
--
--   그 라벨이 이제 이 원장에 앉는데(ADR-058) 컬럼이 NOT NULL 이라 <저장 자체가 막힌다>.
--
--   ★ 포털이 기본값('무제' 같은 것)을 채우는 안은 <기각>했다 — 지어낸 값이 쌓이면 나중에
--     진짜 라벨명과 구분되지 않는다. 값이 없다는 사실을 값으로 표현한다.
--
-- ----------------------------------------------------------------------------
-- * 관제 라벨은 아무것도 달라지지 않는다
-- ----------------------------------------------------------------------------
--   내부 채널의 라벨 생성 통로는 전부 라벨명을 채운다 —
--     · 오토라벨(YOLO/SAM2/보간) : 검출 클래스명 또는 마스터 라벨명
--     · 수동 라벨(라벨링 화면)    : 마스터에서 고른 라벨명 (입구 검증이 공백을 막는다)
--     · 버전 롤백 복원            : 스냅샷이 보유한 라벨명
--   즉 이 완화로 관제 라벨에 NULL 이 새로 생기지는 않는다. <제약만 풀고 값은 그대로>다.
--
--   ⚠ 읽는 쪽은 이미 null 을 견딘다 — 응답 매퍼가 마스터(LS_LABEL) 조인값을 우선하고
--     그것이 없을 때만 이 컬럼을 쓴다. 새로 null 방어를 뿌릴 필요는 없다.
--
-- ----------------------------------------------------------------------------
-- * 되돌리기
-- ----------------------------------------------------------------------------
--   ALTER TABLE ls_data_lbl ALTER COLUMN lbl_nm SET NOT NULL;
--   ⚠ 그때 포털 라벨(이름 없는 행)이 이미 들어 있으면 실패한다. 먼저 그 행을 정리해야 하며,
--     정리하면 사용자가 그린 라벨이 사라진다.
--
-- ----------------------------------------------------------------------------
-- * 멱등성 / 의존성
-- ----------------------------------------------------------------------------
--   - 현재 형상을 확인한 뒤에만 실행한다(재실행 안전).
--     카탈로그 조회는 current_schema() 로 스코프한다 — 'public' 리터럴을 박으면 klid_at 에서
--     영원히 거짓이 되어 조용히 건너뛴다(V62/V63/V71 실사고).
--   - 이 컬럼을 참조하는 뷰·인덱스·제약은 없다(전수 확인). NOT NULL 해제는 데이터를 건드리지
--     않으므로 기존 행에 무해하고, 구 jar 에도 무해하다(늘 값을 채워 넣을 뿐이다).
-- ============================================================================

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name   = 'ls_data_lbl'
          AND column_name  = 'lbl_nm'
          AND is_nullable  = 'NO'
    ) THEN
        ALTER TABLE ls_data_lbl ALTER COLUMN lbl_nm DROP NOT NULL;
    END IF;
END $$;

COMMENT ON COLUMN ls_data_lbl.lbl_nm IS
    '라벨명 — 이 라벨의 표시 이름. 마스터(LS_LABEL) 연결이 있으면 조회 시점에 마스터 이름이 우선하고 이 값은 보조다. ★NULL 을 허용하는 이유(V29): 포털 업로드 자산의 수동 라벨은 마스터를 참조하지 않는 자유 입력이라 이름 없이 도형만 그리는 것이 정상이다. 기본값을 지어 채우면 나중에 진짜 라벨명과 구분되지 않으므로 없다는 사실을 그대로 둔다. 내부 채널 생성 통로는 전부 이 값을 채우므로 관제 라벨에 NULL 이 새로 생기지는 않는다. @design ADR-058, ERD-028';
