-- ============================================================================
-- V25: 위탁 멱등 원장에 <어느 장비로 보냈는가> 를 남긴다  @design ERD-021 @design ADR-057
--
--   ls_webhook_idempotency.srvr_id  추가 (nullable · 시드 없음)
--
-- 외부 시계열 분석 서버가 장비 두 대로 이중화되면서, 위탁을 나눠 보내려면 <장비별 부하>를 셀 수
-- 있어야 하고 결과가 도착했을 때 <어느 장비의 산출인지> 되짚을 수 있어야 한다. 그 자리가 없어서
-- 지금까지는 장비가 둘이어도 한 대만 쓰였다.
--
-- ----------------------------------------------------------------------------
-- * 부하로 세는 것은 <수락된(ACCEPTED)> 행뿐이다
-- ----------------------------------------------------------------------------
--   발급(ISSUED)은 우리가 상관키를 선커밋한 것일 뿐 <벤더가 아직 받지 않은> 상태라 그 장비의
--   부하가 0이다. 그걸 부하로 세면 방금 제출이 몰린 장비를 과대평가해 다음 요청이 반대편으로
--   쏠리고, 그 반대편도 곧 같은 이유로 과대평가된다 — 값이 실제 부하가 아니라 <직전 배분의
--   메아리>가 되어 진자운동한다.
--
-- ----------------------------------------------------------------------------
-- * nullable 인 이유와, 그것이 회수 경로에 거는 제약  ★
-- ----------------------------------------------------------------------------
--   이 컬럼이 생기기 전에 적재된 행은 <장비 미상>이다. 그리고 앞으로도 장비를 고르지 못한 위탁
--   (원장에 시계열 노드가 한 건도 없어 배포 기본 주소로 나가는 구성)은 미상으로 남는다.
--
--   ★ 그러므로 미결 회수 스윕의 조회·클레임 조건에 <장비 축을 걸지 않는다>. 걸면 미상 행과
--     <죽은 장비의 몫>이 영영 회수되지 않는데, 그 스윕은 「응답도 실패 신호도 오지 않아 시계열
--     메타가 무증상으로 영구 결손되는 것」을 막는 유일한 경로다. 죽은 장비의 몫일수록 더 회수돼야
--     한다. (2노드 Active-Active 의 이중 회수는 <백엔드 노드> 축의 문제이고 조건부 UPDATE 가
--     이미 닫았다 — GPU 장비 축과 혼동하지 말 것.)
--
-- ----------------------------------------------------------------------------
-- * 외래키를 걸지 않는다
-- ----------------------------------------------------------------------------
--   이 원장은 <감사 기록>이라 장비 원장보다 오래 살아야 한다. 운영에서 장비를 목록에서 내리거나
--   교체하면 ls_ai_srvr 행이 사라지는데, 그때 RESTRICT 면 장비를 지울 수 없고 CASCADE 면 위탁
--   이력이 통째로 사라지며 SET NULL 이면 <어느 장비였는지가 조용히 지워진다>. 셋 다 이 컬럼의
--   목적(사후 추적)과 어긋난다. 참조 무결성 대신 「지워진 장비의 식별자가 그대로 남는다」를 택한다.
--
--   ⚠ 그 대가로 여기 남은 식별자가 현재 원장에 없을 수 있다. 읽는 쪽은 그것을 오류로 다루지 말 것
--     (부하 집계는 <현재 가용한 장비 목록>을 기준으로 세므로 없는 식별자는 자연히 빠진다).
--
-- ----------------------------------------------------------------------------
-- * 인덱스 — 장비별 부하 집계용
-- ----------------------------------------------------------------------------
--   집계는 위탁 <한 건마다> 돈다(장비를 고르는 순간). 이 표는 위탁 1건당 2행(묘사·추가 질문)씩
--   단조 증가하므로 전체 훑기로 두면 시간이 갈수록 느려진다. 기존 idx_..._ch_state 는 선두
--   컬럼이 채널이라 이 조회(srvr_id 로 좁힘)에 쓰이지 않는다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   서버 = SRVR (행안부) · 아이디 = ID (행안부). 신규 등록 없음.
--   도메인도 정본대로 「아이디 = 명V20」 -> varchar(20) 이며, 같은 값을 담는 ls_ai_srvr.srvr_id 와 동일하다
--   (두 표의 폭이 갈리면 긴 쪽 값이 저장 시점에 잘려 조용히 다른 장비가 된다).
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   nullable 컬럼 추가는 기본값이 없어 테이블을 다시 쓰지 않고, ACCESS EXCLUSIVE 를 순간만 잡는다.
--   구 jar 는 이 컬럼을 모르지만 <모르는 컬럼은 무시>하므로 롤링 재기동에 안전하다(V24 와 다르다 —
--   그쪽은 컬럼을 <지워서> 구 jar 의 매핑이 깨졌다).
--
-- ★ 롤백 절차 — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   되돌리면 어느 장비로 보냈는지가 사라진다(부하 집계가 전 장비 0이 되어 첫 장비로 몰린다).
--
--     DROP INDEX IF EXISTS idx_ls_webhook_idempotency_srvr_state;
--     ALTER TABLE ls_webhook_idempotency DROP COLUMN srvr_id;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '25';
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 커넥션의 search_path 가 정하고,
--     카탈로그 조회는 to_regclass 로 스코프해 조회 대상과 조작 대상을 같게 만든다.
-- ============================================================================

ALTER TABLE ls_webhook_idempotency ADD COLUMN IF NOT EXISTS srvr_id character varying(20);

CREATE INDEX IF NOT EXISTS idx_ls_webhook_idempotency_srvr_state
    ON ls_webhook_idempotency USING btree (srvr_id, stts_cd);

COMMENT ON COLUMN ls_webhook_idempotency.srvr_id IS
    'AI서버아이디 — 이 위탁을 보낸 AI 서버(장비) 식별자. 외부 시계열 분석 서버가 장비 두 대로 이중화되면서 장비별 부하를 세고 결과 출처를 되짚을 자리가 필요해졌다. ★부하로 세는 것은 수락된(ACCEPTED) 행뿐이다 — 발급(ISSUED)은 벤더가 아직 받지 않아 그 장비의 부하가 0이고, 세면 제출이 몰린 장비를 과대평가해 다음 요청이 반대편으로 쏠린다. ★nullable 이라 이 컬럼 도입 전 행과 장비를 고르지 못한 위탁은 장비 미상이다 — 그래서 미결 회수 스윕의 조회·클레임 조건에 장비 축을 걸지 않는다. 걸면 미상 행과 죽은 장비의 몫이 영영 회수되지 않는데, 그 스윕이 무증상 영구 결손을 막는 유일한 경로다. 외래키를 걸지 않는 것도 의도다 — 이 원장은 감사 기록이라 장비 원장보다 오래 살아야 하고, 장비 행이 지워져도 어느 장비였는지는 남아야 한다.';
