-- Phase 3 (CVAT-Like 라벨 풀 포팅): 라벨별 속성(Attribute) 정의 + 객체별 속성값 저장.
-- CVAT AttributeSpec 동등 구조 — 라벨마다 가려짐(yes/no), 방향(N/S/E/W) 등을 정의하고,
-- 라벨링된 객체(LS_DATA_LBL row) 단위로 속성값을 저장한다.
--
-- 비즈니스 규칙:
--   - LS_LABEL_ATTR: (LABEL_ID, ATTR_NM) UNIQUE — DB + Service 이중 가드.
--   - INPUT_TYPE_CD: SELECT / CHECKBOX / RADIO / NUMBER / TEXT (Service 레벨 검증).
--     SELECT/CHECKBOX/RADIO 는 VALUES_CN 필수 — 옵션 목록(JSON 배열) 보관.
--   - MUTABLE_YN='Y'(기본) 면 프레임마다 다른 값 허용, 'N' 이면 트랙 단위 고정.
--     (트랙 전파 강제는 본 Phase 범위 외 — 컬럼만 보유.)
--   - soft delete (USE_YN='N') — hard delete 금지. 객체 속성값 무결성 보호.
--
--   - LS_DATA_LBL_ATTR_VAL: (LBL_SN, ATTR_ID) UNIQUE — upsert 키.
--     LBL_SN → LS_DATA_LBL FK / ATTR_ID → LS_LABEL_ATTR FK.
--
-- H2/MariaDB 공통: BIGINT, VARCHAR(N), TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CONSTRAINT FK, UNIQUE KEY 모두 호환.

CREATE TABLE IF NOT EXISTS LS_LABEL_ATTR (
    ATTR_ID       BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    LABEL_ID      BIGINT        NOT NULL,
    ATTR_NM       VARCHAR(64)   NOT NULL,
    INPUT_TYPE_CD VARCHAR(16)   NOT NULL,
    VALUES_CN     VARCHAR(1000) NULL,
    DFLT_VL       VARCHAR(255)  NULL,
    MUTABLE_YN    VARCHAR(1)    NOT NULL DEFAULT 'Y',
    SORT_SEQ      INT           NOT NULL DEFAULT 0,
    USE_YN        VARCHAR(1)    NOT NULL DEFAULT 'Y',
    REG_ID        VARCHAR(30)   NULL,
    REG_DT        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MDFCN_ID      VARCHAR(30)   NULL,
    MDFCN_DT      TIMESTAMP     NULL,
    PRIMARY KEY (ATTR_ID),
    CONSTRAINT UK_LS_LABEL_ATTR_NAME UNIQUE (LABEL_ID, ATTR_NM),
    CONSTRAINT FK_LS_LABEL_ATTR_LABEL FOREIGN KEY (LABEL_ID) REFERENCES LS_LABEL(LABEL_ID)
);

CREATE INDEX IF NOT EXISTS IDX_LS_LABEL_ATTR ON LS_LABEL_ATTR (LABEL_ID, USE_YN, SORT_SEQ);

-- 주의: 컬럼명 ATTR_VL — H2 에서 VALUE 가 reserved keyword 이므로 회피한다.
-- (다른 마이그레이션의 LS_DATA_META.META_VL 패턴과 동일.)
CREATE TABLE IF NOT EXISTS LS_DATA_LBL_ATTR_VAL (
    ATTR_VAL_ID BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    LBL_SN      BIGINT        NOT NULL,
    ATTR_ID     BIGINT        NOT NULL,
    ATTR_VL     VARCHAR(1000) NULL,
    REG_DT      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MDFCN_DT    TIMESTAMP     NULL,
    PRIMARY KEY (ATTR_VAL_ID),
    CONSTRAINT UK_LS_DATA_LBL_ATTR_VAL UNIQUE (LBL_SN, ATTR_ID),
    CONSTRAINT FK_LS_DATA_LBL_ATTR_LBL FOREIGN KEY (LBL_SN) REFERENCES LS_DATA_LBL(LBL_SN),
    CONSTRAINT FK_LS_DATA_LBL_ATTR_ATTR FOREIGN KEY (ATTR_ID) REFERENCES LS_LABEL_ATTR(ATTR_ID)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DATA_LBL_ATTR_VAL_LBL ON LS_DATA_LBL_ATTR_VAL (LBL_SN);
