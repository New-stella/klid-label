CREATE TABLE IF NOT EXISTS LS_PORTAL_USER_LABEL (
    USER_LBL_SN     BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    PORTAL_USER_NO  VARCHAR(100)    NOT NULL,
    SOURCE_RAW_SN   BIGINT          NOT NULL,
    SOURCE_SRC_SN   BIGINT          NOT NULL,
    LBL_TYPE_CD     VARCHAR(16)     NOT NULL,
    LABEL           VARCHAR(255),
    POINTS          TEXT,
    CREATED_AT      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_LBL_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LPUL_USER ON LS_PORTAL_USER_LABEL (PORTAL_USER_NO, SOURCE_RAW_SN);
CREATE INDEX IF NOT EXISTS IDX_LPUL_SRC ON LS_PORTAL_USER_LABEL (PORTAL_USER_NO, SOURCE_SRC_SN);
