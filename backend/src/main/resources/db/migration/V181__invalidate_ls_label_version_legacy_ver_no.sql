-- V181: LS_LABEL_VERSION.VER_NO 의 옛 의미(프레임별 순번) 값 전량 무효화 (DML 전용)
--
-- V180 이 컬럼의 <의미>를 영상 단위 산출 버전 번호로 재정의했다. 이 스크립트는 그 이전 의미로
-- 적재된 값을 지운다. 스키마 변경은 없다.
--
-- ── 기존 행을 백필하지 않고 전량 NULL 로 <무효화>한다 (사용자 확정, 비가역) ──────
-- 옛 값을 그대로 두면 그것을 산출 회차로 읽는 순간 <엉뚱한 회차의 스냅샷>을 집어, 한 영상 안에
-- 서로 다른 시점의 프레임이 섞인 혼합본이 만들어진다 — 이 설계가 막으려는 바로 그 결함이다.
-- 옛 순번에서 새 회차를 역산할 방법도 없다(승인은 영상 단위인데 내용 무변경 프레임은 스냅샷이
-- 생기지 않아 프레임마다 번호가 밀렸고, 그 과정에서 정보가 이미 소실됐다). 값을 지어내는 대신
-- "모른다"를 정직하게 남긴다.
--
-- ── 왜 V180 과 한 파일에 두지 않았나 ─────────────────────────────────────────
-- 한 트랜잭션이면 V180 의 ALTER 가 잡은 ACCESS EXCLUSIVE 락이 이 UPDATE 가 끝날 때까지 유지되어
-- (PostgreSQL 은 락을 커밋 시점에 해제한다) 그 구간 동안 LS_LABEL_VERSION <조회까지> 막힌다.
-- 별도 스크립트 = 별도 트랜잭션이라 이 UPDATE 는 ROW EXCLUSIVE 락만 잡고 SELECT 를 막지 않는다.
--
-- ⚠ 운영 주의: 아래 UPDATE 는 <전 행 1회 rewrite> 다(그만큼 WAL 이 발생하고, 갱신 대상 행에
--   ROW EXCLUSIVE 락이 걸려 같은 행을 쓰는 승인 트랜잭션은 대기할 수 있다 — 조회는 대기하지
--   않는다). 이 테이블은 승인 스냅샷만 쌓이므로 규모가 크지 않다. 1회성이며 재실행되지 않는다
--   (Flyway 버전 마이그레이션).
--
-- ⚠ (DATA_SRC_SN, VERSION_HASH) UNIQUE 와 멱등 skip 로직은 건드리지 않는다 — 정상 동작이며,
--   P3 의 조회 규칙(VER_NO <= N 중 최대)이 그 위에서 성립한다.
--
-- 우리 소유 LS_* 테이블(관제 MNG_* 아님) — 협의 불요. PostgreSQL 표준 문법.
--
-- 롤백 SQL (V162 규약):
--   -- 값 복원은 불가능하다(옛 순번은 무효화되어 소실됨). 되돌릴 수 있는 것은 제약뿐이며,
--   -- 그 전문은 V180 의 롤백 주석에 있다.
--   ※ 이 롤백은 <이 마이그레이션 직후에만> 유효하다. P3 에서 채번이 배선된 뒤에는
--     "레거시 무효화로 생긴 NULL" 과 "아직 번호가 없는 정상 신규 NULL" 이 한 컬럼에 섞여
--     구분할 수 없으므로, 그때는 이 방식으로 되돌리면 안 된다(정상 신규 스냅샷까지 임의 값으로
--     덮게 된다).
-- =============================================================================

-- 옛 의미(프레임별 순번) 값 전량 무효화. 백필이 아니라 무효화다(위 근거 참조).
UPDATE LS_LABEL_VERSION SET VER_NO = NULL WHERE VER_NO IS NOT NULL;
