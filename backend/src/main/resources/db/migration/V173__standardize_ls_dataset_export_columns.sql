--
--   [@req R4 — 신설 컬럼]
--   · DATA_ETBL_CPCT BIGINT
--       데이터 DATA + 구축 ETBL + 용량 CPCT 가 <전부> 등록어이며, 사업표준용어 "데이터구축용량"의
--       표준도메인이 수B20(BIGINT)이라 타입·크기도 표준 그대로다. 관제 dataset_versions 의 동명
--       컬럼과 물리명이 일치해 양측이 같은 이름으로 같은 값을 말한다.
--       NULL 허용 — 용량 산출은 실패해도 export 자체는 성공으로 종결시킨다(용량 때문에 학습데이터
--       산출이 실패하면 안 된다). 이 변경 이전 행도 NULL 로 남으며 소급 백필하지 않는다.
--
-- ★ 테이블명 LS_DATASET_EXPORT 는 유지한다.
--   표준용어 규칙의 대상은 <새로 만드는> 테이블·컬럼이고, 테이블명 변경은 뷰 본문·JPA @Table·FK·
--   인덱스명까지 연쇄하는데 얻는 것이 없다. 컬럼 물리명만 정정한다.
--
-- ★ 제약·인덱스는 재생성하지 않는다 — <제약명 자체에 컬럼명이 없기> 때문이다.
--   PK 는 V105 에서 제약명을 지정하지 않아 자동명(ls_dataset_export_pkey)이고, UK 는
--   UK_LS_DATASET_EXPORT(DATA_RAW_SN, EXPORT_VER_NO) 인데 이름에 컬럼이 들어 있지 않다.
--   두 정의(참조 컬럼)는 RENAME COLUMN 을 PostgreSQL 이 추종해 자동 갱신한다. 별도 CREATE INDEX 는
--   이 테이블에 없다(V105 주석 — UK 복합 인덱스가 조회를 전부 커버).
--
-- ★ IDENTITY 시퀀스는 <자동으로 따라오지 않는다>.
--   EXPORT_SN 은 GENERATED BY DEFAULT AS IDENTITY 라 시퀀스가 자동명 ls_dataset_export_export_sn_seq
--   로 생성돼 있다(실DB 실측 확인). RENAME COLUMN 은 컬럼 정의만 바꾸고 시퀀스명은 그대로 두므로,
--   이름이 새 컬럼과 어긋난 채 남는다(동작에는 지장 없으나 운영 진단 시 오해를 부른다).
--   IF EXISTS 로 감싸 — 환경에 따라 자동명이 다를 수 있고, 없으면 조용히 넘어간다.
--
-- ⚠ 동명이표 주의 — 전역 치환 금지. 아래는 <다른 테이블>이며 이번 대상이 아니다.
--   · LS_MON_NOTI_ACML.EXPORT_RPRCS_YN (V144) — 현재 DB 에 실재하는 유일한 동명이표.
--   · LS_DATA_SET.EXPORT_SN / EXPORT_STTS_CD (V8) — 테이블은 V86 에서 DROP 됐으나 <과거
--     마이그레이션 SQL 원문>이 남아 있다. 전역 sed 로 그 파일까지 바뀌면 신규 설치의 Flyway
--     재생 자체가 어긋난다.
--   · LS_RESOLUTION_EXPORT.FRAME_CNT / RESL_EXPORT_SN (V55/V122/V123) — 마찬가지로 V126 DROP.
--   회귀 가드: V173DatasetExportStandardTermMigrationIT.
--
-- ★ 뷰(V_COMPLETED_VIDEO)의 <출력 컬럼명은 바뀌지 않는다> — 실측 확인.
--   PostgreSQL 은 RENAME COLUMN 시 뷰 <본문>만 새 컬럼으로 추종하고, 출력 컬럼명은 자동 별칭으로
--   보존한다. V160 본문 'e.EXPORT_PATH_NM' 은 'e.OUTPUT_PATH_NM AS export_path_nm' 이 되며,
--   관제가 SELECT 하는 이름(EXPORT_PATH_NM · FRAME_CNT · EXPORT_STTS_CD)은 그대로다.
--     실측: CREATE VIEW v AS SELECT old_name FROM t; ALTER TABLE t RENAME COLUMN old_name TO new_name;
--           → pg_get_viewdef = 'SELECT new_name AS old_name FROM t' (출력명 old_name 보존)
--   즉 이 마이그레이션은 <관제 연동 계약면(뷰 출력명)을 건드리지 않는다>. 뷰 출력명 정합은 후속
--   라운드의 뷰 명시 재작성이 담당하며, 뷰 DDL 은 여기서 손대지 않는다.
--   회귀 가드: V173DatasetExportStandardTermMigrationIT.뷰_출력컬럼명은_rename_을_따라가지_않는다
--
-- 무손실 rename + nullable 컬럼 추가 — 데이터 손실 0. 우리 소유 LS_* 테이블이라 관제팀 협의 불요.
