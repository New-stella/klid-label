-- 1. 물리명 정정 (@req R3)
ALTER TABLE LS_DATASET_EXPORT RENAME COLUMN EXPORT_SN      TO OUTPUT_SN;
ALTER TABLE LS_DATASET_EXPORT RENAME COLUMN EXPORT_PATH_NM TO OUTPUT_PATH_NM;
ALTER TABLE LS_DATASET_EXPORT RENAME COLUMN EXPORT_STTS_CD TO OUTPUT_STTS_CD;
ALTER TABLE LS_DATASET_EXPORT RENAME COLUMN EXPORT_VER_NO  TO OUTPUT_VER_NO;
ALTER TABLE LS_DATASET_EXPORT RENAME COLUMN FRAME_CNT      TO FRME_CNT;

-- 2. IDENTITY 자동 시퀀스명 정합 (@req R3) — 없으면 조용히 넘어간다.
ALTER SEQUENCE IF EXISTS ls_dataset_export_export_sn_seq RENAME TO ls_dataset_export_output_sn_seq;

-- 3. 데이터구축용량 신설 (@req R4)
ALTER TABLE LS_DATASET_EXPORT ADD COLUMN IF NOT EXISTS DATA_ETBL_CPCT BIGINT;

-- 4. 컬럼 설명 — 물리명이 바뀐 컬럼과 신설 컬럼의 의미를 원장에 남긴다.
COMMENT ON COLUMN LS_DATASET_EXPORT.OUTPUT_SN       IS '산출물일련번호(PK). (V173 개명 — 구 EXPORT_SN. EXPORT 는 표준 미등록이라 산출물=OUTPUT 표준단어로 정정)';
COMMENT ON COLUMN LS_DATASET_EXPORT.OUTPUT_PATH_NM  IS '산출물경로명 — <영상 루트>({dirname(원본)}/{rawSn})다. 버전 루트가 아니다: 관제가 한 경로 아래에서 v1·v2 를 모두 보고 골라야 비교·복구가 성립한다. (V173 개명 — 구 EXPORT_PATH_NM)';
COMMENT ON COLUMN LS_DATASET_EXPORT.OUTPUT_STTS_CD  IS '산출물상태코드. PENDING → SUCCEEDED|PARTIAL|FAILED. (V173 개명 — 구 EXPORT_STTS_CD)';
COMMENT ON COLUMN LS_DATASET_EXPORT.OUTPUT_VER_NO   IS '산출물버전번호(영상별 누적 건수+1). UK(DATA_RAW_SN, OUTPUT_VER_NO)로 동시 승인 중복 채번을 차단한다. (V173 개명 — 구 EXPORT_VER_NO)';
COMMENT ON COLUMN LS_DATASET_EXPORT.FRME_CNT        IS '산출 프레임수(원본벌+비식별벌 합계). (V173 개명 — 구 FRAME_CNT. 프레임=FRME 표준단어, LS_DATA_INGEST.FRME_CNT 와 약어 통일)';
COMMENT ON COLUMN LS_DATASET_EXPORT.DATA_ETBL_CPCT  IS '데이터구축용량 — 이 버전의 산출 폴더({영상루트}/v{n}) 총 바이트(관제 dataset_versions.data_etbl_cpct 공급). 산출 실패 시 NULL 이며 그때도 export 는 성공으로 종결한다. (V173 신설, @req R4)';
