--
--   [@req R3 — 물리명 5건]
--   · EXPORT_SN → OUTPUT_SN / EXPORT_PATH_NM → OUTPUT_PATH_NM
--     EXPORT_STTS_CD → OUTPUT_STTS_CD / EXPORT_VER_NO → OUTPUT_VER_NO
--       'EXPORT' 는 사업·공통 양쪽 <0건>이다. 산출물 = OUTPUT(공통표준단어)을 채택한다.
--       반출 SHPGOT 은 물류(선적) 의미라 부적합하고, 추출 EXTR 은 원천에서 뽑아내는 행위라
--       "폴더로 산출한다"는 이 도메인의 의미와 어긋난다.
--   · FRAME_CNT → FRME_CNT
--       'FRAME' 은 표준 미등록이고 프레임 = FRME (공통표준단어)다. 같은 이유로 V172 가
