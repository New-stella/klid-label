-- 기준: docs/requirements/final-clean/관제서버_DB_신규테이블_DDL.md §9
-- 해상도 유지(COORD_RECALC_YN='N')/저하(SCALE_X/Y 저장) 증강 시 좌표 재계산 정보 저장.
CREATE TABLE IF NOT EXISTS LS_DATA_AUG_LBL_MAP (
    DATA_AUG_LBL_MAP_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    DATA_AUG_SN BIGINT NOT NULL,
    ORGN_DATA_LBL_SN BIGINT NULL,
    DATA_LBL_SN BIGINT NOT NULL,
    COORD_RECALC_YN VARCHAR(1) NOT NULL DEFAULT 'N',
    SCALE_X DECIMAL(10,6) NULL,
    SCALE_Y DECIMAL(10,6) NULL,
    REG_ID VARCHAR(30) NULL,
    REG_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (DATA_AUG_LBL_MAP_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_LBL_MAP_AUG ON LS_DATA_AUG_LBL_MAP (DATA_AUG_SN);
CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_LBL_MAP_LBL ON LS_DATA_AUG_LBL_MAP (DATA_LBL_SN);
CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_LBL_MAP_ORGN ON LS_DATA_AUG_LBL_MAP (ORGN_DATA_LBL_SN);
