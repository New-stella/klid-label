-- ============================================================================
-- V20: LS_PORTAL_USER_LABEL 에 라벨마스터 참조(LBL_ID)와 트랙아이디(TRCK_ID)를 신설한다
--      @design ERD-018 · API-082 · API-203
--
--   LBL_ID    bigint                 NULL 허용
--   TRCK_ID   character varying(30)  NULL 허용
--
-- 포털 사용자가 데이터마트 영상의 작업 데이터를 내려받으면, 그 산출물이 검수 승인 학습데이터와
-- <다른 구조>로 나온다. 그 구조를 통일하기로 확정하면서(NIA COCO 확장) 원천 데이터의 공백이
-- 드러났다 — 산출 문서의 어노테이션은 <분류 식별자>와 <트랙 식별자>를 싣는데, 포털 저장소에는
-- 그 두 값을 담을 자리가 없다. 이 컬럼들이 그 자리다.
--
--   · LBL_ID  → 산출 어노테이션의 분류 식별자(category_id) 조달처. 라벨 마스터를 가리킨다.
--   · TRCK_ID → 산출 어노테이션의 트랙 식별자(track_id) 조달처.
--
-- 본인 저장분이 없어 데이터마트 원본으로 폴백되는 프레임은 이미 두 값을 갖고 있다. 즉 공백은
-- <포털 사용자가 직접 저장한 라벨>에만 있었고, 이 변경이 그 비대칭을 없앤다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (규칙 3 — 우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   <신규 등록이 필요 없다> — 두 물리명 모두 사업표준용어에 이미 등재돼 있다.
--
--     라벨아이디 = LBL_ID  / 도메인 식별자V50 / KLID-BM 표준용어정의서 (2026-05-28 배포)
--     트랙아이디 = TRCK_ID / 도메인 식별자V30 / KLID-BM 표준용어정의서 (2026-05-28 배포)
--
--   구성 단어도 전부 등재어다 — 라벨 LBL(사업) · 트랙 TRCK(사업) · 아이디 ID(공통 5차/사업).
--   행안부 공통표준<용어>에는 이 두 조합어가 없어 (2)사업표준으로 내려온 것이며, 우선순위를
--   거꾸로 적용한 것이 아니다.
--
--   ⚠ TRCK_ID 는 표준도메인 식별자V30 과 <정확히 일치>한다. character varying(30).
--
--   ⚠⚠ LBL_ID 는 표준도메인이 식별자V50(문자형)인데 이 컬럼은 <bigint> 다. <의도된 것이며
--      이 마이그레이션이 만드는 이탈이 아니다.> 이 컬럼이 가리키는 대상인 LS_LABEL.LBL_ID 가
--      bigint 이고, 같은 역할을 하는 LS_DATA_LBL.LBL_ID 도 bigint 다. 표준도메인을 따라
--      varchar(50) 으로 만들면 <참조 대상과 타입이 어긋나> 조인이 깨지고, 같은 값을 담는 두
--      테이블이 서로 다른 표현을 갖게 된다. 즉 표준을 따르는 쪽이 데이터 정합을 깨뜨린다.
--      기존 두 컬럼의 도메인 정합은 이 변경의 범위가 아니다(별도 백로그 — 고치려면 라벨 마스터
--      PK 표현 전환이라 전 도메인에 걸친다).
--
-- ----------------------------------------------------------------------------
-- * 왜 FK 를 걸지 않는가
-- ----------------------------------------------------------------------------
--   포털 전용 저장소는 내부 파이프라인과 <분리 운영>이다. FK 를 걸면 라벨 마스터가 비활성화·
--   삭제될 때 포털 사용자의 과거 작업이 함께 사라지거나 그 삭제가 막힌다. 둘 다 원하지 않는다 —
--   포털 사용자의 작업 결과는 마스터의 수명과 독립이어야 한다.
--   참조 무결성은 <조회 시점 join> 으로 처리하고, 매칭되지 않는 값은 미연결로 표시된다.
--
--   같은 이유로 인덱스도 만들지 않는다. 이 두 컬럼으로 검색·정렬하는 경로가 없다(조회는
--   포털사용자번호 + 영상/프레임 축으로만 한다 — idx_lpul_user · idx_lpul_src).
--
-- ----------------------------------------------------------------------------
-- * 왜 nullable 이고, 왜 기존 행을 백필하지 않는가
-- ----------------------------------------------------------------------------
--   두 값은 <선택>이다. 값 없이 저장된 라벨도 그대로 유효하며 산출물에서 해당 필드만 빈다.
--
--   기존 행은 <백필하지 않는다>. 이 컬럼 신설 이전에 저장된 라벨에는 마스터 연결 정보가 어디에도
--   없으므로 무엇을 넣어도 지어낸 값이다. 라벨명으로 소급 매칭하는 방법은 <채택하지 않았다> —
--   라벨명에는 유일성 제약이 없고 운영자가 바꿀 수 있어, 동명이인·비활성 마스터에 <다른 분류로>
--   연결될 수 있다. 잘못 연결된 분류는 산출물에 그대로 실려 나가므로 빈 값보다 나쁘다.
--   기존 행은 NULL 로 남고, 그 프레임을 <재저장하면 자연 복구>된다.
--
-- ----------------------------------------------------------------------------
-- * 멱등 · 두 경로 수렴
-- ----------------------------------------------------------------------------
--   IF NOT EXISTS 로 두 번 돌아도 안전하다.
--   · 신규 설치(빈 DB) : V1 이 이 두 컬럼 없이 테이블을 만들고 여기서 추가된다(no-op 이 아니다).
--     V1__baseline.sql 은 이미 적용된 이력이라 고치지 않는다(체크섬 불일치 = 전 노드 기동 실패).
--   · 기존 DB          : V19 까지 적용된 상태에서 여기서 추가된다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   ADD COLUMN <NULL 허용 + DEFAULT 없음> 은 PostgreSQL 11+ 에서 카탈로그만 고치므로 테이블
--   재작성이 없고 잠금은 순간이다.
--
--   ★ 이 변경은 <하위호환>이다. 컬럼이 생겨도 구 jar 노드는 그 컬럼을 모르는 SQL 을 만들 뿐이고
--     (엔티티 매핑에 없으므로 SELECT/INSERT 목록에 나타나지 않는다) 새 jar 노드만 쓰고 읽는다.
--     따라서 롤링 재기동으로 무중단 배포가 가능하고, 구 jar 로 되돌려도 컬럼이 남아 있을 뿐
--     아무것도 깨지지 않는다(그 사이 저장된 두 값이 읽히지 않을 뿐이다).
--
-- ★ 롤백 절차 (컬럼까지 되돌릴 때) — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   되돌릴 필요는 없다(하위호환). 그래도 지워야 한다면 <기록된 마스터 연결·트랙 정보가 함께
--   사라지며>, 그 프레임을 재저장하기 전까지 산출물의 해당 필드가 다시 빈다.
--
--     ALTER TABLE ls_portal_user_label DROP COLUMN lbl_id;
--     ALTER TABLE ls_portal_user_label DROP COLUMN trck_id;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '20';
--
-- ----------------------------------------------------------------------------
-- * 이번에 손대지 않는 것 (빠뜨린 것이 아니다)
-- ----------------------------------------------------------------------------
--   · 산출 구조 전환 자체 — 프레임별 산출 문서 생성은 애플리케이션 변경이다. 이 파일은 그 값을
--     담을 <자리>만 만든다.
--   · 기존 두 컬럼(LS_LABEL.LBL_ID · LS_DATA_LBL.LBL_ID)의 표준도메인 정합 — 위 표준용어 절 참조.
--   · LS_PORTAL_ULD_LBL(포털 <업로드 자산> 라벨) — 별개 저장소이고 데이터마트 산출 경로가 아니다.
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 커넥션의 search_path(기본 klid_at)가
--     정한다.
-- ============================================================================

ALTER TABLE ls_portal_user_label
    ADD COLUMN IF NOT EXISTS lbl_id bigint;

ALTER TABLE ls_portal_user_label
    ADD COLUMN IF NOT EXISTS trck_id character varying(30);

COMMENT ON COLUMN ls_portal_user_label.lbl_id IS
    '라벨아이디 — 이 라벨이 가리키는 라벨 마스터. 산출 어노테이션의 분류 식별자 조달처. 외래키를 걸지 않으며 조회 시점 join 으로 해석한다(미매칭은 미연결). 값이 없으면 NULL.';

COMMENT ON COLUMN ls_portal_user_label.trck_id IS
    '트랙아이디 — 산출 어노테이션의 트랙 식별자 조달처. 값이 없으면 NULL.';
