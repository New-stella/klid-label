CREATE TABLE LS_LABEL_PRESET (
  PRESET_ID    BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  NAME         VARCHAR(64)  NOT NULL,
  DESCRIPTION  VARCHAR(500) NULL,
  CREATED_AT   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (PRESET_ID),
  CONSTRAINT UK_LS_LABEL_PRESET_NAME UNIQUE (NAME)
);

CREATE TABLE LS_LABEL_PRESET_CODE (
  CODE_SN      BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  PRESET_ID    BIGINT       NOT NULL,
  CODE         VARCHAR(32)  NOT NULL,
  SORT_ORDER   INT          NOT NULL DEFAULT 0,
  PRIMARY KEY (CODE_SN),
  CONSTRAINT UK_LS_LABEL_PRESET_CODE UNIQUE (PRESET_ID, CODE),
  CONSTRAINT FK_LS_LABEL_PRESET_CODE_PRESET FOREIGN KEY (PRESET_ID) REFERENCES LS_LABEL_PRESET(PRESET_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_LS_LABEL_PRESET_CODE_PRESET ON LS_LABEL_PRESET_CODE (PRESET_ID);
