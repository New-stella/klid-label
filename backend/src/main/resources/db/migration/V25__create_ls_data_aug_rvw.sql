-- LS_DATA_AUG_RVW: 증강 데이터 검수 결과.
-- 기준: docs/requirements/final-clean/관제서버_DB_신규테이블_DDL.md §8
-- 증강 파일 생성 상태는 LS_DATA_AUG 에 두고 검수 결과는 본 테이블로 분리한다.
CREATE TABLE IF NOT EXISTS LS_DATA_AUG_RVW (
    DATA_AUG_RVW_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    DATA_AUG_SN BIGINT NOT NULL,
    DATA_RAW_SN BIGINT NOT NULL,
    DATA_SRC_SN BIGINT NOT NULL,
    RVW_STTS_CD VARCHAR(20) NOT NULL,
    LBL_INTGRT_PCT DECIMAL(5,2) NULL,
    REJECT_RSN VARCHAR(1000) NULL,
    RVW_ID VARCHAR(30) NULL,
    RVW_DT TIMESTAMP NULL,
    REG_ID VARCHAR(30) NULL,
    REG_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MDFCN_ID VARCHAR(30) NULL,
    MDFCN_DT TIMESTAMP NULL,
    PRIMARY KEY (DATA_AUG_RVW_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_RVW_AUG ON LS_DATA_AUG_RVW (DATA_AUG_SN);
CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_RVW_TARGET ON LS_DATA_AUG_RVW (DATA_RAW_SN, DATA_SRC_SN);
CREATE INDEX IF NOT EXISTS IDX_LS_DATA_AUG_RVW_STTS ON LS_DATA_AUG_RVW (RVW_STTS_CD);
