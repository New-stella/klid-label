-- ============================================================================
-- V21: 관리자 자격(비밀번호 해시)을 DB 로 옮긴다 — 단일 행  @design ADR-046 · API-069
--
--   ls_mngr_pswd   관리자비밀번호 (신규 테이블 · 행 1개)
--
-- 관리자 유효창은 지금까지 배포 설정에 박힌 공유 패스워드 해시로만 발급됐다. 그러면 자격을 바꾸는
-- 유일한 길이 <재배포> 라, 사람이 바뀌어도 자격이 그대로 남는다. 이 표가 그 자격을 데이터로
-- 옮겨 운영 중에 교체할 수 있게 하는 <저장 자리> 다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   관리자 = MNGR (행안부) · 비밀번호 = PSWD (행안부) · 일련번호 = SN (행안부)
--   수정자 = MDFR (행안부) · 비밀번호수정일시 = PSWD_MDFCN_DT (행안부)
--   비밀번호해시 = PSWD_HASH (사업표준 · 도메인 번호V100) -> varchar(100)
--
--   수정자아이디는 이 저장소의 기존 mdfr_id 와 같은 폭(30)을 쓴다.
--
-- ----------------------------------------------------------------------------
-- * ★ 단일 행 강제 — PK + CHECK 두 겹이 <함께> 있어야 성립한다
-- ----------------------------------------------------------------------------
--   운영자가 공유하는 자격은 <하나> 다. 행이 둘이 되면 어느 것이 현재 자격인지 판정할 수 없고,
--   그 판정을 애플리케이션이 "가장 최근 것" 같은 규칙으로 대신하기 시작하면 그 규칙이 곧 두 번째
--   진실원이 된다.
--
--   기본키만으로는 부족하다 — 값이 1, 2, 3 인 행이 나란히 설 수 있다.
--   CHECK 만으로도 부족하다 — 값이 전부 1 인 행을 여러 개 넣을 수 있다.
--   둘을 함께 걸어야 <행이 최대 1개> 가 된다.
--
-- ----------------------------------------------------------------------------
-- * ★ 세대·판수·버전 컬럼을 두지 않는다 (부재가 설계 결정이다)
-- ----------------------------------------------------------------------------
--   자격을 교체하면 그 전에 발급된 유효창은 무효가 되어야 한다. 그것을 세대 번호로 이루려면
--   토큰에 세대를 싣고 검증 때마다 현재 세대와 대조해야 하는데, 그러면 상태가 하나 늘고 그 상태가
--   토큰 형식과 결합한다.
--
--   대신 <서명이 현재 자격에 의존하게> 해서 같은 결과를 얻는다 — 자격이 바뀌면 과거 토큰의 서명이
--   더 이상 맞지 않아 자동으로 무효가 된다. 상태를 늘리지 않는다.
--   ⇒ 나중에 "무효화 세대가 필요하다" 는 생각이 들면, 그것은 이 결정을 되돌리는 것이다.
--
-- ----------------------------------------------------------------------------
-- * ★ 시드 행을 넣지 않는다 (폴백이 확정 동작이다)
-- ----------------------------------------------------------------------------
--   행이 없으면 배포 설정값으로 폴백한다. 그래서 이 마이그레이션은 <빈 표> 를 만들고 끝난다.
--   시드를 넣으면 그 순간 폴백 경로가 죽고, 넣을 값도 없다(해시는 사람이 정한 비밀번호에서 나온다).
--   기존 배포는 이 변경 이후에도 <설정값 그대로> 동작한다 — 행이 생기기 전까지 아무것도 바뀌지 않는다.
--
--   ⚠ 평문을 넣지 않는다. 이 컬럼은 해시만 담는다.
--
-- ----------------------------------------------------------------------------
-- * 멱등 · 두 경로 수렴
-- ----------------------------------------------------------------------------
--   CREATE TABLE IF NOT EXISTS + <제약은 카탈로그 조회 후 없을 때만 추가> 라 두 번 돌아도 안전하다.
--   ★ 카탈로그 조회는 conrelid = to_regclass(...) 로 <스코프> 한다. 스코프 없는 조회는 다른 스키마의
--     동명 객체를 보고 조작 대상과 조회 대상이 어긋난다(이 저장소에서 실제로 깨진 적이 있다).
--   · 신규 설치(빈 DB) : V1 이 이 표 없이 스키마를 만들고 여기서 추가된다.
--     V1__baseline.sql 은 이미 적용된 이력이라 고치지 않는다(체크섬 불일치 = 전 노드 기동 실패).
--   · 기존 DB          : V20 까지 적용된 상태에서 여기서 추가된다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   신규 테이블 생성뿐이라 기존 트래픽과 경합하지 않는다. 이 변경은 <하위호환> 이다 — 구 jar 노드는
--   이 표를 모르고 설정값 폴백으로 그대로 동작한다. 롤링 재기동으로 무중단 배포가 가능하다.
--
-- ★ 롤백 절차 — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   되돌리면 <운영 중에 교체한 자격이 사라지고> 배포 설정값으로 되돌아간다.
--
--     DROP TABLE ls_mngr_pswd;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '21';
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 커넥션의 search_path(기본 klid_at)가
--     정하고, 카탈로그 조회는 to_regclass 로 스코프해 조회 대상과 조작 대상을 같게 만든다.
-- ============================================================================

CREATE TABLE IF NOT EXISTS ls_mngr_pswd (
    mngr_pswd_sn smallint NOT NULL,
    pswd_hash character varying(100) NOT NULL,
    mdfr_id character varying(30),
    pswd_mdfcn_dt timestamp without time zone
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('ls_mngr_pswd') AND conname = 'ls_mngr_pswd_pkey'
    ) THEN
        ALTER TABLE ls_mngr_pswd ADD CONSTRAINT ls_mngr_pswd_pkey PRIMARY KEY (mngr_pswd_sn);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('ls_mngr_pswd') AND conname = 'ck_ls_mngr_pswd_single_row'
    ) THEN
        ALTER TABLE ls_mngr_pswd ADD CONSTRAINT ck_ls_mngr_pswd_single_row CHECK (mngr_pswd_sn = 1);
    END IF;
END $$;

COMMENT ON TABLE ls_mngr_pswd IS
    '관리자비밀번호 — 관리자 유효창 발급에 쓰는 공유 자격의 해시. ★행은 최대 1개다(기본키 + 일련번호를 1로 고정하는 체크 제약). 둘이 되면 어느 것이 현재 자격인지 판정할 수 없고, 그 판정을 애플리케이션이 대신하기 시작하면 그것이 두 번째 진실원이 된다. 행이 없는 것이 정상 상태이며 그때는 배포 설정값으로 폴백한다 — 그래서 시드하지 않는다. ★세대·판수 컬럼을 두지 않는다: 자격 교체 시 기존 유효창 무효화는 서명이 현재 자격에 의존하게 해서 이루므로 상태를 늘리지 않는다(부재가 설계 결정이다).';
COMMENT ON COLUMN ls_mngr_pswd.mngr_pswd_sn IS '관리자비밀번호일련번호 — 값이 1로 고정된다. 기본키와 체크 제약이 함께 걸려 있어야 「행 최대 1개」가 성립한다(기본키만 있으면 1·2·3이 나란히 서고, 체크만 있으면 값이 전부 1인 행이 여러 개 들어간다).';
COMMENT ON COLUMN ls_mngr_pswd.pswd_hash IS '비밀번호해시 — ★평문을 담지 않는다. 사업표준 도메인 번호V100.';
COMMENT ON COLUMN ls_mngr_pswd.mdfr_id IS '수정자아이디 — 마지막으로 자격을 교체한 사람. 공유 자격이라 「누가 지금 아는가」는 알 수 없고, 「누가 마지막으로 바꿨는가」만 남는다.';
COMMENT ON COLUMN ls_mngr_pswd.pswd_mdfcn_dt IS '비밀번호수정일시 — 마지막 교체 시각.';
