-- V15: 이벤트 유형·카테고리·라벨 마스터를 시드한다  @design DOMAIN-003 · DOMAIN-010
--
--   1) ls_evnt_ctgry  이벤트 카테고리 11종 (표시명의 원천)
--   2) ls_evnt_type   이벤트 유형     16종 (수집 15 + 비수집 폴백 1)
--   3) ls_label       라벨 마스터      9종
--
-- ----------------------------------------------------------------------------
-- * 왜 마이그레이션인가 — 온프렘(상용)에 이 세 표가 비어서 나가고 있었다
-- ----------------------------------------------------------------------------
--   같은 내용이 db/seed/dev-seed.sql 에 있었지만 그 파일은 <db/seed> 라 Flyway 가 읽지
--   않는다. 온프렘 배포 스냅샷(deploy/onprem/db/schema.sql)은 클린 DB 에 마이그레이션을
--   전량 적용한 뒤 뜬 pg_dump 이므로, 마이그레이션 밖의 시드는 실리지 않는다.
--   실측: 그 파일의 ls_label · ls_evnt_type 은 COPY 바로 뒤가 \. 인 <빈 표>였다.
--
--   그대로 설치하면 라벨 마스터 0건 · 이벤트 유형 0건으로 기동한다. 기동은 성공하고
--   화면에서 라벨을 고를 수 없고 이벤트 필터가 비어 있는 상태로만 드러난다 —
--   ddl-auto 검증이 이 저장소에서 무동작이라 시작 시점에는 아무 신호도 없다.
--   ls_system_config 12건이 V1 에 있어 정상적으로 실려 있는 것과 대비된다.
--
--   ⚠ deploy/onprem/scripts/seed-mng-event-type.sh 로 메우려 하지 말 것. 그 스크립트는
--     관제 MNG_EX_EVNT_TYPE* 에서 퍼오는데 그 표들은 이미 제거됐다(MNG_* 전면 정리).
--
-- ----------------------------------------------------------------------------
-- * 멱등 — 이미 시드된 DB(로컬·dev)에서는 아무것도 하지 않는다
-- ----------------------------------------------------------------------------
--   전부 ON CONFLICT DO NOTHING 이다. 로컬·dev 는 dev-seed 로 같은 내용이 이미 들어가
--   있으므로 이 마이그레이션은 no-op 으로 지나간다. 값을 <덮어쓰지 않는다> — 운영자가
--   라벨 관리 화면에서 이름·색·형태를 바꿨을 수 있고, 시드가 그것을 되돌리면 안 된다.
--
-- ----------------------------------------------------------------------------
-- * 이벤트 유형에 이름(evnt_nm)을 넣지 않는 것은 의도다
-- ----------------------------------------------------------------------------
--   관제 마스터에 유형별 이름이 애초에 없고 사람이 읽는 이름은 카테고리 레벨에만 있다.
--   그래서 표시명은 카테고리명으로 폴백하며, EV01000101/102/103 이 모두 '침수(범람)' 으로
--   보이는 것은 정상이다. 관제가 특정 유형에 이름을 보내기 시작하면 그 유형만 갈라진다.
--   운영자 표시명(optr_indct_nm)도 비운다 — 관리 화면에서 지정하는 값이다.
--
-- ----------------------------------------------------------------------------
-- * 라벨 형태 — 폴리곤은 셋뿐이다 (사용자 확정)
-- ----------------------------------------------------------------------------
--   화재·연기·침수만 POLYGON 이고 나머지는 BBOX 다. 경계가 불규칙해 사각형으로 감싸면
--   배경이 과하게 섞이는 대상만 폴리곤을 쓴다.
--
--   dtct_type_cd 는 AI 검출 클래스(COCO) 매핑이며 이 값이 있는 라벨만 오토라벨 대상이
--   된다. 폴리곤 3종은 COCO 에 대응 클래스가 없어 비운다 — 지어내면 엉뚱한 클래스의
--   검출 결과가 그 라벨로 귀속된다.
--   ⚠ 활성 라벨 1개 = COCO 클래스 1개 (uk_ls_label_dtct_type). 운영자가 이미 그 클래스를
--     다른 라벨에 배정했으면 ON CONFLICT 로 조용히 물러난다.
--
--   lbl_id 를 명시하지 않는다 — identity 가 발급한다. 이 값을 참조하는 것은 데이터
--   (프리셋·라벨 행)뿐이고 코드에 박힌 리터럴이 없어 번호를 고정할 이유가 없다.
--   ⚠ sort_seq 7 이 비어 있는 것은 의도다(dev 시드와 같은 배치를 유지한다).
-- ============================================================================

