-- ============================================================================
-- V29 — 포털 채널 전용 표를 공용 원장에 흡수하기 위한 스키마 정합  @design ADR-058, ERD-028
--
--   1) ls_data_raw   에 portal_user_no varchar(100) 신설  (되돌릴 수 있다)
--   2) ls_data_lbl.reg_user_no  bigint → character varying(100)  (되돌릴 수 있다)
--   3) ls_tus_upload.user_no    varchar(64) → varchar(100)        (되돌릴 수 있다)
--
--   ★ 구 전용 표(ls_portal_uld · _frme · _lbl · ls_portal_tus_uld)는 <지우지 않는다>.
--     드롭은 되돌릴 수 없어 별도 단계로 분리한다. 이 파일은 전부 순수 확장이라
--     구 jar 에 무해하고(추가된 칸을 안 읽을 뿐), 중간 상태도 멀쩡하다.
--     ⚠ V28 이 폭 확대와 컬럼 제거를 한 파일에 둔 것은 <중간 상태가 고장나서>였다.
--       여기는 그 전제가 없으므로 관례대로 나눈다.
--
-- ----------------------------------------------------------------------------
-- * 왜 이 셋인가 — 흡수 대응표 (ERD-028)
-- ----------------------------------------------------------------------------
--   ls_portal_uld       -> ls_data_raw      : 신설 컬럼 <소유자 하나>
--   ls_portal_uld_frme  -> ls_data_src      : 신설 컬럼 0 (공용 원장이 상위집합)
--   ls_portal_uld_lbl   -> ls_data_lbl      : 소유자는 기존 reg_user_no 를 쓴다(자료형 확대)
--   ls_portal_tus_uld   -> ls_tus_upload    : 사용자 식별자 폭 확대 하나
--   ls_portal_user_label-> ★흡수하지 않는다 (단방향 오버레이 — 라벨 원장에 합치면 원본을 덮어쓴다)
--
--   업로드 자산의 나머지 칸은 이미 있는 자리로 간다 — 파일 경로·등록/수정 일시는 원장 대응
--   컬럼, 원본 파일명/매체 유형/초당 프레임 수/파일 크기는 메타 원장(ls_data_meta)의
--   video.* 키, 업로드 처리 상태/실패 사유는 같은 원장의 portal.* 키, 프레임 수는 프레임
--   원장 행을 세어 얻는다. 자산 종류는 보관하지 않고 매체 유형에서 판정한다.
--   ⇒ 그래서 이 파일이 만드는 <새 컬럼은 소유자 하나>뿐이다.
--
-- ----------------------------------------------------------------------------
-- * 1) 왜 소유자 컬럼을 신설하나
-- ----------------------------------------------------------------------------
--   포털 자산은 인가가 전적으로 소유자 기반이라(본인 자산만 조회·수정·내려받기) 이 값 없이는
--   원장에 앉힐 수 없다. 관제 영상에는 소유자 개념이 없어 <비워 둔다> — 원장 안에서 항상
--   부분적으로만 채워진 컬럼이 하나 생기는 것은 인지하고 수용한 대가다(ADR-058).
--
--   물리명 portal_user_no 는 사업표준용어 <포털사용자번호 / PORTAL_USER_NO> 등록분이고,
--   폭 100 은 공통표준도메인 번호V100 이다(ls_marking.reg_user_no 와 같은 폭 — V28).
--
--   ★ 이 컬럼은 <보존기간 만료 자동 삭제의 판별자 셋 중 하나>다. 삭제 대상은
--     「출처 판별자 + 소유자 보유 + 보존기간 경과」를 동시에 충족해야 하며 하나만 빠져도
--     관제 영상을 지운다. 부분 인덱스가 그 조회를 받쳐 준다.
--
-- ----------------------------------------------------------------------------
-- * 2) 왜 라벨 등록자를 문자로 넓히나
-- ----------------------------------------------------------------------------
--   포털 업로드 라벨의 소유자는 <포털이 발급한 토큰의 주체 식별자>이고 숫자가 아니다.
--   숫자로 두면 파싱 실패로 조용히 null 이 되어 <소유자 없는 라벨>이 저장되고, 그 순간
--   소유자 스코프 조회가 남의 라벨을 함께 집거나 자기 라벨을 못 집는다.
--
--   ⚠ ERD-013(마킹)이 「라벨 원장의 같은 컬럼에 이미 같은 조치가 돼 있다」고 적었던 것은
--     사실이 아니었다 — 그 컬럼은 V28 시점까지 숫자였고 여기서 처음 넓힌다.
--
--   기존 행의 값은 숫자를 문자로 옮길 뿐이라 <무손실>이다(1001 -> '1001').
--
-- ----------------------------------------------------------------------------
-- * 3) 왜 재개 업로드 세션의 사용자 식별자를 넓히나
-- ----------------------------------------------------------------------------
--   같은 이유다. 다만 여기는 자료형이 이미 문자라 <폭만> 넓힌다(64 -> 100). 좁으면 서로
--   다른 사용자가 같은 값으로 잘려 세션 인가가 조용히 어긋난다.
--   ⚠ 폭 확대는 값을 자르지 않으므로 기존 행에 무해하다.
--
-- ----------------------------------------------------------------------------
-- * 데이터 이관을 여기 넣지 않는 이유
-- ----------------------------------------------------------------------------
--   구 표의 행을 공용 원장으로 옮기는 것은 <공용 영상 원장에 INSERT 하는 일>이라 되돌리려면
--   그 원장에서 지워야 한다. 그리고 옮긴 행의 모양(상태·실패사유 키의 값역, 클립 식별자 합성)이
--   맞았는지는 <그 모양을 읽는 코드가 있어야> 확인되는데 그 코드가 아직 없다. 스키마만 있는
--   지금 옮기면 검증할 수단 없이 공용 원장에 행을 넣는 셈이다.
--   ⇒ 이관은 코드 이관과 같은 묶음에서, 그 모양이 고정된 뒤에 한다.
--   (신규 설치는 애초에 옮길 행이 없다 — 온프렘은 Flyway 가 아니라 schema.sql 을 적재한다.)
--
-- ----------------------------------------------------------------------------
-- * 멱등성 / 의존성
-- ----------------------------------------------------------------------------
--   - ADD COLUMN / CREATE INDEX 는 IF NOT EXISTS 로 재실행 안전.
--   - 타입·폭 변경은 현재 형상을 확인한 뒤에만 실행한다(재실행 안전).
--     카탈로그 조회는 반드시 current_schema() 로 스코프한다 — 'public' 리터럴을 박으면
--     klid_at 에서 영원히 거짓이 되어 조용히 건너뛴다(V62/V63/V71 실사고).
--   - 두 컬럼을 참조하는 뷰는 없다. 참조되면 PostgreSQL 이 타입 변경 자체를 거부하므로
--     조용히 넘어가지 않는다.
--   - ls_data_lbl.reg_user_no 에 걸린 인덱스·제약은 없다(전수 확인).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) 영상 원장에 소유자 컬럼 신설
-- ----------------------------------------------------------------------------
ALTER TABLE ls_data_raw ADD COLUMN IF NOT EXISTS portal_user_no character varying(100);

COMMENT ON COLUMN ls_data_raw.portal_user_no IS
    '포털사용자번호 — 포털 채널이 발급한 토큰의 주체. 이 영상이 포털 사용자 본인 업로드 자산일 때만 채워지고 관제 인입 영상에는 비어 있다. 포털 경로의 인가는 전적으로 이 값 기반이며(본인 자산만 조회·수정·내려받기), 보존기간 만료 자동 삭제가 대상을 고를 때 쓰는 판별자 셋(출처유형·이 컬럼·보존기간 경과) 중 하나다. 하나만 빠뜨리면 관제 영상이 함께 지워진다. @design ADR-058, ERD-028';

-- 소유자 목록 조회(최신순)를 받치는 부분 인덱스 — 포털 자산에만 행이 들어가므로 관제 영상
-- 비중이 큰 원장에서 인덱스가 부풀지 않는다(흡수 전 idx_ls_portal_uld_user_reg 대응).
CREATE INDEX IF NOT EXISTS idx_ldr_portal_user_reg
    ON ls_data_raw (portal_user_no, reg_dt)
    WHERE portal_user_no IS NOT NULL;

-- ----------------------------------------------------------------------------
-- 2) 라벨 등록자: bigint -> varchar(100)
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name   = 'ls_data_lbl'
          AND column_name  = 'reg_user_no'
          AND data_type    = 'bigint'
    ) THEN
        -- bigint -> varchar 는 자동 캐스트가 없으므로 USING 이 필요하다.
        -- NULL 은 NULL 로 남는다(::text 가 NULL 을 그대로 전파).
        ALTER TABLE ls_data_lbl ALTER COLUMN reg_user_no TYPE character varying(100)
            USING (reg_user_no::text);
    END IF;
END $$;

COMMENT ON COLUMN ls_data_lbl.reg_user_no IS
    '등록사용자번호 — 이 라벨을 만든 사용자. 내부 채널에서는 작업자이고, 포털 업로드 자산의 라벨에서는 그 라벨의 소유자이자 인가 판정의 키라 반드시 채워진다. ★자료형이 숫자가 아니라 문자인 이유(V29): 포털이 발급한 토큰의 주체 식별자를 담아야 한다. 숫자로 두면 파싱 실패로 조용히 null 이 되어 소유자 없는 라벨이 저장된다. 폭 100 은 공통표준도메인 번호V100 이며 ls_marking.reg_user_no(V28)와 같다. @design ADR-058, ERD-028';

-- ----------------------------------------------------------------------------
-- 3) 재개 업로드 세션 사용자 식별자: varchar(64) -> varchar(100)
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name   = 'ls_tus_upload'
          AND column_name  = 'user_no'
          AND character_maximum_length < 100
    ) THEN
        -- 폭 확대는 값을 자르지 않으므로 USING 없이 안전하다.
        ALTER TABLE ls_tus_upload ALTER COLUMN user_no TYPE character varying(100);
    END IF;
END $$;

COMMENT ON COLUMN ls_tus_upload.user_no IS
    '사용자번호 — 재개 업로드 세션의 소유자. 소유자만 진행 상태 조회·이어올리기·취소를 할 수 있다. ★폭이 100 인 이유(V29): 포털 채널 세션이 이 원장을 함께 쓰며 포털 토큰 주체 식별자를 담아야 한다. 좁히면 서로 다른 사용자가 같은 값으로 잘려 세션 인가가 조용히 어긋난다. 공통표준도메인 번호V100. @design ADR-058, ERD-028';
