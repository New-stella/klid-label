-- V13: 추론 입력 해상도 설정 키(YOLO_IMGSZ)를 폐지한다  @design SCREEN-025  @design UC-031
--
--   DELETE ls_system_config WHERE stng_key = 'YOLO_IMGSZ'   (V1 baseline 시드 1행)
--
-- 이 키는 <조정해도 아무것도 바뀌지 않는 설정>이었다. ai-server 의 YOLOX 로더가 입력 크기를
-- _DEFAULT_INPUT_SIZE = (640, 640) 으로 고정해 추론하므로, 요청 바디에 실린 imgsz 는 로그에만
-- 남고 추론 경로에 반영되지 않는다. 그런데 운영 화면(시스템 설정 > AI 탐지 추론 파라미터)에는
-- 320~1920 범위의 입력칸으로 노출돼 있어, <검출 정밀도가 오르지 않을 때 운영자가 원인을 이
-- 값에서 찾게 만드는> 잘못된 조작면이었다.
--
-- 화이트리스트(ConfigKeys.ALLOWED)에서 키를 뺐으므로 이 행이 남아 있어도 조회·수정 경로는 이미
-- 닫힌다. 그럼에도 행을 지우는 이유는 <설정 목록 조회가 화이트리스트로 필터링만 할 뿐 행 자체는
-- 계속 들고 있어>, 다음 사람이 DB 를 열어 보고 "화면에 없는 설정이 있다"고 오해하기 때문이다.
-- 죽은 행을 남기지 않는다.
--
-- ----------------------------------------------------------------------------
-- * 왜 V1__baseline.sql 의 INSERT 를 지우지 않고 별도 DELETE 를 두는가
-- ----------------------------------------------------------------------------
--   V1 은 이미 적용된 마이그레이션이라 내용을 고치면 체크섬이 달라져 <전 노드가 기동에 실패>한다
--   (조용한 손상이 아니라 즉시 실패). 스키마 변경은 항상 새 버전 파일로만 한다.
--
--   그래서 신규 설치는 "V1 이 넣고 V13 이 지우는" 왕복을 한 번 하게 된다. 왕복 비용은 1행이고,
--   대안(V1 수정)은 기존 DB 를 전부 못 뜨게 만든다 — 비교 대상이 아니다.
--
-- ----------------------------------------------------------------------------
-- * 되살리려면 무엇을 먼저 해야 하나
-- ----------------------------------------------------------------------------
--   <ai-server 가 요청받은 입력 크기를 실제로 쓰도록 먼저 고쳐야 한다.> 그 전에 키만 되돌리면
--   같은 결함(조정해도 안 바뀌는 설정)이 그대로 재발한다. 되살리기 방지 가드는
--   ConfigKeysTest.imgszKeyIsNotConfigurable() 이며, 키를 다시 등록하면 그 테스트가 깨진다.
--
--   ⚠ ai-server 요청 규격의 imgsz <필드 자체는 폐지하지 않았다>. 호출부(YoloAutolabelStep ·
--     AutolabelOnlineService · YoloTrackService)가 상수 DEFAULT_IMGSZ(1280)를 계속 싣는다.
--     바뀐 것은 "운영자가 조정할 수 있는가" 하나뿐이며 외부 요청 형태는 무변경이다.
--
-- ----------------------------------------------------------------------------
-- * 멱등성
-- ----------------------------------------------------------------------------
--   DELETE 는 대상이 없어도 성공한다(영향행수 0). 이 키를 한 번도 시드하지 않은 DB 에서도 안전.
-- ============================================================================

DELETE FROM ls_system_config WHERE stng_key = 'YOLO_IMGSZ';
