-- =============================================================================
-- V34 — 멱등 원장에 「보낸 질문 문구」 칸 신설
--       @design ERD-021 · INTSPEC-003 · INT-002 · CDIAG-013
--
--   ls_webhook_idempotency.qstn_cn  varchar(4000) NULL  (질문내용)
--
-- -----------------------------------------------------------------------------
-- * 왜 이 칸이 필요한가 (CO-20260907-VLM연동규격-v120-정합)
-- -----------------------------------------------------------------------------
--   외부 시계열 분석 사업자가 추가 질문 축의 창구를 바꾸라고 안내했다. 새 창구는 이벤트 유형을
--   받지 않고 <질문 문구를 요청 본문에 직접> 싣는다. 그 문구는 저작도구가 검증 이벤트 유형별로
--   보관하는 값이다.
--
--   종전에는 그 문구를 <결과를 받은 뒤에만> 조달해 이벤트 어노테이션의 질문 칸을 채웠다.
--   이제는 <위탁하는 시점>의 값이 실제로 사업자에게 나간 값이 된다.
--
--   ★ 그런데 질문 목록은 <전체 교체>로 저장되고, 가리키던 행이 사라지는 것이 정상 동선이다.
--     그래서 결과 수신 시점에 다시 조달하면 <보낸 질문과 기록된 질문이 갈린다>.
--     이 창구 전환의 핵심 이득이 바로 그 자리에서 무너진다.
--
--   → 위탁 시점에 조달한 문구를 이 칸에 보관하고, 결과 수신 시에는 재조달하지 않고 이 값을 읽는다.
--     결과 수신부는 이미 요청 식별자로 이 원장 행을 역조회하므로 보관 자리로 자연스럽고,
--     재위탁·도착순서 문제가 구조적으로 해결된다(위탁 1건 = 원장 1행).
--
--   ⚠ 질문 <식별자>가 아니라 <문구 전문>을 보관한다. 식별자만 두면 그 행이 사라졌을 때
--     다시 읽을 수 없어 보장이 성립하지 않는다.
--   ⚠ 인지·수용한 대가 — 이 원장은 본래 중복 판정용인데 <업무 값>이 한 종류 섞인다.
--
-- -----------------------------------------------------------------------------
-- * 표준용어·표준도메인 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- -----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 했다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   qstn_cn  <- 행안부 공통표준용어 「질문내용 = QSTN_CN」, 표준도메인 「내용V4000」
--               구성 단어도 둘 다 공통표준단어다 — 질문 QSTN / 내용 CN.
--               ★ 신규 용어 등록 불필요 — 이미 공통표준에 있다.
--
--   같은 저장소의 기존 칸 ls_vrfc_evnt_qstn.qstn_cn 이 varchar(4000) 으로 동일하고,
--   사업자 요청 본문의 질문 문구 상한(4,000자)과도 정확히 일치한다.
--
-- -----------------------------------------------------------------------------
-- * 되돌리기
-- -----------------------------------------------------------------------------
--   nullable 이라 되돌리지 않아도 무해하다. 드롭 마이그레이션을 만들지 않는다
--   (되돌릴 수 없는 작업을 한 묶음에 넣지 않는 관례 — ls_meta_repl_outbox 선례).
-- =============================================================================

ALTER TABLE ls_webhook_idempotency
    ADD COLUMN IF NOT EXISTS qstn_cn varchar(4000);

COMMENT ON COLUMN ls_webhook_idempotency.qstn_cn IS
    '질문내용 — 위탁 시점에 외부 분석 서버로 보낸 질문 문구 전문. 결과 수신 시 재조달하지 않고 이 값을 읽어 이벤트 어노테이션의 질문 칸을 채운다(질문 목록이 전체 교체로 저장되어 재조달하면 보낸 질문과 기록된 질문이 갈리기 때문). 묘사 축 위탁 행에는 값이 없다.';
