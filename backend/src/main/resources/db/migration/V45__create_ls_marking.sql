CREATE TABLE IF NOT EXISTS LS_MARKING (
    MARKING_SN BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    RAW_SN     BIGINT       NOT NULL,
    EVENT_NAME VARCHAR(100) NOT NULL,
    MARKING_MODE VARCHAR(16) NOT NULL,
    INTERVAL_SEC INT,
    VIDEO_PATH VARCHAR(500) NOT NULL,
    MARKS      TEXT         NOT NULL,
    STATUS     VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MARKING_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LM_RAW ON LS_MARKING (RAW_SN);
