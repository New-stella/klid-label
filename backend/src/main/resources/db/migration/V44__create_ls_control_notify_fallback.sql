-- Phase 2: 관제서버 outbound 통지 fallback 큐 (TASK_COMPLETED / TASK_MODIFIED).
-- LS_GITEA_FALLBACK_QUEUE 패턴 동일 — 영속 백킹 스토어 + dead-letter.

CREATE TABLE LS_CONTROL_NOTIFY_FALLBACK (
    QUEUE_SN       BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    IDEMPOTENCY_KEY VARCHAR(64)  NOT NULL,
    EVENT_TYPE     VARCHAR(32)   NOT NULL,
    RAW_SN         BIGINT        NOT NULL,
    PAYLOAD        TEXT          NOT NULL,
    RETRY_COUNT    INT           NOT NULL DEFAULT 0,
    MAX_RETRY      INT           NOT NULL DEFAULT 5,
    STATUS         VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    LAST_ERROR     VARCHAR(2000),
    NEXT_RETRY_AT  TIMESTAMP,
    DEAD_LETTER_AT TIMESTAMP,
    CREATED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (QUEUE_SN),
    CONSTRAINT UK_LCNF_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY)
);

CREATE INDEX IDX_LCNF_STATUS ON LS_CONTROL_NOTIFY_FALLBACK (STATUS, NEXT_RETRY_AT);
