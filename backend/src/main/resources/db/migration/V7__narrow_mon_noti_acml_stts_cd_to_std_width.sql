-- ============================================================================
-- V7: LS_MON_NOTI_ACML.STTS_CD 를 표준도메인 폭(16)에 맞춘다  @req R2  @design ERD-027
--
--   character varying(20) → character varying(16)
--
-- 설계 진실원(ERD-027)은 이미 이 컬럼을 16 으로 확정했고, 여기서는 그 사양을 DB 에 반영한다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (규칙 3 — 우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   (1) 물리명 — 행안부 공통표준<단어> 상태 = STTS · 코드 = CD.
--       STTS_CD 는 이미 표준 조합이라 <이름은 바꾸지 않는다>. 어긋나 있던 것은 폭뿐이다.
--
--   (2) 폭 — 행안부 공통표준<용어>에는 「상태코드」 단독 용어가 <없다>(STTS 를 쓰는 용어 31건은
--       전부 「…상태명 = …STTS_NM / 명V300」 계열이다). 따라서 우선순위 규칙의 (1)행안부 조항이
--       개입하지 않고 (2)사업표준이 적용된다.
--         사업표준용어 「상태코드 = STTS_CD」 : 데이터타입 V · 길이 16 (출처 KLID-저작도구 ERD-013)
--       즉 남의 사전을 우회하는 상황이 아니라 <우리가 등록한 값을 우리가 어기고 있던> 상황이다.
--
--   V5 가 같은 폭으로 형제 두 테이블의 상태코드를 맞췄다
--   (LS_CLIP_SCHEDULE_QUE.STTS_CD · LS_META_REPL_OUTBOX.STTS_CD). 이 테이블만 20 으로 남아
--   같은 개념이 스키마 안에서 두 폭을 갖고 있었다.
--   (참고 — V5 헤더는 이 16 의 출처를 "공통표준용어"라고 적었으나 CSV 정본 대조 결과 사업표준용어다.
--    값 16 은 동일하다. 이미 적용된 마이그레이션은 체크섬 때문에 수정할 수 없어 여기에 남긴다.)
--
-- ----------------------------------------------------------------------------
-- * 왜 fail-closed 인가 — 조용히 자르지 않는다
-- ----------------------------------------------------------------------------
--   PostgreSQL 은 폭을 줄일 때 초과 값이 있으면 스스로 오류를 내지만, 그 원문
--   (value too long for type character varying(16))만으로는 <무엇이 몇 건> 걸렸는지 알 수 없다.
--   대상·목표 폭·초과 건수·최장 길이를 담은 사유로 중단시켜 사람이 바로 조치할 수 있게 한다.
--
--   초과한 <값 자체>는 메시지에 싣지 않는다 — 로그로 새어 나간다(CWE-209).
--
--   애플리케이션이 쓰는 값은 PENDING(7자) · FLUSHING(8자) 둘뿐이라 정상 DB 에서는 걸릴 것이 없다.
--   그럼에도 가드를 두는 이유는 이 마이그레이션을 작성한 시점에 <일부 환경의 실데이터를 확인할 수
--   없었기> 때문이다. 확인하지 못한 것을 "없을 것"으로 가정하고 자르면 그 윈도우는 어느 상태로도
--   해석되지 않아 영영 flush 되지 않는다(통지·재생성 영구 소실).
--
-- ----------------------------------------------------------------------------
-- * 부속 객체 — 함께 확인할 것
-- ----------------------------------------------------------------------------
--   ALTER ... TYPE 은 DEFAULT 'PENDING' · NOT NULL 을 유지하고, 이 컬럼을 물고 있는 인덱스 3종
--   (IDX_LMNA_STTS_REG · IDX_LMNA_STTS_MDFCN · 부분 유니크 UK_LMNA_RAW_PENDING)을 자동 재구축한다.
--   특히 부분 유니크는 <술어>에 이 컬럼이 있어(WHERE STTS_CD = 'PENDING') 술어가 무너지면
--   "영상당 열린 윈도우 1개" 불변식이 조용히 깨진다. 그래서 정의 문자열이 아니라 실제 강제 여부까지
--   테스트로 고정한다 (V7MonNotiAcmlSttsWidthGuardIT · V7MonNotiAcmlSttsWidthIT).
--
-- ----------------------------------------------------------------------------
-- * 이번에 손대지 않는 것 (빠뜨린 것이 아니다)
-- ----------------------------------------------------------------------------
--   · 접두형 *_STTS_CD 컬럼들(varchar(20)) — 그중 일부는 데이터마트 뷰(V_COMPLETED_*)의 출력
--     컬럼이라 관제서버가 직접 SELECT 하는 <외부 계약면>이다. 폭을 건드리면 협의 대상이 된다.
--     별도 라운드에서 뷰 계약과 함께 다룬다.
--   · 이 테이블의 다른 컬럼 · 테이블명 · 인덱스 이름 — 컬럼 폭 축이 아니다(별건).
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 klid_at 이며, 카탈로그 조회는
--     current_schema() / to_regclass 로 스코프하고 식별자는 비한정으로 둔다 — 그래야 조회 대상과
--     조작 대상이 반드시 같은 스키마가 된다.
-- ============================================================================

DO $$
DECLARE
    tbl      CONSTANT text := 'ls_mon_noti_acml';
    col      CONSTANT text := 'stts_cd';
    tgt_len  CONSTANT integer := 16;
    cur_len  integer;
    over_cnt bigint;
    max_len  integer;
BEGIN
    IF to_regclass(tbl) IS NULL THEN
        RAISE NOTICE '% 가 없다 → no-op', tbl;
        RETURN;
    END IF;

    SELECT character_maximum_length INTO cur_len
      FROM information_schema.columns
     WHERE table_schema = current_schema()
       AND table_name = tbl AND column_name = col;

    -- 컬럼 부재 또는 이미 목표 폭 → no-op(재실행 시 테이블 재작성을 일으키지 않는다).
    IF cur_len IS NULL OR cur_len <= tgt_len THEN
        RETURN;
    END IF;

    EXECUTE format('SELECT count(*), coalesce(max(length(%I)), 0) FROM %I WHERE length(%I) > %s',
                   col, tbl, col, tgt_len)
       INTO over_cnt, max_len;

    IF over_cnt > 0 THEN
        RAISE EXCEPTION
            '%.% 를 %자로 줄일 수 없다 — 초과 행 %건(최장 %자). 조용히 자르면 상태값이 훼손되어 '
            '그 윈도우가 영영 flush 되지 않으므로 중단한다. 해당 행을 확인해 정리한 뒤 재기동하라.',
            tbl, col, tgt_len, over_cnt, max_len;
    END IF;

    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I TYPE character varying(%s)', tbl, col, tgt_len);
    RAISE NOTICE '표준도메인 폭 정합: %.% → varchar(%)', tbl, col, tgt_len;
END $$;
