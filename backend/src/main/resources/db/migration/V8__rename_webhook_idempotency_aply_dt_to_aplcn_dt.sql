-- ============================================================================
-- V8: LS_WEBHOOK_IDEMPOTENCY.APLY_DT 를 APLCN_DT 로 개명한다  @req R2  @design ERD-021
--
--   APLY_DT(신청일시) → APLCN_DT(적용일시)
--
-- 이 컬럼이 담는 값은 markProcessed 시점, 즉 <콜백 처리 완료(PROCESSED)를 원장에 반영한 시각>이다.
-- 뜻은 「적용」인데 물리명은 「신청」의 표준 약어를 쓰고 있었다. 논리명은 처음부터 '적용일시'였으므로
-- <논리명은 그대로 두고 물리명만> 뜻에 맞는 표준 약어로 바로잡는다.
--
-- 설계 진실원(ERD-021 · CDIAG-013)은 이미 APLCN_DT / aplcnDt 로 확정됐고, 여기서는 그 사양을
-- DB 에 반영한다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (규칙 3 — 우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   행안부 공통표준<단어>  : 신청 = APLY  /  적용 = APLCN   (둘 다 등록. 서로 다른 낱말이다)
--   행안부 공통표준<용어>  : 신청일시 = APLY_DT  /  적용일시 = APLCN_DT   (<둘 다> 등록돼 있다)
--
--   즉 이것은 "표준에 없어서 비슷한 것을 빌려 쓴" 상황이 아니다. <뜻이 다른 두 표준용어가 나란히
--   등록돼 있는데 그중 틀린 쪽을 골라 쓰고 있던> 상황이라, 물리명만 보고 읽는 사람에게 이 컬럼은
--   「무언가를 신청한 시각」으로 읽힌다. 감리 지적 대상이자 의미 오독의 원인이다.
--
--   ⚠ 우선순위 규칙상 (1)행안부에 「적용일시 = APLCN_DT」가 있으므로 여기서 판정이 끝난다.
--     (2)사업표준은 행안부에 <없는 개념>을 채우는 보충이며, 있는 개념을 덮어쓰는 자리가 아니다.
--
--   ⚠ <이 스키마에 「적용일시」 개념의 선례는 없다> — 실측: APLCN 을 쓰는 컬럼 0개, APLY 를 쓰는
--     컬럼은 이것 하나뿐이다(V1 베이스라인 · deploy/onprem/db/schema.sql 전수 조회). 즉 이 개명은
--     "형제를 따라 맞추는 것"이 아니라 <이 스키마에서 APLCN 을 처음 쓰는 것>이며, 근거는 오직 위
--     행안부 표준용어 대조다. 형제 선례를 근거로 들 수 없으니 표준 대조를 근거로 남긴다.
--     (LS_DEIDENT_PROC_LOG 가 이미 DE_IDNTF_APLCN_DT 를 쓴다는 서술이 있으나 <사실이 아니다> —
--      그 테이블의 일시 컬럼은 REQ_DT·RSPNS_DT·PRCS_BGNG_DT 등이고 APLCN 컬럼은 없다.)
--
-- ----------------------------------------------------------------------------
-- * 사업표준용어 사전의 override 행은 여기서 건드리지 않는다 (별건 · 사용자 판정 대기)
-- ----------------------------------------------------------------------------
--   사업표준<용어>에 「적용일시 = APLY_DT」가 <우리 프로젝트 출처(KLID-저작도구 ERD-021)>로 등록돼
--   있고, 그 설명이 "gov 표준 APLY_DT=신청일시와 약어 충돌하나 우리 의미는 적용일시라 override 등록"
--   이라고 <충돌을 인지한 채> 적혀 있다. 그러나 행안부에 「적용일시 = APLCN_DT」가 <이미 있으므로>
--   그 override 는 애초에 성립하지 않는다 — 없는 개념을 채운 것이 아니라 있는 개념을 다른 약어로
--   덮어쓴 것이기 때문이다.
--
--   ⚠ 그 사전 행의 정리(폐기 또는 APLCN_DT 로 정정)는 <이 마이그레이션의 범위가 아니다>.
--     사전은 관제서버·포털과 공유하는 자산이라 우리 판단만으로 고치지 않는다(소유권 규칙).
--     여기서 확정되는 것은 <우리 컬럼명>이며, 사전 정합은 별도 축이다.
--     (V5 헤더가 PAYLOAD_CN 에 대해 "우리 컬럼명은 확정, 사전 정합은 별건"이라 적은 것과 같은 구도.)
--
-- ----------------------------------------------------------------------------
-- * 왜 RENAME 인가 — 재생성·DROP+ADD 금지
-- ----------------------------------------------------------------------------
--   이 원장은 <미결 위탁의 상관키 저장소>다. 행이 사라지면 이미 발급된 request_id 가 사라져
--   ①뒤늦게 도착한 콜백이 발급 게이트를 통과하지 못하고(인증 거부) ②미결 스위퍼가 회수할 대상을
--   잃어 그 영상의 시계열 메타가 영구 결손된다. DROP+ADD 면 APLY_DT 값도 함께 사라진다.
--   RENAME COLUMN 은 카탈로그만 고치므로 값·PK·인덱스·FK·컬럼 순서를 전부 보존한다.
--
-- ----------------------------------------------------------------------------
-- * fail-closed — 두 이름이 동시에 있으면 중단한다
-- ----------------------------------------------------------------------------
--   폭 축소(V5·V7)와 달리 개명에는 <값이 잘릴 위험이 없다>. 대신 이 파일이 막아야 할 것은
--   <어느 컬럼이 진짜인지 알 수 없는 형상>이다 — 두 이름이 동시에 존재하면 수기 조작이나 실패한
--   부분 적용의 흔적이며, 그대로 두면 애플리케이션은 APLCN_DT 만 보고 APLY_DT 에 남은 값은
--   <아무도 읽지 않는 채로 사라진다>. RENAME 자체도 duplicate column 오류로 실패하지만 그 원문만으로는
--   무엇을 조치해야 하는지 알 수 없으므로, 사람이 바로 판단할 수 있는 사유로 중단시킨다.
--
--   ⚠ 사유에는 <컬럼 이름과 상태>만 싣는다. 원장 값(idmp_key 는 외부 상관키다)은 싣지 않는다(CWE-209).
--
-- ----------------------------------------------------------------------------
-- * 두 경로가 수동 개입 없이 같은 결과로 수렴한다
-- ----------------------------------------------------------------------------
--   · 신규 설치(빈 DB)  : V1 이 <옛 이름으로> 이 테이블을 만들고 여기서 개명된다.
--     V1__baseline.sql 은 이미 적용된 이력이라 고치지 않는다(체크섬 불일치 = 전 노드 기동 실패).
--     그래서 신규 설치도 기존 DB 와 <같은 순서>를 탄다(no-op 이 아니다).
--   · 기존 DB(로컬·dev) : V7 까지 적용된 상태에서 여기서 개명된다.
--   두 번 돌아도 안전하다 — 이미 새 이름이면 no-op 이고, 테이블 자체가 없으면 완전 no-op 이다.
--
-- ★ 카탈로그 조회는 <현재 스키마로 스코프>를 건다 (V1 헤더 「규칙 2」)
--   to_regclass 는 search_path 로, information_schema 조회는 current_schema() 로 스코프한다.
--   'public' 리터럴은 쓰지 않는다 — klid_at 운영에서 전부 오판정이 된다(실사고 이력 V62·V63·V71).
--   동적 SQL 의 식별자는 전부 format('%I') 로 인용한다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   잠금은 순간이다 — RENAME COLUMN 은 카탈로그만 고치므로 테이블 재작성이 없다.
--
--   ⚠ 문제는 잠금 시간이 아니라 <전진 창>이다. 이 개명은 <하위호환이 아니다>. 스키마에 V8 이 적용된
--     뒤에도 아직 구 jar 인 노드는 APLY_DT 로 SQL 을 만들므로 이 원장을 쓰는 경로가 실패한다
--     (오류 `column "aply_dt" does not exist`).
--
--   ⚠ <영향 경로는 둘이며 읽기 축만이 아니다> — 아래 ②를 빠뜨리면 창의 대가를 과소평가하게 된다.
--     (1) 웹훅 콜백 처리 : VlmResultService 가 markProcessed 로 원장을 갱신하는 지점.
--     (2) <위탁 제출>    : VlmTimeseriesStep 이 외부 호출 직전에 recordIssued 로 상관키를 적재하는
--         지점. 엔티티에 @DynamicInsert 가 없어 Hibernate INSERT 가 전 컬럼을 명시하므로 여기서도
--         깨진다. 그 실패는 CustomException 으로 승격되어 <파이프라인이 FAILED 로 전이>한다 —
--         즉 (1) 처럼 가용성만 잃는 것이 아니라 상태 전이와 재시도 예산까지 소모한다.
--         진입점은 구 jar 노드에서 도는 잔여 배치다(마킹 완료 이벤트 · 배치 재처리).
--
--   ★ 데이터는 잃지 않는다 — 실패는 트랜잭션 롤백이라 부분 기록이 남지 않고, 원장 행은 미결
--     (ISSUED/ACCEPTED)로 남는다. 벤더 재전송이 없더라도 미결 스위퍼(VlmSubmitPendingSweeper)가
--     콜백 창 경과 후 회수해 재위탁하므로 두 노드 재기동이 끝나면 자기치유된다.
--     <중복 위탁도 열리지 않는다> — recordIssued 가 외부 호출보다 앞이고 실패 시 abort 하므로
--     원장 없는 제출이 나갈 수 없다(fail-closed).
--
--   ⚠ <창을 여는 것은 Flyway 가 아니다 — 2노드와 Flyway 는 이 배포 형상에서 상호배타다.>
--     온프렘 2노드 이중화는 SPRING_FLYWAY_ENABLED=false 라 <어느 노드도 V8 을 적용하지 않는다>
--     (스키마는 schema.sql 로드). 반대로 Flyway 가 켜진 구성은 단일 노드다. 따라서 "노드 A 가
--     적용한 순간부터" 라는 창은 Flyway 경로에서는 생기지 않는다.
--     2노드에서 창을 여는 것은 <DBA 의 수동 DDL> 이며, 그 적용 시점과 노드 재기동 순서를 맞추는
--     것이 배포 절차의 핵심이다. 수동 적용 시점에 따라 <두 노드가 동시에 구 jar 인 구간>이
--     생길 수 있어, 위 "한 노드만 구 jar" 가정보다 불리한 구간이 존재한다.
--
--   ★ 배포 선택지는 둘이며 <운영 정책 결정>이다 — 배포 담당이 고른다.
--     (a) 양쪽 노드 정지 후 DDL 적용 후 배포 : 창이 없다. 대가는 짧은 다운타임. <권장>
--     (b) 롤링 재기동                        : 무중단이지만 창 동안 (1)(2) 가 실패한다.
--     V5 와 달리 사용자 대면 500 이 없고 회수 경로가 있어 (b) 도 성립하나, (2) 의 FAILED 전이를
--     감수해야 하므로 <V5 처럼 (a) 를 권장>한다.
--     절차는 09-operations-runbook.md 의 「V8 배포 시 주의」 절 참조.
--
-- ★ 롤백 절차 (구버전 jar 로 내릴 때) — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   구버전 엔티티는 옛 컬럼명으로 매핑하므로 개명을 되돌리지 않으면 콜백 처리가 계속 깨진다.
--   아래를 실행한 뒤 DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '8'; 한다.
--
--     ALTER TABLE ls_webhook_idempotency RENAME COLUMN aplcn_dt TO aply_dt;
--
-- ----------------------------------------------------------------------------
-- * 이번에 손대지 않는 것 (빠뜨린 것이 아니다)
-- ----------------------------------------------------------------------------
--   · 이 테이블의 다른 컬럼 · 테이블명 · 인덱스/제약 이름 — 이 라운드의 축이 아니다(별건).
--     인덱스·PK·FK <정의>는 RENAME 을 자동 추종한다.
--   · 논리명 '적용일시' — 처음부터 이 뜻이었고 바뀌지 않는다. 바뀐 것은 물리명뿐이다.
--   · 다른 테이블의 APLY_* 컬럼 — 이 스키마에 APLY 를 쓰는 컬럼은 이것 하나뿐이다(전수 확인).
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 klid_at 이며, 카탈로그 조회는
--     current_schema() / to_regclass 로 스코프하고 식별자는 비한정으로 둔다 — 그래야 조회 대상과
--     조작 대상이 반드시 같은 스키마가 된다.
-- ============================================================================

DO $$
DECLARE
    tbl     CONSTANT text := 'ls_webhook_idempotency';
    old_col CONSTANT text := 'aply_dt';
    new_col CONSTANT text := 'aplcn_dt';
    has_old boolean;
    has_new boolean;
BEGIN
    IF to_regclass(tbl) IS NULL THEN
        RAISE NOTICE '% 가 없다 → no-op', tbl;
        RETURN;
    END IF;

    SELECT EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = current_schema()
                      AND table_name = tbl AND column_name = old_col),
           EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = current_schema()
                      AND table_name = tbl AND column_name = new_col)
      INTO has_old, has_new;

    -- 두 이름이 동시에 존재 → 어느 쪽이 진짜인지 알 수 없다. 조용히 진행하면 옛 컬럼에 남은 값이
    -- 아무도 읽지 않는 채로 사라진다.
    IF has_old AND has_new THEN
        RAISE EXCEPTION
            '%.% 와 %.% 가 동시에 존재한다 — 어느 쪽이 정본인지 알 수 없어 중단한다. '
            '옛 컬럼(%)에 남은 값을 새 컬럼(%)으로 옮겨 확인한 뒤 옛 컬럼을 제거하고 재기동하라.',
            tbl, old_col, tbl, new_col, old_col, new_col;
    END IF;

    -- 이미 개명됨 → 두 번째 실행은 아무것도 하지 않는다.
    IF has_new THEN
        RETURN;
    END IF;

    -- 둘 다 없음 → 이 마이그레이션이 다룰 형상이 아니다. 만들어 내지 않는다(값을 지어내지 않는다).
    IF NOT has_old THEN
        RAISE NOTICE '%.% 도 %.% 도 없다 → no-op', tbl, old_col, tbl, new_col;
        RETURN;
    END IF;

    EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I', tbl, old_col, new_col);
    RAISE NOTICE '표준용어 정합: %.% → %', tbl, old_col, new_col;
END $$;
