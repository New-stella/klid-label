-- H2 전용 Quartz 스키마 (운영 MariaDB는 기존 QRTZ_* 테이블 공유)
-- Phase 3: 영상 수신 + 큐 + Quartz 부트스트랩.
-- 운영 klid_system 에는 본 테이블이 이미 존재하므로 IF NOT EXISTS 로 충돌 방지.
-- 컬럼 정의는 저작도구_DB설계서_FINAL.md §3.3 / §3.9 / §3.10 + plan Phase 3 기준.

-- ============================================================
-- §3.3 원시 영상 (LS_DATA_RAW)
--  - VMS_CLIP_ID UK 로 관제서버로부터의 중복 송신 방지(upsert 기반)
--  - 본 테이블은 H2/MariaDB 양쪽 호환을 우선해 NOT NULL/디폴트만 지정.
-- ============================================================

CREATE TABLE IF NOT EXISTS LS_DATA_RAW (
    RAW_SN          BIGINT          NOT NULL AUTO_INCREMENT,
    VMS_CLIP_ID     VARCHAR(128)    NOT NULL,
    VMS_CCTV_ID     VARCHAR(64)     NOT NULL,
    EVNT_TYPE_CD    VARCHAR(32),
    LCLGV_CD        VARCHAR(32),
    PRVC_TYPE_CD    VARCHAR(16)     NOT NULL,
    PRVC_YN         VARCHAR(1)      NOT NULL DEFAULT 'N',
    DE_IDNTF_YN     VARCHAR(1)      NOT NULL DEFAULT 'N',
    FILE_PATH       VARCHAR(500)    NOT NULL,
    CAPTURED_AT     TIMESTAMP,
    DURATION_SEC    INT,
    DATA_STTS_CD    VARCHAR(32)     NOT NULL DEFAULT 'PENDING',
    REG_DT          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPD_DT          TIMESTAMP,
    PRIMARY KEY (RAW_SN),
    CONSTRAINT UK_LS_DATA_RAW_VMS_CLIP UNIQUE (VMS_CLIP_ID)
);

CREATE INDEX IF NOT EXISTS IX_LS_DATA_RAW_CCTV ON LS_DATA_RAW (VMS_CCTV_ID);
CREATE INDEX IF NOT EXISTS IX_LS_DATA_RAW_STTS ON LS_DATA_RAW (DATA_STTS_CD);

CREATE TABLE IF NOT EXISTS LS_DATA_RAW_HSTRY (
    HSTRY_SEQ       BIGINT          NOT NULL AUTO_INCREMENT,
    RAW_SN          BIGINT          NOT NULL,
    CHG_TYPE        VARCHAR(16)     NOT NULL,
    PREV_STTS_CD    VARCHAR(32),
    NEW_STTS_CD     VARCHAR(32),
    CHG_USER_NO     BIGINT,
    CHG_DT          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (HSTRY_SEQ)
);

CREATE INDEX IF NOT EXISTS IX_LS_DATA_RAW_HSTRY_RAW ON LS_DATA_RAW_HSTRY (RAW_SN);

