-- ============================================================
-- §3.9 배치 작업 큐 (MNG_CLIP_SCHEDULE_QUE)
--  - JOB_TYPE = 'LABELING_BATCH' 값으로 라벨링 배치 파이프라인 적재.
--  - STATUS: PENDING / IN_PROGRESS / DONE / FAILED.
