-- =============================================================================
-- V36 — AI 장비 식별자에 하이픈·밑줄을 허용한다
--       @design API-227 · ERD-034 · ADR-062
--
--   ls_ai_srvr.srvr_id  형식 제약  '^[a-z0-9]{1,20}$'  ->  '^[a-z0-9_-]{1,20}$'
--
-- -----------------------------------------------------------------------------
-- * 왜 넓히는가 (CO-20260908-AI장비-이중화-실제동작-시계열헬스체크-추론선택기배선)
-- -----------------------------------------------------------------------------
--   장비를 등록할 때 소문자와 숫자만 쓸 수 있어 <읽을 수 있는 이름>을 지을 수 없었다.
--   `vlm-01`·`infer_gpu2` 처럼 구분자를 넣는 것이 이 값의 자연스러운 쓰임인데
--   그것이 막혀 `vlm01`·`infergpu2` 로 붙여 써야 했다.
--
--   ★ 하이픈·밑줄은 <맨 앞·맨 뒤에 와도> 허용한다. 자리로 제한하면 규칙과 오류 문구가
--     길어지는데, 막아서 얻는 것이 없다 -- 아래 「왜 형식을 아예 없애지 않는가」가
--     걸러야 할 것을 이미 다 거른다.
--
-- -----------------------------------------------------------------------------
-- * 길이 20 은 그대로 둔다
-- -----------------------------------------------------------------------------
--   srvr_id 컬럼이 varchar(20) 이다. 형식만 늘리고 길이를 늘리면 <입구를 통과한 값이
--   저장 시점에 실패>한다. 길이를 늘리려면 컬럼 폭을 먼저 넓혀야 하고 그건 별개 결정이다.
--
-- -----------------------------------------------------------------------------
-- * 왜 형식을 아예 없애지 않는가 (다음 사람이 「자유 입력으로 하지」로 가지 않게)
-- -----------------------------------------------------------------------------
--   이 값은 <외부 벤더 요청과 기록에 그대로 실린다>. 공백·개행·제어문자가 섞이면
--   기록이 오염되고(CWE-117) 상대측 파싱이 깨진다. 하이픈·밑줄은 그 위험이 없다.
--
-- -----------------------------------------------------------------------------
-- * 하위호환 -- 넓히는 변경이라 기존 식별자는 전부 그대로 유효하다
-- -----------------------------------------------------------------------------
--   새 형식은 옛 형식의 <상위집합>이다. 그래서 재적용이 기존 행을 거부할 수 없고,
--   이 변경으로 못 쓰게 되는 식별자가 없다. 회귀로 오해하지 말 것.
--
--   ⚠ 반대 방향(다시 좁히기)은 이 성질이 없다 -- 하이픈·밑줄을 쓴 장비가 등록된 뒤에
--     좁히면 그 행들이 제약 재적용에서 걸려 <되돌릴 수 없다>. 되돌리려면 그 행을 먼저
--     개명해야 한다.
--
-- -----------------------------------------------------------------------------
-- * 표준용어·표준도메인 근거
-- -----------------------------------------------------------------------------
--   신규 컬럼·표가 없다. 기존 칸의 <값 형식 제약>만 바꾼다.
--   srvr_id (서버 SRVR + 식별자 ID) 와 varchar(20) 은 V23 그대로이며 손대지 않는다.
--
-- -----------------------------------------------------------------------------
-- * 왜 V23 을 고치지 않고 새 파일을 만드는가
-- -----------------------------------------------------------------------------
--   V23 은 이미 적용된 마이그레이션이다. 내용을 바꾸면 체크섬이 달라져
--   <이미 적용한 노드가 전부 기동을 거부>한다.
--
-- -----------------------------------------------------------------------------
-- * 되돌리기
-- -----------------------------------------------------------------------------
--   드롭 마이그레이션을 만들지 않는다. 위 「반대 방향」 주의대로 좁히기는 데이터에
--   의존하므로 자동으로 되돌릴 수 있는 작업이 아니다.
-- =============================================================================

-- 제약을 <바꾸는> 것이라 이름이 같다. 지우고 다시 만드는 순서여야 하며,
-- 두 문장 모두 IF EXISTS / 조건부라 재실행해도 안전하다.
ALTER TABLE ls_ai_srvr
    DROP CONSTRAINT IF EXISTS ck_ls_ai_srvr_srvr_id_format;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('ls_ai_srvr') AND conname = 'ck_ls_ai_srvr_srvr_id_format'
    ) THEN
        -- 문자 클래스에서 '-' 는 맨 뒤에 두어야 범위 기호가 아니라 문자 자체로 읽힌다.
        ALTER TABLE ls_ai_srvr ADD CONSTRAINT ck_ls_ai_srvr_srvr_id_format
            CHECK (srvr_id ~ '^[a-z0-9_-]{1,20}$');
    END IF;
END $$;

COMMENT ON COLUMN ls_ai_srvr.srvr_id IS
    '서버식별자 — 소문자·숫자·하이픈·밑줄 20자 이하. 하이픈과 밑줄은 맨 앞·맨 뒤에 와도 된다. 값이 외부 벤더 요청과 기록에 그대로 실리므로 공백·개행·제어문자는 받지 않는다.';
