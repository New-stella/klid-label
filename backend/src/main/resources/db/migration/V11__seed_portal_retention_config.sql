-- ============================================================================
-- V11: 포털 보존기간 설정 3키를 시드한다  @req R2  @design DFEAT-055
--
--   portal.datamart.retention-days        7  데이터마트 영상에 포털 사용자가 저장한 라벨의 보존일수
--   portal.upload.retention-days          7  포털 업로드 자산 중 정상 처리(READY)된 것의 보존일수
--   portal.upload.failed-retention-days   1  같은 업로드 자산 중 처리 실패(FAILED)한 것의 보존일수
--
-- 전부 STNG_TYPE_CD = NUMBER(정수)이며 허용 범위는 ConfigKeys.NUMBER_RANGE 가 [1, 3650] 로 강제한다.
-- 조회는 SystemConfigService.getInt 이고, 편집은 REVIEWER 가 설정 화면(/v1/manage/configs)에서 한다.
--
-- ----------------------------------------------------------------------------
-- * 왜 시드가 필수인가 — 이 3키를 읽는 삭제 배치는 폴백하지 않는다
-- ----------------------------------------------------------------------------
--   다른 설정 키는 조회 실패 시 서비스 상수로 폴백하지만(fail-safe), 보존기간을 읽는 삭제 배치는
--   <값이 없으면 폴백하지 않고 그 회차를 건너뛴다>. 파괴적 기능이 fail-open 하면 아무도 지시하지
--   않은 기본값으로 사용자 데이터를 지우게 되기 때문이다.
--
--   그 대가가 이 파일이다 — 폴백을 막았으므로 <시드가 없으면 기능이 죽은 채 배포된다>.
--   즉 「폴백 금지」와 「시드」는 세트이며, 한쪽만 두면 배치가 조용히 아무것도 하지 않거나
--   반대로 임의 기간으로 지운다. 이 파일을 지우려면 폴백 정책을 먼저 뒤집어야 한다.
--
-- ----------------------------------------------------------------------------
-- * 왜 하한이 1 인가 — 0·음수는 "즉시 삭제"다 (범위는 ConfigKeys 가 강제)
-- ----------------------------------------------------------------------------
--   이 값은 삭제 커트라인(now - N일)의 N 이다. 0 이면 방금 저장한 라벨·방금 올린 파일이 다음
--   스윕에 곧바로 사라지고, 음수면 커트라인이 미래가 되어 전량이 대상이 된다. 어느 쪽도 복구
--   수단이 없으므로 값 자체를 입구에서 막는다. 상한 3650(10년)은 실질 무제한과 같되 오타로 들어온
--   천문학적 값이 커트라인 계산을 넘치게 하는 것을 막는 상식선이다.
--
-- ----------------------------------------------------------------------------
-- * 실패분을 별도 키로 둔 것은 의도다
-- ----------------------------------------------------------------------------
--   FAILED 자산은 사용자가 다시 올리면 그만인 잔여물이라 정상 자산과 같은 기간을 붙잡아 둘 이유가
--   없다(기본 1일). 두 축을 한 키로 합치면 둘 중 하나는 반드시 틀린 기간으로 운영된다.
--
-- ----------------------------------------------------------------------------
-- * 이 파일이 지키는 규칙
-- ----------------------------------------------------------------------------
--   - 멱등: ON CONFLICT (STNG_KEY) DO NOTHING — 이미 있으면 NOOP 이며, 운영자가 화면에서 바꿔 둔
--     값을 <되돌리지 않는다>. UPSERT 로 쓰면 재적용이 운영 설정을 기본값으로 덮어쓴다.
--   - 스키마 한정자를 쓰지 않는다: 대상 스키마는 커넥션의 search_path(기본 klid_at)가 정한다.
--     기본 스키마 이름을 접두로 박으면 신규 DB 재적용이 조용히 엉뚱한 스키마를 건드린다(실사고 이력).
--   - 신규 컬럼·테이블이 없다(기존 LS_SYSTEM_CONFIG INSERT 뿐) → 표준용어·표준도메인 신규 등록
--     대상이 아니다. LS_* 접두 저작도구 전용 테이블이라 관제서버팀 협의도 면제.
--   - 반영 지연: 설정 캐시 TTL 60초 + 2노드 Active-Active → 다른 노드는 최대 60초 뒤 반영된다.
-- ============================================================================

INSERT INTO LS_SYSTEM_CONFIG (STNG_KEY, STNG_VALUE, STNG_TYPE_CD, EXPLN, MDFR_ID) VALUES
