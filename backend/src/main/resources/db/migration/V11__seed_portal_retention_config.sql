     '포털 데이터마트 라벨 보존일수 (1~3650)', 'SYSTEM'),
    ('portal.upload.retention-days', '7', 'NUMBER',
     '포털 업로드 자산 보존일수 (1~3650)', 'SYSTEM'),
    ('portal.upload.failed-retention-days', '1', 'NUMBER',
     '포털 업로드 실패 자산 보존일수 (1~3650)', 'SYSTEM')
ON CONFLICT (STNG_KEY) DO NOTHING;
