-- ============================================================================
-- V12: LS_ACNT_USER 에 최종로그인일시(LAST_LGN_DT)를 신설한다  @req R2  @design SCREEN-024
--
--   LAST_LGN_DT  timestamp without time zone  NULL 허용
--
-- 사용자 관리 화면(/manage/users)이 「최신 로그인」 컬럼을 그리는데 <그 데이터가 존재하지 않았다>.
-- 화면은 값이 없으니 등록일(REG_DT)을 폴백으로 넣어 보여 주고 있었다 — 즉 가입 시각이 "최근
-- 로그인"이라는 헤더 아래 표시되는 <거짓 표기>였다. 이 컬럼이 그 데이터의 저장소다.
--
-- 등록일과 최종로그인일시는 <용도가 다른 별개 축>이다. 등록일은 가입 이력이고, 최종로그인일시는
-- 휴면 계정 판단용이다. 한쪽이 다른 한쪽을 대체할 수 없으므로 화면도 두 컬럼을 함께 보인다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (규칙 3 — 우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   행안부 공통표준<용어> : 최종로그인일시 = LAST_LGN_DT / 도메인 연월일시분초D / 1차(2020-08) 등록
--
--   ⚠ 우선순위 규칙상 (1)행안부에 이 용어가 <이미 있으므로 여기서 판정이 끝난다>. (2)사업표준은
--     행안부에 <없는 개념>을 채우는 보충이며, 있는 개념을 다른 약어로 덮어쓰는 자리가 아니다.
--     (과거 이 순서를 거꾸로 적용해 이미 맞던 행안부 약어 RTRY 를 사업 약어 RTY 로 바꿔 놓고
--      다음 라운드에서 되돌린 실사고가 있다. 같은 실수를 반복하지 않는다.)
--
--   ⚠ <유사 용어를 고르지 않았다> — 같은 사전에 최근로그인일시(RCNT_LGN_DT) · 로그인일시(LGN_DT) ·
--     사용자로그인일시(USER_LGN_DT) 도 등록돼 있다. 이 컬럼이 담는 값은 「맨 나중에 접속한 시각」
--     하나이므로 그 뜻의 용어(최종=LAST)를 쓴다. RCNT(최근)는 "얼마 되지 않은 기간"이라는 구간
--     개념이고 LGN_DT 는 개별 로그인 이력 행의 시각이다 — 둘 다 이 컬럼의 뜻이 아니다.
--
--   ⚠ <로그인 이력 테이블을 만드는 것이 아니다>. 이력을 쌓으려면 별도 테이블과 보존정책이 필요하고
--     그것은 이 변경의 범위가 아니다. 여기서 만드는 것은 <마지막 값 1개>를 담는 컬럼뿐이다.
--
-- ----------------------------------------------------------------------------
-- * 왜 nullable 인가 — 기본값을 넣으면 접속을 날조한다
-- ----------------------------------------------------------------------------
--   한 번도 접속하지 않은 계정은 <값이 없는 것이 사실>이다. DEFAULT CURRENT_TIMESTAMP 나 REG_DT
--   백필을 넣으면 "접속한 적 있음"이라는 없던 사실이 생기고, 휴면 계정 판단이 통째로 무의미해진다.
--   NULL 은 화면에서 미접속 표기('-')로 그려진다.
--
--   같은 이유로 <기존 행을 백필하지 않는다>. 이 컬럼 신설 이전의 접속 기록은 어디에도 없으므로
--   무엇을 넣어도 지어낸 값이다. 기존 전 행은 NULL 로 남고, 각자 다음 접속에서 자연히 채워진다.
--
-- ----------------------------------------------------------------------------
-- * 타입 — 레포의 기존 _dt 컬럼 관례와 동일
-- ----------------------------------------------------------------------------
--   같은 테이블의 REG_DT·MDFCN_DT 를 포함해 이 스키마의 모든 일시 컬럼이
--   timestamp without time zone 이다. timestamptz 로 혼자 다르게 만들면 같은 테이블 안에서 두
--   시간 축이 섞인다. 표준도메인 연월일시분초D 도 이 표현으로 충족된다.
--
-- ----------------------------------------------------------------------------
-- * 기록 주체와 빈도 (이 컬럼을 쓰는 쪽의 계약 — 참고)
-- ----------------------------------------------------------------------------
--   저작도구에는 독립 로그인 UI 가 없다(관제/포털이 발급한 JWT 를 인계받는다). 따라서 "로그인
--   시점"이라는 단일 이벤트가 없고, <JWT 검증을 통과한 INTERNAL 요청>이 기록 지점이다.
--   그 경로는 <모든 요청>에서 돌기 때문에 매 요청 UPDATE 를 하면 요청 수만큼 행 잠금·WAL 이
--   생긴다. 그래서 애플리케이션은 조건부 UPDATE 한 문장으로 최소 간격을 강제한다
--   (WHERE LAST_LGN_DT IS NULL OR LAST_LGN_DT < now - 최소간격). 2노드 Active-Active 라
--   로컬 캐시가 아니라 <이 조건절>이 정확성의 근거다.
--
--   ⚠ MDFCN_DT 는 이 기록에서 <건드리지 않는다>. 그 컬럼은 관제 인계 표시정보(USER_ID·USER_NM)의
--     변경 시각이며, 접속마다 갱신하면 "프로필이 바뀐 시각"이라는 뜻이 오염된다.
--
-- ----------------------------------------------------------------------------
-- * 멱등 · 두 경로 수렴
-- ----------------------------------------------------------------------------
--   IF NOT EXISTS 로 두 번 돌아도 안전하다.
--   · 신규 설치(빈 DB) : V1 이 이 컬럼 없이 테이블을 만들고 여기서 추가된다(no-op 이 아니다).
--     V1__baseline.sql 은 이미 적용된 이력이라 고치지 않는다(체크섬 불일치 = 전 노드 기동 실패).
--   · 기존 DB          : V11 까지 적용된 상태에서 여기서 추가된다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   ADD COLUMN <NULL 허용 + DEFAULT 없음> 은 PostgreSQL 11+ 에서 카탈로그만 고치므로 테이블
--   재작성이 없고 잠금은 순간이다.
--
--   ★ 이 변경은 <하위호환>이다. 컬럼이 생겨도 구 jar 노드는 그 컬럼을 모르는 SQL 을 만들 뿐이고
--     (엔티티 매핑에 없으므로 SELECT/INSERT 목록에 나타나지 않는다) 새 jar 노드만 쓰고 읽는다.
--     따라서 롤링 재기동으로 무중단 배포가 가능하며, 위 V5·V8 같은 전진 창이 없다.
--     구 jar 로 되돌려도 컬럼이 남아 있을 뿐 아무것도 깨지지 않는다.
--
-- ★ 롤백 절차 (컬럼까지 되돌릴 때) — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   되돌릴 필요는 없다(하위호환). 그래도 지워야 한다면 <기록된 접속 시각이 함께 사라진다>.
--
--     ALTER TABLE ls_acnt_user DROP COLUMN last_lgn_dt;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '12';
--
-- ----------------------------------------------------------------------------
-- * 이번에 손대지 않는 것 (빠뜨린 것이 아니다)
-- ----------------------------------------------------------------------------
--   · 인덱스 — 이 컬럼으로 검색·정렬하는 경로가 없다(목록은 USER_ID/USER_NM/USER_EML_ADDR 로만
--     검색한다). 쓰기가 잦은 컬럼에 근거 없는 인덱스를 붙이면 갱신 비용만 늘어난다.
--   · 로그인 이력 테이블 · 최종로그인IP주소(LAST_LGN_IP_ADDR) — 요청 범위 밖이다.
--   · 포털 채널 접속 — 이 컬럼은 저작도구 사용자 마스터의 축이다. 포털 토큰의 sub 는 이 테이블의
--     USER_NO 로 <매핑이 확인되지 않았으므로> 추측 조인하지 않는다(애플리케이션이 INTERNAL 만 기록).
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 커넥션의 search_path(기본 klid_at)가
--     정하고, 카탈로그 조회는 current_schema() 로 스코프해 조회 대상과 조작 대상을 같게 만든다.
-- ============================================================================

ALTER TABLE ls_acnt_user
    ADD COLUMN IF NOT EXISTS last_lgn_dt timestamp without time zone;

COMMENT ON COLUMN ls_acnt_user.last_lgn_dt IS
    '최종로그인일시 — 맨 나중에 접속한 시각. 한 번도 접속하지 않았으면 NULL(기본값을 넣지 않는다).';
