-- 롤백 SQL (V162 규약 — 스키마 변경에는 롤백 전문을 동반한다):
--   ALTER TABLE LS_RAW_DATA_STATUS DROP COLUMN IF EXISTS REVLT_YN;
--   ※ 애플리케이션 롤백도 함께 필요하다 — 엔티티 매핑(LsRawDataStatus.revltYn)이 남아 있으면
--     컬럼 부재로 INSERT/조회가 실패한다(ddl-auto=validate).
