ALTER TABLE LS_RAW_DATA_STATUS ADD COLUMN IF NOT EXISTS REVLT_YN CHAR(1) NOT NULL DEFAULT 'N';

COMMENT ON COLUMN LS_RAW_DATA_STATUS.REVLT_YN IS
    '재검토여부 — 검수 승인(APPROVED) 이후 라벨/메타가 수정되어 검수자의 재검토가 필요한가. '
    'Y=재검토 필요(재승인 대기) / N=재검토 불요(기본값). 행안부 공통표준용어 REVLT_YN + 공통표준도메인 여부C1(CHAR(1), Y/N).';
