-- ============================================================================
-- V22: 역할 변경에 「바꾼 사람」을 남긴다 — ls_user_role.mdfr_id 신설  @design AC-1018 · API-004
--
--   ls_user_role.mdfr_id   수정자아이디 (신규 컬럼 · nullable)
--
-- 지금까지 역할 변경 기록에는 <대상> 만 있고 <주체> 가 없었다. 남는 것은 애플리케이션 로그의
-- "userNo / before / after" 뿐이고 영속 기록에는 아무 흔적이 없어, 누가 누구를 관리자로 올렸는지를
-- 알려면 별도 유효창 발급 로그와 <시각으로 이어 붙이는> 수밖에 없었다.
-- 권한 상승은 감사에서 가장 중요한 사건이라 그 자리를 데이터로 남긴다.
--
-- ----------------------------------------------------------------------------
-- * 표준용어 근거 (우선순위 (1)행안부 공통표준 -> (2)사업표준 -> (3)신규)
-- ----------------------------------------------------------------------------
--   판정은 docs/ 아래 CSV 정본 전수 대조로 한다(검색 API 는 상한 때문에 "미등록" 오판을 낸다).
--
--   수정자아이디 = MDFR_ID (사업표준 · 사업도메인 <식별자V30>) -> character varying(30)
--     · 정본 행: 사업표준용어.csv 「수정자아이디, MDFR_ID, 사업도메인 식별자V30」
--     · 이 저장소에 이미 같은 물리명·같은 폭으로 쓰이는 컬럼이 5개 있다
--       (ls_system_config · ls_notice · ls_mngr_pswd · ls_otsd_ctgry_mpng · ls_vrfc_evnt_type).
--       새 이름을 짓지 않고 그 폭을 그대로 따른다 — 같은 개념에 두 물리명이 서면 그 자체가 드리프트다.
--
-- ----------------------------------------------------------------------------
-- * ★ nullable 이다 — 기존 행을 깨지 않는 것이 조건이다
-- ----------------------------------------------------------------------------
--   NOT NULL + 기본값으로 채우면 <이 컬럼이 생기기 전에 바뀐 행> 에 사실이 아닌 주체가 박힌다.
--   기록이 없다는 사실 자체가 정보이므로 null 로 남긴다 = "이 컬럼이 생기기 전에 바뀐 것".
--   지어낸 값보다 빈 값이 낫다.
--
--   백필하지 않는다 — 과거 변경의 주체를 알 방법이 없다(그것이 이 변경의 동기다).
--
-- ----------------------------------------------------------------------------
-- * ★ 이력 표를 만들지 않는다 (부재가 설계 결정이다)
-- ----------------------------------------------------------------------------
--   이 컬럼이 남기는 것은 <마지막으로 바꾼 사람> 하나다. 변경 이력 전체가 필요하면 별도 표가
--   있어야 하는데, 그것은 보존 주기·조회 창구·정리 배치를 함께 정해야 하는 별개 결정이다.
--   여기서는 「주체가 아예 없다」는 결함만 닫는다 — 범위를 넓히면 그 결정을 추정으로 대신하게 된다.
--   ⇒ 나중에 "변경 이력이 필요하다" 는 생각이 들면, 그것은 이 결정을 확장하는 별개 작업이다.
--
-- ----------------------------------------------------------------------------
-- * 멱등 · 두 경로 수렴
-- ----------------------------------------------------------------------------
--   ADD COLUMN IF NOT EXISTS 라 두 번 돌아도 안전하다.
--   · 신규 설치(빈 DB) : V1 이 이 컬럼 없이 표를 만들고 여기서 추가된다.
--     V1__baseline.sql 은 이미 적용된 이력이라 고치지 않는다(체크섬 불일치 = 전 노드 기동 실패).
--   · 기존 DB          : V21 까지 적용된 상태에서 여기서 추가된다.
--
-- ----------------------------------------------------------------------------
-- * 잠금과 배포 창 (2노드 Active-Active)
-- ----------------------------------------------------------------------------
--   기본값 없는 nullable 컬럼 추가는 PostgreSQL 11+ 에서 카탈로그만 고치므로 표를 다시 쓰지 않는다.
--   ACCESS EXCLUSIVE 잠금은 순간이고 행 수도 사용자 수만큼이라 무시할 만하다.
--   이 변경은 <하위호환> 이다 — 구 jar 노드는 이 컬럼을 모르고 그대로 동작한다(insert 목록에
--   없으면 null 이 들어간다). 롤링 재기동으로 무중단 배포가 가능하다.
--
-- ★ 롤백 절차 — Flyway 는 down-migration 을 하지 않으므로 DBA 가 수동 적용.
--   되돌리면 <누가 역할을 바꿨는지> 가 사라진다. 비가역이므로 서두르지 말 것.
--
--     ALTER TABLE ls_user_role DROP COLUMN mdfr_id;
--     DELETE FROM FLYWAY_SCHEMA_HISTORY WHERE VERSION = '22';
--
-- ----------------------------------------------------------------------------
-- * 작성 규칙 (이 저장소에서 실제로 깨진 적이 있는 것들)
-- ----------------------------------------------------------------------------
--   · 달러-중괄호 플레이스홀더 표기를 <주석에도> 쓰지 않는다. Flyway 가 placeholder 로 읽어
--     "No value provided for placeholder" 로 파일 전체가 적용되지 않는다.
--   · 스키마 리터럴(public 등)을 박지 않는다. 대상 스키마는 커넥션의 search_path(기본 klid_at)가
--     정한다.
-- ============================================================================

ALTER TABLE ls_user_role ADD COLUMN IF NOT EXISTS mdfr_id character varying(30);

COMMENT ON COLUMN ls_user_role.mdfr_id IS
    '수정자아이디 — 이 사용자의 역할을 마지막으로 바꾼 사람(인계 토큰 subject). ★요청 바디가 아니라 인증 주체에서만 취한다(바디 값은 위조 가능하다). null 은 「이 컬럼이 생기기 전에 바뀐 행」이거나 「인증 주체를 알 수 없는 경로(운영 배치·시험 하네스)」를 뜻하며, 지어낸 값을 채우지 않는다. 이 컬럼이 남기는 것은 마지막 변경자 하나뿐이고 변경 이력 전체는 대상이 아니다(별개 결정).';
