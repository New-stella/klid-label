-- ============================================================================
-- V26 — 영상별 배정 이력의 장비 외래키를 없앤다
--
-- 배정 표(ls_ai_srvr_altmnt)는 <처리가 도는 동안> 영상의 프레임을 한 노드에 묶어 두는
-- 자리다. 추적기 상태가 그 노드 프로세스의 로컬 메모리에 있어 프레임이 두 노드로 흩어지면
-- 추적이 끊기기 때문이다.
--
-- ★ 그런데 그 묶음은 <처리가 끝나면 의미가 없다> — 추적기 메모리는 그때 이미 사라졌다.
--   끝난 배정은 순수 이력인데, ON DELETE RESTRICT 가 걸려 있어 <한 번이라도 영상을 처리한
--   장비는 영구히 삭제 불가>가 된다. 장비 교체가 구조적으로 막히는 것이라 과한 제약이다.
--
-- ★ 같은 저장소에 이미 선례가 있고 근거도 적혀 있다 — ls_webhook_idempotency.srvr_id 는
--   외래키를 <일부러> 걸지 않았고 그 컬럼 주석이 이유를 이렇게 말한다:
--     "이 원장은 감사 기록이라 장비 원장보다 오래 살아야 하고, 장비 행이 지워져도 어느
--      장비였는지는 남아야 한다."
--   배정 이력에 같은 논리가 그대로 적용되는데 한쪽만 외래키가 걸려 있었다. 축을 맞춘다.
--
-- ⚠ <처리 중인> 영상까지 보호가 사라지는 것이 아니다 — 그 보호는 외래키가 아니라
--   정비중(DRAINING) 상태가 담당한다("신규 배정만 막고 진행 중인 배정은 끝까지 간다").
--   그리고 유형별 마지막 가용 장비 보호가 삭제·활성 이탈 양쪽을 따로 막는다.
--
-- ⚠ 이 마이그레이션은 <제약만> 없앤다. 표·컬럼·행은 그대로이며 배정 이력은 남는다.
--   장비를 지우면 그 행의 srvr_id 는 <이제 없는 장비를 가리키는 값>으로 남는데,
--   그것이 의도다(어느 장비였는지의 기록).
--
-- 되돌리기:
--   ALTER TABLE ls_ai_srvr_altmnt ADD CONSTRAINT fk_ls_ai_srvr_altmnt_srvr
--       FOREIGN KEY (srvr_id) REFERENCES ls_ai_srvr (srvr_id) ON DELETE RESTRICT;
--   ⚠ 되돌리기 전에 고아 행(ls_ai_srvr 에 없는 srvr_id)을 먼저 정리해야 한다.
-- ============================================================================

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('ls_ai_srvr_altmnt')
          AND conname = 'fk_ls_ai_srvr_altmnt_srvr'
    ) THEN
        ALTER TABLE ls_ai_srvr_altmnt DROP CONSTRAINT fk_ls_ai_srvr_altmnt_srvr;
    END IF;
END $$;

COMMENT ON COLUMN ls_ai_srvr_altmnt.srvr_id IS
    'AI서버아이디 — 이 영상을 보내기로 한 장비. ★외래키를 걸지 않는다(V26): 이 표는 처리가 도는 동안 프레임을 한 노드에 묶어 두는 자리이고, 처리가 끝나면 그 묶음은 의미가 없다(추적기 메모리가 이미 사라졌다). 끝난 배정까지 장비 삭제를 막으면 한 번이라도 영상을 처리한 장비는 영구히 교체 불가가 된다. 장비 행이 지워져도 어느 장비였는지는 남아야 하므로 값은 그대로 둔다 — 위탁 원장(ls_webhook_idempotency.srvr_id)과 같은 축이다. 처리 중인 영상의 보호는 외래키가 아니라 정비중(DRAINING) 상태와 유형별 마지막 가용 장비 보호가 담당한다.';
