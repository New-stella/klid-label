-- LS_DEIDENT_REPORT: 영상 비식별 요청/결과 이력 + 사용자 신고 통합 테이블.
-- 기준: docs/requirements/final-clean/관제서버_DB_신규테이블_DDL.md §5
-- 비식별 결과는 LS_DATA_RAW 에 붙이지 않고 본 이력 테이블에만 저장한다.
CREATE TABLE IF NOT EXISTS LS_DEIDENT_REPORT (
    DEIDENT_REPORT_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    DATA_RAW_SN BIGINT NOT NULL,
    -- 시스템 비식별 처리 이력
    REQ_ID VARCHAR(64) NULL,
    ORGN_FILE_PATH_NM VARCHAR(1000) NULL,
    DE_IDNTF_FILE_PATH_NM VARCHAR(1000) NULL,
    PROC_STTS_CD VARCHAR(20) NOT NULL,
    REQ_DT TIMESTAMP NULL,
    RES_DT TIMESTAMP NULL,
    ERROR_CD VARCHAR(50) NULL,
    ERROR_MSG VARCHAR(1000) NULL,
    -- 사용자 신고 (NULL 허용)
    REPORTER_NO BIGINT NULL,
    RSN VARCHAR(1000) NULL,
    REPORT_STTS_CD VARCHAR(16) NULL,
    REPORT_DT TIMESTAMP NULL,
    RESOLVED_DT TIMESTAMP NULL,
    -- audit
    REG_ID VARCHAR(30) NULL,
    REG_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MDFCN_ID VARCHAR(30) NULL,
    MDFCN_DT TIMESTAMP NULL,
    PRIMARY KEY (DEIDENT_REPORT_SN)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DEIDENT_REPORT_RAW ON LS_DEIDENT_REPORT (DATA_RAW_SN);
CREATE INDEX IF NOT EXISTS IDX_LS_DEIDENT_REPORT_REQ ON LS_DEIDENT_REPORT (REQ_ID);
CREATE INDEX IF NOT EXISTS IDX_LS_DEIDENT_REPORT_PROC ON LS_DEIDENT_REPORT (PROC_STTS_CD);
CREATE INDEX IF NOT EXISTS IDX_LS_DEIDENT_REPORT_REPORT ON LS_DEIDENT_REPORT (REPORT_STTS_CD, REPORT_DT);
