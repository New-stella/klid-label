-- ============================================================================
-- V28 — 마킹 원장의 중복 두 칸을 없애고 등록 사용자 번호를 문자로 넓힌다  @design ERD-013
--
--   1) ls_marking.reg_user_no  bigint → character varying(100)   (되돌릴 수 있다)
--   2) ls_marking.evnt_nm               제거                      (★되돌릴 수 없다)
--   3) ls_marking.video_file_path_nm    제거                      (★되돌릴 수 없다)
--
-- ----------------------------------------------------------------------------
-- * 왜 두 칸을 없애나
-- ----------------------------------------------------------------------------
--   두 값은 영상 행(ls_data_raw)에 이미 있는 것을 마킹 행에 <베껴 둔 중복>이다.
--     evnt_nm            <- ls_data_raw.evnt_type_cd     (마킹 생성 시 그대로 복사했다)
--     video_file_path_nm <- ls_data_raw.raw_file_path_nm (마킹 생성 시 그대로 복사했다)
--   영상 쪽이 바뀌면 두 값이 어긋나고, 어느 쪽이 맞는지 판정할 축이 없다.
--
--   없애는 계기는 포털 업로드 영상 마킹이다. 그 경로에는 <둘 다 채울 값이 없다> —
--   관제 인입 이벤트 유형이 애초에 오지 않고, 본인 데이터라 비식별을 하지 않는다.
--   그런데 두 칸이 NOT NULL 이라 <저장 자체가 막혀> 있었다.
--
--   ⚠ 마킹 응답의 두 값은 사라지지 않는다 — 영상 행을 읽어 채우므로 화면·외부 계약은
--     그대로다(MarkingResponse.from 이 ls_data_raw 의 두 값을 받는다).
--
-- ----------------------------------------------------------------------------
-- * 왜 등록 사용자 번호를 넓히나
-- ----------------------------------------------------------------------------
--   포털 채널에서는 이 값이 그 마킹의 소유자이자 <인가 판정의 키>라 반드시 채워지는데,
--   포털이 발급한 토큰의 주체 식별자는 숫자가 아니다. 지금은 숫자로 못 바꾸면 조용히
--   NULL 이 되어(파싱 실패 → null) 소유자 없는 마킹이 저장된다.
--
--   폭 100 은 공통표준도메인 번호V100(문자 100자)을 따른다. 더 좁게 잡으면 서로 다른
--   사용자가 같은 값으로 잘려 인가가 조용히 어긋난다.
--
--   기존 행의 값은 숫자를 문자로 옮길 뿐이라 <무손실>이다(1001 → '1001').
--
-- ----------------------------------------------------------------------------
-- * ★ 이 마이그레이션은 되돌릴 수 없다
-- ----------------------------------------------------------------------------
--   컬럼을 지우면 그 안에 있던 값이 함께 사라진다. 되살리려면 컬럼을 다시 만들 수는
--   있어도 <값은 복구되지 않는다>. 다만 두 값은 영상 행에서 다시 조달할 수 있으므로
--   (위 대응표) 되살릴 필요가 생기면 그 조인으로 백필한다.
--
--   폭 확대만 되돌리려면:
--     ALTER TABLE ls_marking ALTER COLUMN reg_user_no TYPE bigint
--         USING (NULLIF(reg_user_no, '')::bigint);
--     ⚠ 숫자가 아닌 값(포털 주체 식별자)이 이미 들어 있으면 이 되돌리기는 실패한다.
--       먼저 그 행을 정리해야 하며, 정리하면 <소유자 정보가 사라진다>.
--
-- ----------------------------------------------------------------------------
-- * 왜 폭 확대와 컬럼 제거를 한 파일에 두나
-- ----------------------------------------------------------------------------
--   이 저장소에는 "되돌릴 수 없는 작업을 분리한다" 는 관례가 있다(포털 복제 발신함 표를
--   지우지 않고 남긴 사례). 그 관례가 성립하는 조건은 <중간 상태가 멀쩡할 때>다 —
--   그때는 읽는 코드가 0건이라 표를 남겨 둬도 아무 일이 없었다.
--
--   여기는 그렇지 않다. 엔티티가 두 필드를 더 이상 채우지 않으므로, 제거를 미룬 중간
--   상태에서는 두 NOT NULL 컬럼에 값이 들어가지 않아 <마킹 저장이 전건 실패>한다.
--   즉 나누면 "안전하게 멈출 수 있는 지점" 이 아니라 <고장난 지점> 이 하나 생긴다.
--   두 변경은 같은 확정(2026-09-02)에서 나왔고 어느 하나만으로는 목적을 이루지 못한다.
--
--   PostgreSQL 에서 Flyway 는 마이그레이션 하나를 <한 트랜잭션>으로 실행하므로,
--   한 파일에 두어도 절반만 적용되는 상태는 생기지 않는다.
--
-- ----------------------------------------------------------------------------
-- * 멱등성 / 의존성
-- ----------------------------------------------------------------------------
--   - 타입 변경은 현재 자료형을 확인한 뒤에만 실행한다(재실행 안전).
--     카탈로그 조회는 current_schema() 로 스코프한다 — 'public' 리터럴을 박으면
--     klid_at 에서 영원히 거짓이 되어 조용히 건너뛴다(V62/V63/V71 실사고).
--   - DROP COLUMN 은 IF EXISTS 로 재실행 안전.
--   - 두 컬럼을 참조하는 뷰·인덱스·제약은 없다(전수 확인: 인덱스 idx_lm_raw 는 raw_sn,
--     부분 유니크 uk_ls_marking_raw_actvtn 은 raw_sn + stts_cd, 외래키는 raw_sn).
--     reg_user_no 도 어떤 뷰에서도 참조되지 않는다 — 참조되면 PostgreSQL 이 타입 변경
--     자체를 거부하므로 조용히 넘어가지 않는다.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) 등록 사용자 번호: bigint → varchar(100)  (되돌릴 수 있는 변경)
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name   = 'ls_marking'
          AND column_name  = 'reg_user_no'
          AND data_type    = 'bigint'
    ) THEN
        -- bigint → varchar 는 자동 캐스트가 없으므로 USING 이 필요하다.
        -- NULL 은 NULL 로 남는다(::text 가 NULL 을 그대로 전파).
        ALTER TABLE ls_marking ALTER COLUMN reg_user_no TYPE character varying(100)
            USING (reg_user_no::text);
    END IF;
END $$;

COMMENT ON COLUMN ls_marking.reg_user_no IS
    '등록사용자번호 — 마킹을 만든 사용자. 내부 채널에서는 작업자이고, 포털 채널에서는 그 마킹의 소유자이자 인가 판정의 키라 반드시 채워진다. ★자료형이 숫자가 아니라 문자인 이유(V28): 포털이 발급한 토큰의 주체 식별자를 담아야 한다. 폭 100 은 공통표준도메인 번호V100 을 따르며, 더 좁게 잡으면 서로 다른 사용자가 같은 값으로 잘려 인가가 조용히 어긋난다.';

-- ----------------------------------------------------------------------------
-- 2) 중복 두 칸 제거  (★되돌릴 수 없는 변경 — 위 주석의 백필 경로 참조)
-- ----------------------------------------------------------------------------
ALTER TABLE ls_marking DROP COLUMN IF EXISTS evnt_nm;
ALTER TABLE ls_marking DROP COLUMN IF EXISTS video_file_path_nm;
