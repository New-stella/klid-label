-- =============================================================================
-- 포털 DB 복제본 프로비저닝 DDL — LS_DATASET_VIDEO_META (+ 활성 1건 부분 유니크 인덱스)
--
-- ⚠ 이 스크립트는 애플리케이션 Flyway 가 자동 실행하지 않는다.
--    - control Flyway 는 `classpath:db/migration` 만 스캔한다(재귀). 본 파일은 의도적으로
--      `db/portal/`(migration 경로 밖)에 둔다 → control DB 에 오적용되지 않는다.
--    - 포털 DB(별도 물리 DB, PORTAL_DB_*)는 저작도구가 소유하지 않고 인프라가 제공하므로,
--      복제본 테이블은 인프라/운영이 이 스크립트를 포털 DB 에 1회 수동 적용(또는 포털 전용
--      Flyway 데이터소스를 별도 구성)하여 프로비저닝한다.
--    - 복제 워커(MetaReplicationWorker)는 대상 테이블 부재 시 graceful skip 한다(중단 아님) —
--      프로비저닝 완료 후 다음 tick 부터 복제가 재개된다.
--
-- 스키마는 control 원본(V97 + V99)과 동일 DDL 이어야 한다(복제본). 표준용어/타입 정합은 V97 참조.
-- PostgreSQL 표준 문법.
-- =============================================================================

CREATE TABLE IF NOT EXISTS LS_DATASET_VIDEO_META (
    META_SNPSHT_SN   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    RAW_SN           BIGINT       NOT NULL,
    SNPSHT_HASH      VARCHAR(64)  NOT NULL,
    ACTIVE_YN        CHAR(1)      NOT NULL DEFAULT 'Y',

    -- 원시(LS_DATA_RAW 유래)
    ORGNL_RAW_SN     BIGINT,
    VMS_CLIP_ID      VARCHAR(128),
    VMS_CCTV_ID      VARCHAR(64),
    RAW_FILE_PATH_NM VARCHAR(500),
    SHT_DT           TIMESTAMP,
    VDO_LEN_SEC      INT,
    LCLGV_CD         VARCHAR(32),
    PRVC_YN          CHAR(1),
    PRVC_TYPE_CD     VARCHAR(16),
    DE_IDENT_YN      CHAR(1),
    AI_CRT_YN        CHAR(1),
    EVNT_TYPE_CD     VARCHAR(32),

    -- MNG 동결
    CCTV_NM          VARCHAR(255),
    WGS84_LAT        DECIMAL(10,7),
    WGS84_LOT        DECIMAL(10,7),
    SIDO_NM          VARCHAR(100),
    SGG_NM           VARCHAR(100),
    FILE_FMT         VARCHAR(32),
    EVNT_NM          VARCHAR(255),

    -- ffprobe 기술 메타
    VDO_CDC          VARCHAR(32),
    FPS              NUMERIC,
    BIT_RT           BIGINT,
    ASPRT_RT         NUMERIC,
    RESL             VARCHAR(32),
    VDO_WDTH         INT,
    VDO_HGT          INT,
    FILE_SZ          BIGINT,

    -- 파생(SHT_DT)/수기
    DAY_NGT_CD       VARCHAR(8),
    SESN_CD          VARCHAR(8),
    WTHR_NM          VARCHAR(32),

    -- 관리
    RVW_CMPL_DT      TIMESTAMP,
    REG_DT           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID           VARCHAR(64),

    PRIMARY KEY (META_SNPSHT_SN),
    CONSTRAINT UK_LS_DATASET_VIDEO_META UNIQUE (RAW_SN, SNPSHT_HASH)
);

CREATE INDEX IF NOT EXISTS IDX_LS_DATASET_VIDEO_META_RAW_ACTIVE
    ON LS_DATASET_VIDEO_META (RAW_SN, ACTIVE_YN);

CREATE INDEX IF NOT EXISTS IDX_LS_DATASET_VIDEO_META_RVW_CMPL
    ON LS_DATASET_VIDEO_META (RVW_CMPL_DT);

-- 활성 1건 불변식(V99 동형) — 복제본에서도 RAW_SN 당 ACTIVE_YN='Y' 최대 1건.
CREATE UNIQUE INDEX IF NOT EXISTS UK_LS_DATASET_VIDEO_META_RAW_ACTIVE
    ON LS_DATASET_VIDEO_META (RAW_SN)
    WHERE ACTIVE_YN = 'Y';
