package kr.co.cudo.authoring.video.dto;

/**
 * 해상도 변경 표준 하위 해상도 프리셋 — Phase 1 (RQ-SFR-06-03 v1.8/1.10).
 *
 * <p>표준 하위 해상도 화이트리스트(1080p/720p/480p)만 제공한다. enum 바인딩으로 화이트리스트를
 * 강제하여 그 외의 값은 Jackson 역직렬화 단계에서 400(INVALID_INPUT) 으로 거부된다
 * (CWE-20 입력 검증 — 자유 입력 해상도 차단).
 *
 * <h3>두 수치는 고정 캔버스가 아니라 <b>크기 상한</b>이다 (확정, @design ADR-018)</h3>
 * <p>산출 프레임 크기는 원본 종횡비에 따라 달라진다 — 원본의 짧은 변을 프리셋의 짧은 값
 * (1080/720/480)에 맞추는 배율을 구하고, 그 배율로 계산한 긴 변이 프리셋의 긴 값(1920/1280/854)을
 * 넘을 때만 긴 변이 상한에 맞도록 배율을 낮춘다. 남는 영역을 채우는 <b>패딩이 없다</b>.
 *
 * <p>720p 기준 산출 예 — {@code 1920×1080 → 1280×720} / {@code 1440×1080 → 960×720}(짧은 변 기준) /
 * {@code 640×480 → 960×720}(업스케일 허용) / {@code 1080×1920 → 720×1280}(세로 영상) /
 * {@code 2560×1080 → 1280×540}(긴 변 상한에 걸려 배율이 낮아진 경우).
 *
 * <p>배율은 {@code LetterboxTransform} 이 <b>단일 계산</b>하며 가로·세로에 같은 값을 적용한다
 * (종횡비 보존). 픽셀(리사이즈)과 라벨 좌표(BBOX·POLYGON·세그멘테이션·키포인트)가 같은 값을 쓰고,
 * 라벨 좌표 변환은 {@code x' = x*scale} 곱셈만이며 오프셋 가산이 없다.
 *
 * <p><b>기존 파생본은 재생성하지 않는다</b> — 신규 생성부터 이 규칙이 적용된다.
 */
public enum ResolutionPreset {

    RESL_1080P(1920, 1080),
    RESL_720P(1280, 720),
    RESL_480P(854, 480);

    private final int width;
    private final int height;

    ResolutionPreset(int width, int height) {
        this.width = width;
        this.height = height;
    }

    /**
     * 가로 <b>상한</b>(px) — 산출 프레임의 고정 가로가 아니다. 실제 산출 가로는 원본 종횡비로 계산된다
     * (예: 원본 1440×1080 을 720p 로 파생하면 960).
     */
    public int width() {
        return width;
    }

    /**
     * 세로 <b>상한</b>(px) — 산출 프레임의 고정 세로가 아니다. 실제 산출 세로는 원본 종횡비로 계산된다
     * (예: 원본 2560×1080 을 720p 로 파생하면 540 — 긴 변 상한에 걸려 배율이 낮아진다).
     */
    public int height() {
        return height;
    }
}
