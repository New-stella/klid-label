package kr.co.cudo.authoring.batch.policy;

/**
 * 영상의 이벤트 유형 → 오토라벨 프리셋 해석 결과의 <b>사유 구분</b>. [@design ADR-054]
 *
 * <h3>왜 사유를 구분하는가</h3>
 * <p>구 구현은 프리셋을 특정하지 못하는 네 경우를 모두 빈 값 하나로 뭉갰고, 호출자는 그 빈 값을
 * <b>전량 저장(fail-open)</b> 으로 해석했다. 그래서 ①프리셋이 없다는 사실이 아무 증상 없이 지나가고
 * ②운영자가 프리셋을 등록해 두고도 그것이 실효하지 않는 상태를 화면 어디에서도 알 수 없었다.
 * 보류 판정도 화면 표시도 이 구분 없이는 성립하지 않는다.
 *
 * <p><b>이 판정이 배치·프리셋 화면·이벤트 유형 화면이 공유하는 단일 진실원이다</b> — 다른 곳에서
 * 프리셋을 다시 조회해 실효성을 재유도하지 말 것(한쪽만 갱신되는 드리프트가 이 저장소의 반복 결함이다).
 *
 * <h3>★{@link #PRESET_EMPTY} 만 성격이 다르다 — 사고가 아니라 선언이다 [@design AC-119]</h3>
 * <p>라벨을 하나도 담지 않은 프리셋은 「그 이벤트 유형을 오토라벨 대상에서 뺀다」는 <b>사람의 선언</b>
 * 이므로 보류하지 않고 오토라벨 묶음만 건너뛴 채 배치를 완료로 마감한다. 되살릴 것이 없어 재개 대상도
 * 아니다. 반면 라벨은 골랐는데 전부 검출 클래스 매핑이 없는 {@link #PRESET_UNMAPPED} 는 <b>사고</b>라
 * 종전대로 보류한다 — 둘을 같게 다루면 실수와 의도가 구분되지 않는다.
 */
public enum PresetResolutionStatus {

    /** 실효 — 검출 클래스에 매핑된 활성 라벨이 1건 이상이라 토글 맵을 만들었다. */
    RESOLVED,

    /**
     * 영상에 이벤트 유형 코드가 없거나, 있어도 이벤트 유형 마스터에 등록돼 있지 않다.
     * 프리셋을 특정할 수 없으므로 fail-closed 로 보류한다.
     */
    EVENT_TYPE_UNREGISTERED,

    /** 이벤트 유형은 등록됐으나 그 키에 걸린 프리셋이 없다. */
    PRESET_ABSENT,

    /**
     * 프리셋은 있으나 <b>라벨을 하나도 담지 않았다</b> — 오토라벨 제외 선언.
     * 보류가 아니라 완료다(위 클래스 Javadoc 참조).
     */
    PRESET_EMPTY,

    /** 프리셋에 담긴 코드가 전부 라벨 마스터에 연결돼 있지 않거나, 연결이 가리키는 활성 마스터가 없다. */
    PRESET_UNLINKED,

    /**
     * 연결·활성 라벨은 있으나 전부 AI 검출 클래스에 매핑돼 있지 않다(또는 형태가 도형이 아니다).
     * 운영자는 필터를 걸었다고 믿는데 실제로는 걸리지 않는 상태라 가장 위험하다.
     */
    PRESET_UNMAPPED
}
