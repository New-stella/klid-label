package kr.co.cudo.authoring.common.client;

import java.util.Optional;

/**
 * 「이 추론 호출을 <b>어느 장비로</b> 보낼까」 하나만 답하는 창구. [@design ADR-057]
 *
 * <h3>왜 인터페이스인가 — 방향을 뒤집기 위해서다</h3>
 * <p>장비를 고르는 판단은 원장·부하·상태를 아는 <b>AI 장비 도메인</b>이 갖는다. 그런데 그 판단을
 * 쓰는 자리는 연동 클라이언트다. 클라이언트가 그 도메인을 직접 부르면 공용 클라이언트 묶음이
 * 도메인 패키지에 매달려 <b>서로가 서로를 참조</b>하게 된다(그 도메인은 이미 이 묶음을 쓴다).
 * 그래서 <b>계약만 여기 두고 구현은 그 도메인에</b> 둔다.
 *
 * <h3>세 가지 답을 <b>갈라서</b> 돌려준다 — 합치면 장애가 감춰진다</h3>
 * <ul>
 *   <li><b>주소가 있다</b> — 그 장비로 고정해 보낸다.</li>
 *   <li><b>{@link Optional#empty()}</b> — <b>고를 수 없었지만 막지는 않는다</b>. 원장·부하
 *       <b>조회가 실패</b>했을 때다. 분산만 포기하고 배포 기본 주소로 나간다 — 저장소 순단이 정상
 *       추론을 전량 죽이지 않게 하는 축이다.</li>
 *   <li><b>예외</b> — <b>쓸 수 있는 후보가 0</b>이다. 사유를 가리지 않으며(형식 위반·목적지 불가·
 *       주소 정책 탈락·전부 이용불가·그 유형의 행 0건) <b>어떤 주소로도 폴백하지 않는다</b>.
 *       [@design AC-1093] [@design AC-1092]</li>
 * </ul>
 *
 * <p>⚠ <b>뒤의 둘을 합치지 말 것.</b> 「후보가 0이다」를 {@code empty} 로 낮추면 그 순간 호출이
 * 배포 기본 주소로 조용히 나가 <b>실제 장애가 감춰진다</b> — 두 장비가 함께 죽은 현장에서 실제로
 * 그렇게 됐다. 반대로 「조회하지 못했다」를 예외로 올리면 DB 순단이 추론 전체를 멈춘다.
 */
public interface AiSrvrTargetResolver {

    /**
     * 이 용도의 요청을 보낼 장비 <b>기준 주소</b>.
     *
     * @param workload 호출 용도. 장비 안에서 실행이 격리돼 있으므로 부하도 <b>그 용도의 것만</b> 본다
     * @return 고정할 기준 주소. 고르지 못했으나 막지 않을 때는 {@code empty}
     * @throws NonRetryableExternalException 쓸 수 있는 후보가 하나도 없을 때(폴백 없음)
     */
    Optional<String> resolveAddress(AiWorkload workload);
}
