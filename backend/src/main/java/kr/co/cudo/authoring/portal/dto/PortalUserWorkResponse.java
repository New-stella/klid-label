package kr.co.cudo.authoring.portal.dto;

import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * 「내 작업」 목록 1행 — 포털 채널 진입 화면이 그리는 목록의 원소. @design API-225, SCREEN-028, UC-024
 *
 * <h3>★ 이 목록은 데이터마트 카탈로그가 아니다</h3>
 * <p>데이터마트 영상 <b>전체</b>를 훑어보는 목록은 포털(Host)이 자기 화면에서 제공한다. 이 목록의
 * 모집단은 두 축이며 <b>축마다 싣는 기준이 다르다</b>.
 * <ul>
 *   <li>{@link PortalWorkAssetSource#PORTAL_UPLOAD} — 본인이 올린 자산이라 <b>저작 여부와 무관하게 전부</b></li>
 *   <li>{@link PortalWorkAssetSource#DATAMART} — 본인 저작물(저장 라벨 · 메타 오버레이 · 이벤트
 *       어노테이션 오버레이) 중 <b>어느 하나라도</b> 있는 영상만</li>
 * </ul>
 * <p>저작물이 하나도 없는 데이터마트 영상이 여기 실리면 그것이 곧 카탈로그를 대신 그리는 것이다.
 *
 * <h3>★★ 만료 예정일은 한 목록 안에서 <b>두 규칙</b>으로 계산된다</h3>
 * <p>데이터마트 행은 <b>그 사용자의 저작 최초 저장 시각</b>(세 저작물을 통틀어 가장 이른 것)을
 * 기산점으로, 업로드 행은 <b>업로드 채널 자체의 보존 규칙</b>(상태별로 기산점이 갈린다)으로 계산한다.
 * 두 축은 기산점이 다르므로 <b>한 규칙으로 통일하지 말 것</b>(DFEAT-055). 판정은
 * {@code PortalRetentionPolicy} 한 곳이 소유하며 이 응답은 그 결과를 나를 뿐이다.
 *
 * <p>⚠ {@link #expiresOn} 을 {@link #lastSavedAt} 에서 다시 계산하지 말 것 — <b>축이 다르다</b>.
 * 마지막 저장에서 계산하면 저장을 반복할 때마다 만료가 뒤로 밀려 자동 삭제가 영영 실행되지 않는다
 * (2026-09-04 에 고친 결함이다).
 *
 * <p>⚠ <b>저장하지 않는 파생값</b>이라 조회 시점의 보존기간 설정으로 매번 재계산된다 —
 * <b>클라이언트는 캐시하지 말 것</b>. 보존기간 설정이 없으면 {@code null} 이다.
 *
 * <h3>★ 「어디로 들어가는가」와 「저장 이력이 있는가」는 다른 필드가 답한다</h3>
 * <p>{@link #entrySrcSn} 은 <b>진입 대상</b>이고 {@link #lastSavedAt} 은 <b>저장 이력</b>이다. 전자는
 * 저장 이력이 없어도 첫 프레임으로 채워지므로, 그 값의 유무로 「작업한 적이 있는가」를 가르면 아직
 * 아무것도 저장하지 않은 업로드 행이 <b>작업한 행으로 읽힌다</b>. 두 축을 섞지 말 것.
 *
 * @param rawSn          대상 영상 식별자. 업로드 축에서는 자산 식별자와 같은 값이다
 * @param assetSource    자산 출처 — 화면이 이어서 작업·내려받기 동선을 가르는 축
 * @param videoName      목록 표시용 이름. 업로드 축은 사용자가 올린 원본 파일명이 1순위다
 * @param labelCount     본인이 저장한 라벨 건수. <b>0 인 행이 정상으로 존재한다</b> — 라벨 없이 메타나
 *                       이벤트 어노테이션만 고친 행, 아직 아무 저작물도 없는 업로드 행.
 *                       ★ <b>이 값으로 내려받기 가부나 저작 이력을 판정하지 말 것</b> — 라벨 축만
 *                       세므로 메타만 고친 행이 「작업 없음」으로 읽힌다. 그 판정은 {@link #lastSavedAt} 몫이다
 * @param lastSavedAt    <b>사람이 직접 남긴 마지막 저작 편집</b>의 시각 — 저장 라벨 · 포털 메타 편집
 *                       (촬영환경·프레임 설명·개인정보 판정·시계열 메타) · 이벤트 어노테이션 셋을
 *                       통틀어 가장 늦은 것. 데이터마트축은 오버레이에, 업로드축은 자기 자산 원장에
 *                       쌓이지만 <b>저작물이라는 성질은 같다</b>. 아직 아무 저작 편집도 없으면 {@code null}
 *                       (대체 시각을 채워 넣지 않는다 — 정렬만 등록일로 대신한다).
 *                       ★ 자동으로 읽어 넣은 기술메타와 업로드 처리 상태·실패 사유는 같은 원장에 앉아도
 *                       <b>세지 않는다</b>. 세면 업로드 직후 자산이 「저장한 행」으로 뒤집힌다.
 *                       ★★ <b>보존기간 기산 입력과 같은 값이 아니다</b> — 기산은 다른 기능이 소유하며
 *                       업로드축은 라벨 마지막 저장일이 기준점이다. 하나로 합치지 말 것
 * @param entrySrcSn     <b>이어서 작업하러 들어갈 수 있는 대상 프레임</b> — 갈래는 셋이고 비는 사유는 둘이다.
 *                       ①마지막으로 저장한 라벨의 프레임이 있으면 그것 ②없으면 <b>첫 프레임</b>
 *                       ③<b>프레임이 0건이거나 진입이 허용되지 않으면</b> {@code null}.
 *                       ⚠ 비는 사유 둘을 이 값이 구분해 주지 않는다 — 인지·수용한 대가이며 화면은
 *                       공통 문구를 쓴다. ⚠ 이 좁힘은 화면이 <b>미리</b> 막게 하려는 것이고 서버 진입
 *                       가드를 대신하지 않는다(가드를 걷어내면 주소를 직접 쳐서 들어간다).
 *                       비어 있어도 <b>그 행을 목록에서 빼지 않으며</b> 내려받기·만료 표시는 그대로다.
 *                       ★ <b>「저장 이력이 있는가」의 판정에 쓰지 말 것</b> — 저작물이 0건인 업로드
 *                       행에도 첫 프레임이 실리므로 정반대 판정이 된다. 그 판정은
 *                       {@link #lastSavedAt} 이 소유한다({@code null} 이면 아직 아무 저작물도 없다)
 * @param expiresOn      보존기간 만료 <b>예정일</b>. 사양이 날짜 단위로 고지하도록 정했으므로 시각의
 *                       날짜 부분만 싣는다(API-225 — {@code format: date}). 만료 판정이 서지 않는
 *                       상태이거나 보존기간 설정이 없으면 {@code null}
 */
public record PortalUserWorkResponse(
        Long rawSn,
        PortalWorkAssetSource assetSource,
        String videoName,
        int labelCount,
        LocalDateTime lastSavedAt,
        Long entrySrcSn,
        LocalDate expiresOn
) {

    /**
     * 만료 예정 <b>시각</b>을 사양이 정한 <b>날짜</b> 고지값으로 옮긴다.
     *
     * <p>판정 자체는 하지 않는다 — 여기서 {@code null} 이 되는 것은 위에서 이미 {@code null} 로
     * 내려온 경우뿐이다(값을 지어내지 않는다).
     */
    public static LocalDate toExpiresOn(LocalDateTime expiresAt) {
        return expiresAt == null ? null : expiresAt.toLocalDate();
    }
}
