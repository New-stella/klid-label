package kr.co.cudo.authoring.batch.status;

import kr.co.cudo.authoring.batch.orchestrator.BatchStageBundle;

/**
 * "이 영상에 그 <b>작업 묶음의 산출물</b>이 있는가" 판정 — 묶음마다 한 벌. [@design SCREEN-009] [@design AC-051]
 *
 * <h3>왜 「재수행 성공 표식」이 아니라 「산출물」인가 (설계 결정 — 되돌리지 말 것)</h3>
 * <p>대안이던 성공 표식 신설은 채택하지 않았다. ①완주 훅({@code markRawDataCompleted})이 어느 묶음을
 * 돌렸는지 <b>모른다</b> ②<b>시계열은 오케스트레이터 완주가 곧 성공이 아니다</b> — 위탁이 논블로킹이라
 * 제출 직후 반환하고 결과는 웹훅으로 나중에 오므로, 그 지점에 성공을 남기면 <b>벤더가 답하기 전에
 * 성공을 주장</b>하게 된다 ③{@link ManualStageSkip#MARKER_ERR_CDS} 확장은 쿼리에서 "마지막 표식" 후보
 * 자체를 좁히는 조건이라 스킵 게이트·재수행 수락 판정 등이 동시에 흔들린다(all-or-nothing).
 *
 * <p>산출물 축은 그 셋을 전부 비켜간다 — <b>서술이 적재되면 그게 곧 성공</b>이기 때문이다.
 *
 * <h3>⚠ 「최초 배치로 만든 산출물」과 「재수행으로 만든 산출물」을 구분하지 않는다</h3>
 * <p>인지하고 수용한 성질이다. 화면이 답해야 하는 질문은 <i>"이 묶음에 지금 조치가 필요한가"</i> 이지
 * <i>"과거에 재수행을 했는가"</i> 가 아니다. 과거 이력은 {@code LS_BATCH_PROC_LOG} 감사 행에 그대로
 * 남으며 이 판정은 그 행을 <b>읽지도 지우지도 않는다</b>.
 *
 * <h3>구현 규약</h3>
 * <p>구현체는 스프링 빈이어야 하고 {@link BundleArtifactPresenceRegistry} 가 자동 수집한다 —
 * 호출부가 {@code if (bundle == VLM)} 로 분기하면 묶음이 늘 때 조용히 빠지므로 매핑은 그 한 곳뿐이다.
 * <b>읽기 전용</b>이다.
 *
 * <p><b>판정 실패는 삼키지 않고 올린다</b> — 조회가 실패하면 그대로 예외가 전파돼 영상 상세가
 * 오류로 끝난다. 의도한 것이다: 삼켜서 {@code false}(=산출물 없음)를 주면 조용히 과잉 노출이 되고,
 * {@code true} 를 주면 <b>조치가 필요한 영상이 화면에서 사라진다</b>. 감추는 쪽으로 실패하는 것보다
 * <b>시끄럽게 실패</b>하는 편이 안전하다(fail-open 금지).
 */
public interface BundleArtifactPresence {

    /** 이 판정기가 담당하는 묶음. 한 묶음에 두 구현체가 있으면 레지스트리가 기동을 실패시킨다. */
    BatchStageBundle bundle();

    /**
     * 그 영상에 이 묶음의 산출물이 <b>하나라도</b> 있는가.
     *
     * @param rawSn 영상 PK. {@code null} 이면 {@code false}(판정 불가는 "없음" 쪽으로 — 아래 fail-safe)
     */
    boolean exists(Long rawSn);

    /**
     * <b>파이프라인이 종결하면 이 묶음의 작업도 끝난 것인가</b> — 종결 축 적용 여부를 묶음이 스스로
     * 선언한다. 기본값은 {@code false}(적용하지 않음). [@design AC-051] [@design SCREEN-009]
     *
     * <h3>왜 묶음이 선언하는가</h3>
     * <p>호출부가 {@code if (bundle == VLM)} 로 분기하면 묶음이 늘 때 그 분기가 조용히 빠진다.
     * 산출물 판정과 같은 원칙으로, <b>묶음이 선언하고 판정기가 읽는다</b>.
     *
     * <h3>{@code true} 인 묶음에만 종결 축이 붙는 이유</h3>
     * <p>종결 축을 정당화하는 근거는 <b>「검출 0건도 정상 결과」</b> 인데, 그것은 파이프라인 안에서
     * 작업이 <b>동기적으로 완결</b>되는 묶음에만 성립한다. 그런 묶음은 산출물이 0건이어도 파이프라인이
     * 완주했다면 실제로 조치가 끝난 것이다.
     *
     * <p>반대로 <b>외부에 논블로킹으로 위탁</b>하는 묶음은 제출 직후 반환하고 결과가 웹훅으로 나중에
     * 오므로, 파이프라인 완주는 <b>「보냈다」일 뿐 「끝났다」가 아니다.</b> 거기에 종결 축을 붙이면
     * <b>벤더가 답하기 전에 조치 완료를 주장</b>하게 된다 — 「완주 시점에 성공 표식을 남기는 안」이
     * 기각된 근거가 정확히 그것이며, 종결 축을 무차별 적용하면 그 기각된 동작이 되살아난다.
     * 그런 묶음은 <b>산출물 축 단독</b>으로 판정한다(외부 결과가 적재되면 그게 곧 성공이다).
     *
     * <p>애초에 논블로킹 위탁 묶음에는 「검출 0건」에 해당하는 상태가 없으므로, 종결 축은 얻는 것
     * 없이 <b>거짓 음성</b>(조치가 필요한데 사라짐)만 만든다.
     */
    default boolean completionIsSynchronous() {
        return false;
    }
}
