package kr.co.cudo.authoring.webhook.service;

/**
 * 외부 시계열 분석 결과를 이벤트 어노테이션의 초안 칸으로 넘기는 협력자 포트. [design: CDIAG-014]
 *
 * <p>콜백 수신부는 <b>어느 창구의 결과인지 되짚어 넘기는 일</b>까지만 하고, 이벤트 어노테이션의
 * 구조·동결·재검수 시맨틱은 그 도메인이 소유한다. 수신부에 그 규칙을 복제하면 한쪽만 갱신돼
 * 조용히 어긋난다.
 *
 * <p><b>이름이 축 중립인 이유</b> — 창구가 둘(묘사·추가 질문)이다. 추가 질문 전용을 함의하는 이름은
 * 묘사 축까지 담게 되는 순간 이름과 책임이 어긋난다. 반면 <b>메서드 이름</b>의 「추가 질문」 표기는
 * 어느 창구의 결과인지를 가리키는 것이라 그대로 둔다.
 *
 * <p><b>자동 채움의 경계</b>(구현이 반드시 지켜야 하는 계약):
 * <ul>
 *   <li>사람이 이미 고친 값과 검수 승인으로 동결된 값은 <b>덮지 않는다</b>.</li>
 *   <li>자동 채움 자체는 재검수를 발화시키지 않는다 — 사람이 고치는 것과 구분된다.</li>
 *   <li>같은 결과를 여러 번 받아도 결과가 같아야 한다(규격상 콜백은 중복 수신될 수 있다).</li>
 *   <li>두 창구가 <b>같은 캡션 후보를 공유</b>하고 도착 순서가 보장되지 않으므로, 후보를 통째로
 *       교체하지 않고 자기 칸만 채워 먼저 도착한 축의 값을 지우지 않는다.</li>
 * </ul>
 */
public interface TimeseriesResultApplier {

    /**
     * 묘사(describe) 전문을 초안으로 반영한다.
     *
     * <p>전문 가운데 <b>「상황」 항목만</b> 뽑아 캡션 후보의 사고 단계 1단계 칸에 넣는다. 그 파싱은
     * 이 포트를 구현하는 어노테이션 도메인이 수행하며 콜백 수신부에 두지 않는다. 항목을 찾지 못하면
     * <b>지어내지 않고 건너뛴다</b>.
     *
     * <p>서술 전문 자체({@code video.vd_description})의 조달 경로는 이 계약과 무관하다 — 그쪽은
     * 종전대로 시계열 메타에서 온다.
     *
     * @param rawSn       대상 영상.
     * @param description 묘사 결과 서술 전문.
     * @return 실제로 초안이 채워졌으면 true. 채우지 못해도 시계열 서술 전문의 적재는 롤백되지 않는다.
     */
    boolean applyDescription(Long rawSn, String description);

    /**
     * 추가 질문(describe-sub) 결과를 초안으로 반영한다.
     *
     * <p>서술은 같은 캡션 후보의 <b>캡션 본문</b> 칸에 넣는다. <b>답변 칸은 자동으로 채우지 않는다</b>
     * — 사람이 확정할 공란이다.
     *
     * <p><b>질문 문장 칸은 이 계약이 채우지 않는다</b> — 그 값의 조달원은 저작도구가 보관하는 검증
     * 이벤트 유형별 질문 문구 목록이며, 어노테이션 도메인이 마킹에서 고른 질문(없으면 그 유형의
     * 첫 번째)을 읽어 채운다.
     *
     * @param rawSn       대상 영상.
     * @param description 분석 결과 서술(자연어 평문 — 형식이 고정돼 있지 않으므로 파싱에 의존하지 않는다).
     * @return 실제로 초안이 채워졌으면 true, 이미 사람이 손댔거나 동결돼 건너뛰었으면 false.
     */
    boolean applySubDescription(Long rawSn, String description);
}
