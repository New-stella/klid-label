package kr.co.cudo.authoring.portal.service;

/**
 * 데이터셋 영상 원장 등록이 실패한 사유 — <b>값으로 보존</b>한다(메시지 파싱 금지).
 *
 * <p>⚠ 어느 값도 경로·파일명·문서 원문을 담지 않는다(CWE-209). 운영자가 다음 조치를 고를 수 있을 만큼만
 * 가른다 — 앞의 값들은 <b>배포본 구성이 확인한 실물과 다르다</b>는 뜻이고(개발망 실물 확인 2026-09-16),
 * 뒤의 셋은 구성은 맞았는데 적재가 끝나지 않은 것이다.
 *
 * <p>★ <b>값을 지우지 않는다</b> — 이미 쓰인 표식 파일({@code registration.json})이 그 값을 담고 있어
 * 지우면 옛 표식을 읽지 못한다. 지금은 나지 않는 값도 <b>존치</b>하고 주석으로만 그 사실을 남긴다.
 *
 * @design ADR-068
 */
public enum PortalDatasetRegistrationFailureReason {

    /** 해제본 자리가 없다 — 소재 해제본이 공개되지 않았거나 지워졌다. */
    CONTENT_MISSING,

    /** 해제본 안에 심링크가 있다 — 따라가지 않고 멈춘다(CWE-59). */
    SYMLINK_REJECTED,

    /** 해제본 어디에도 이미지·문서 <b>짝이 한 건도 없다</b> — 등록할 수 있는 영상이 없다. */
    NO_VIDEO,

    /**
     * 짝은 있는데 문서에 <b>영상 파일명이 없다</b> — 영상 식별자를 정할 수 없다.
     *
     * <p>{@link #NO_VIDEO}(짝 자체가 없다)와 가르는 이유는 조치가 다르기 때문이다 — 이쪽은 배포본이
     * 왔는데 문서 스키마가 어긋난 것이라 문서를 만든 쪽에 물어야 한다.
     */
    VIDEO_FILENAME_MISSING,

    /**
     * [더 이상 나지 않는다] 같은 영상 키가 서로 다른 자리에 있다.
     *
     * <p>영상 키가 <b>폴더 이름</b>이던 구 구성의 값이다. 지금은 문서의 영상 파일명이 키라 같은 값이
     * 여러 자리에 있는 것이 <b>정상</b>(한 영상으로 묶는다)이다. 옛 표식 판독을 위해 남긴다.
     */
    AMBIGUOUS_VIDEO_KEY,

    /**
     * 영상 파일명으로 클립 식별자를 만들 수 없다 — 허용 길이를 넘거나, 경로 구분자·상위 참조·제어
     * 문자가 섞여 있다.
     */
    INVALID_VIDEO_KEY,

    /** 프레임 이미지와 같은 이름의 라벨 문서 짝이 맞지 않는다(한쪽만 있거나 같은 번호가 둘이다). */
    PAIR_MISMATCH,

    /** 라벨 문서를 읽을 수 없다(JSON 이 아니거나 우리가 쓰는 칸의 형식이 어긋난다). */
    DOCUMENT_UNREADABLE,

    /** 프레임 이미지가 JPEG 가 아니다. */
    IMAGE_NOT_JPEG,

    /** 문서 값이 원장에 앉을 수 없다(좌표 형식·길이 상한 위반 등) — 잘라 넣거나 고쳐 넣지 않는다. */
    INVALID_VALUE,

    /** 등록 토글이 꺼져 있다 — 운영자가 등록을 멈췄다. */
    DISABLED,

    /** 파일 복사·읽기 중 입출력이 실패했다. */
    IO_ERROR,

    /** 원장 적재가 실패했다. */
    PERSIST_FAILED
}
