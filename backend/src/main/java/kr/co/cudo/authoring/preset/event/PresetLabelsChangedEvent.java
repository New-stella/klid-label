package kr.co.cudo.authoring.preset.event;

/**
 * 오토라벨 프리셋의 <b>라벨 구성이 바뀌었음</b>을 알리는 도메인 이벤트 — 보류된 오토라벨의 재개 트리거.
 * [@design ADR-054] [@design AC-115]
 *
 * <h3>왜 필요한가 (보류의 영구 고착 방지)</h3>
 * <p>탐지 단계는 그 영상의 이벤트 유형에 실효 프리셋이 없으면 오토라벨 묶음을 <b>실패가 아니라 보류</b>로
 * 끝낸다(SKIPPED + 사유를 배치 처리 이력에 적재). 보류는 실패 행을 남기지 않으므로 배치 재시도 큐도
 * 실패 회수기도 이를 집지 않는다. 즉 운영자가 프리셋을 등록해도 <b>스스로 재개되지 않고</b> 그 영상은
 * 오토라벨 없이 남는다 — 이 이벤트가 유일한 복구 경로다("차단엔 되돌리는 길, 보류엔 끝").
 *
 * <h3>발행 계약 (프리셋 도메인이 지킨다)</h3>
 * <ul>
 *   <li><b>등록·수정</b> 시 발행한다. 프리셋을 복제해 새 이벤트 유형에 거는 경로도 등록에 해당한다.</li>
 *   <li><b>삭제 시 발행하지 않는다</b> — 프리셋이 사라지면 오히려 보류 조건이 성립한다. 발행하면
 *       재개 러너가 돌았다가 스스로 다시 보류하는 헛일이 된다.</li>
 *   <li>소비자는 반드시 {@code AFTER_COMMIT} 리스너여야 한다. 커밋 전에 실행하면 재개 러너가
 *       <b>아직 보이지 않는 프리셋</b>을 조회해 실효하지 않다고 판정하고 스스로 다시 보류한다.</li>
 *   <li>이벤트 발행 실패가 프리셋 저장을 롤백시켜서는 안 된다.</li>
 * </ul>
 *
 * <p>재개 대상 <b>영상</b> 은 싣지 않는다 — 어느 영상이 보류됐는지는 프리셋 도메인이 알 수 없고,
 * 판정은 배치 처리 이력(보류 기록)을 읽는 소비자가 담당한다.
 *
 * @param evntTypeCd 프리셋이 걸린 이벤트 유형 코드({@code LS_LABEL_PRESET.EVNT_TYPE_CD}).
 *                   이 값은 <b>그룹 대표코드(필터 키)</b> 축이며, 소비자가 그룹을 펼쳐 영상의 상세
 *                   EV-코드와 대조한다. {@code null}/공백이면 소비자가 대상 유형을 좁히지 않고
 *                   보류 기록 전체를 후보로 본다(재개 판정 자체는 후보마다 다시 하므로 안전하다)
 */
public record PresetLabelsChangedEvent(String evntTypeCd) {
}
