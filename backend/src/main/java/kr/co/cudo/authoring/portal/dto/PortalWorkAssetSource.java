package kr.co.cudo.authoring.portal.dto;

/**
 * 「내 작업」 목록 한 행의 <b>자산 출처</b> — 화면이 행마다 동선을 가르는 축. @design API-225
 *
 * <p>이 목록은 성질이 다른 두 축을 <b>한 목록에 섞어</b> 내린다(업로드 자산은 저작 여부와 무관하게
 * 전부, 데이터마트 영상은 본인 저작물이 있는 것만). 그런데 <b>이어서 작업하러 들어가는 자리와
 * 내려받을 수 있는 것이 출처마다 다르므로</b>, 응답이 출처를 싣지 않으면 화면이 행마다 동선을
 * 가를 수 없다(API-225 — 필드 이름을 사양이 확정하지 않아 구현이 정한 이름이 {@code assetSource} 다).
 *
 * <h3>★ 값 이름은 {@code PortalWorkTargetResolver.Origin} 과 <b>한 글자도 다르지 않다</b></h3>
 * <p>자산 출처를 가르는 판정은 이미 그 클래스가 단독으로 소유한다. 여기서 이름이 다른 값을 쓰면
 * 같은 축에 <b>두 개의 어휘</b>가 생겨, 화면이 「저장은 어디로 갔는가」와 「이 행은 어느 축인가」를
 * 서로 다른 낱말로 받게 된다. 값 집합이 어긋나지 않게 하는 것은
 * {@code PortalUserWorkSourceVocabularyTest} 한 건이며, 어느 한쪽에 값을 더하면 그 시험이 죽는다.
 *
 * <p>⚠ 계층을 이유로 이 열거를 서비스 열거로 대체하지 말 것 — 응답 계약이 서비스 내부 판정 열거에
 * 묶이면 판정 축을 넓힐 때 외부 계약이 함께 움직인다.
 */
public enum PortalWorkAssetSource {

    /** 관제가 구축한 데이터마트에서 불러온 영상. 본인 저작물(라벨·메타·이벤트 어노테이션)이 있는 것만 실린다. */
    DATAMART,

    /** 포털 사용자가 직접 올린 본인 자산. <b>저작물 보유 여부와 무관하게</b> 전부 실린다. */
    PORTAL_UPLOAD
}
